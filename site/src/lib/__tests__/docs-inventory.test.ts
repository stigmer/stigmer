import { afterEach, describe, expect, it } from "vitest";
import * as fs from "node:fs/promises";
import * as os from "node:os";
import * as path from "node:path";
import {
  buildInventory,
  extractEmbeds,
  isGeneratedContent,
  isValidFate,
  parseClassification,
  renderReport,
} from "../docs-inventory";
import { cleanContent } from "../llms-pages";

/** Materializes a docs tree from a { relativePath: contents } map. */
async function makeDocsDir(files: Record<string, string>): Promise<string> {
  const dir = await fs.mkdtemp(path.join(os.tmpdir(), "docs-inventory-"));
  for (const [rel, contents] of Object.entries(files)) {
    const abs = path.join(dir, rel);
    await fs.mkdir(path.dirname(abs), { recursive: true });
    await fs.writeFile(abs, contents, "utf-8");
  }
  return dir;
}

function mdx(title: string, body = ""): string {
  return `---\ntitle: ${title}\ndescription: About ${title}.\n---\n\n# ${title}\n${body}`;
}

/** A generated page carrying a real marker variant. */
function generatedMdx(title: string): string {
  return `---\ntitle: ${title}\n---\n\n{/* Auto-generated by stigmer-codegen. DO NOT EDIT. */}\n\n# ${title}\n`;
}

function meta(data: object): string {
  return JSON.stringify(data);
}

/** A minimal valid entry, overridable per test. */
function entry(overrides: Record<string, unknown> = {}): Record<string, unknown> {
  return {
    fate: "keep",
    diataxis: "explanation",
    teaches: "Something concrete.",
    medium: "none",
    ...overrides,
  };
}

function yamlOf(doc: object): string {
  return JSON.stringify(doc); // valid YAML — js-yaml parses JSON
}

const tempDirs: string[] = [];

async function setup(files: Record<string, string>): Promise<string> {
  const dir = await makeDocsDir(files);
  tempDirs.push(dir);
  return dir;
}

afterEach(async () => {
  await Promise.all(
    tempDirs.splice(0).map((dir) => fs.rm(dir, { recursive: true, force: true })),
  );
});

describe("parseClassification", () => {
  it("accepts a valid document", () => {
    const { classification, errors } = parseClassification(
      yamlOf({
        pages: {
          "concepts/agents": entry({
            medium: "diagram",
            why: "Structure, not a screen.",
          }),
        },
        cohorts: {
          "sdk/react/": {
            generator: "gen-react-sdk-docs",
            diataxis: "reference",
            medium: "none",
          },
        },
      }),
    );
    expect(errors).toEqual([]);
    expect(classification?.pages["concepts/agents"].medium).toBe("diagram");
    expect(classification?.cohorts["sdk/react/"].generator).toBe("gen-react-sdk-docs");
  });

  it("collects every schema problem instead of stopping at the first", () => {
    const { classification, errors } = parseClassification(
      yamlOf({
        pages: {
          bad: {
            fate: "resurrect",
            diataxis: "sermon",
            teaches: "",
            medium: "hologram",
          },
          "needs-why": entry({ medium: "animated-tour" }),
          "bad-embed": entry({ embeds: { "some-tour": "maybe" } }),
        },
        cohorts: {
          "no-slash": { generator: "", diataxis: "reference", medium: "none" },
        },
      }),
    );
    expect(classification).toBeNull();
    const text = errors.join("\n");
    expect(text).toContain('pages["bad"]: fate');
    expect(text).toContain('pages["bad"]: diataxis');
    expect(text).toContain('pages["bad"]: teaches');
    expect(text).toContain('pages["bad"]: medium');
    expect(text).toContain(
      'pages["needs-why"]: a non-"none" medium and a non-"keep" fate each require',
    );
    expect(text).toContain('pages["bad-embed"]: embeds["some-tour"]');
    expect(text).toContain('cohorts["no-slash"]: cohort prefixes must end with "/"');
    expect(text).toContain('cohorts["no-slash"]: generator');
    // "bad" has an invalid fate AND an invalid medium — each already has
    // its own error, so the why requirement must not pile on a third.
    expect(errors.filter((message) => message.includes('"why"'))).toHaveLength(1);
  });

  it('requires a "why" for any non-"keep" fate, independent of medium', () => {
    // The oss#315 hole: keying why on medium alone let a destructive plan
    // (fate: split, medium: none) rest with no reason on the record.
    const { errors } = parseClassification(
      yamlOf({
        pages: {
          "silent-split": entry({ fate: "split" }),
          "silent-move": entry({ fate: "move:concepts/elsewhere" }),
          "explained-merge": entry({
            fate: "merge:concepts/agents",
            why: "Duplicates the agents page, section for section.",
          }),
          "plain-keep": entry(),
        },
        cohorts: {},
      }),
    );
    const text = errors.join("\n");
    expect(text).toContain('pages["silent-split"]');
    expect(text).toContain('pages["silent-move"]');
    expect(text).not.toContain('pages["explained-merge"]');
    expect(text).not.toContain('pages["plain-keep"]');
  });

  it("rejects malformed YAML and non-mapping documents with one clear error", () => {
    expect(parseClassification(":\n  - {").errors[0]).toMatch(/not parseable/);
    expect(parseClassification("- just\n- a list\n").errors[0]).toMatch(
      /top level must be a mapping/,
    );
  });

  it("validates targeted fates", () => {
    expect(isValidFate("keep")).toBe(true);
    expect(isValidFate("move:concepts/agents")).toBe(true);
    expect(isValidFate("merge:guides/workflows")).toBe(true);
    expect(isValidFate("move:")).toBe(false);
    expect(isValidFate("rename:x")).toBe(false);
  });
});

describe("isGeneratedContent", () => {
  it("recognizes every marker variant the generators write", () => {
    const markers = [
      "{/* Auto-generated by @stigmer/react docs generator. DO NOT EDIT. */}",
      "{/* Auto-generated by stigmer-codegen. DO NOT EDIT. */}",
      "{/* Autogenerated by stigmer-codegen. DO NOT EDIT. */}",
      "{/* Auto-generated by gen-cli-docs. Do not edit manually. */}",
      "{/* Auto-generated by the theme token docs generator (make gen-theme-docs). DO NOT EDIT. */}",
      "{/* Auto-generated by generate-ink-sdk-docs. DO NOT EDIT. */}",
    ];
    for (const marker of markers) {
      expect(isGeneratedContent(`---\ntitle: X\n---\n\n${marker}\n`)).toBe(true);
    }
  });

  it("does not flag hand-authored pages", () => {
    expect(isGeneratedContent(mdx("Agents", "Auto-generated content is nice.")))
      .toBe(false);
  });
});

describe("extractEmbeds", () => {
  it("extracts ScenarEmbed ids including multi-line tags, and legacy Demo components", () => {
    const content = [
      '<ScenarEmbed id="quickstart-tour" />',
      "<ScenarEmbed",
      '  id="api-key-setup"',
      '  title="Set up an API key"',
      "/>",
      "<DemoToolCallsPlayback />",
    ].join("\n");
    expect(extractEmbeds(content)).toEqual([
      "quickstart-tour",
      "api-key-setup",
      "DemoToolCallsPlayback",
    ]);
  });

  it("dedupes repeated embeds", () => {
    const content = '<ScenarEmbed id="a-tour" />\n<ScenarEmbed id="a-tour" />';
    expect(extractEmbeds(content)).toEqual(["a-tour"]);
  });

  it("ignores commented-out embeds when composed with cleanContent", () => {
    const body = '{/* <ScenarEmbed id="retired-tour" /> */}\n<DemoByoaSetup />';
    expect(extractEmbeds(cleanContent(body))).toEqual(["DemoByoaSetup"]);
  });
});

describe("buildInventory", () => {
  it("passes a fully classified tree with zero violations", async () => {
    const dir = await setup({
      "index.mdx": mdx("Home", '<ScenarEmbed id="create-agent-tour" />'),
      "meta.json": meta({ pages: ["---Agents---", "concepts/agents"] }),
      "concepts/agents.mdx": mdx("Agents"),
      "sdk/react/button.mdx": generatedMdx("button"),
    });
    const { violations } = await buildInventory(
      dir,
      yamlOf({
        pages: {
          index: entry({
            diataxis: "landing",
            medium: "animated-tour",
            why: "The homepage sells the product moving.",
            embeds: { "create-agent-tour": "keep" },
          }),
          "concepts/agents": entry(),
        },
        cohorts: {
          "sdk/react/": {
            generator: "gen-react-sdk-docs",
            diataxis: "reference",
            medium: "none",
          },
        },
      }),
    );
    expect(violations).toEqual([]);
  });

  it("flags unclassified hand-authored pages — including nav orphans", async () => {
    const dir = await setup({
      "index.mdx": mdx("Home"),
      // orphan.mdx is on disk but absent from the nav: still in scope,
      // because the disk walk (not the nav walk) is the universe.
      "meta.json": meta({ pages: [] }),
      "concepts/orphan.mdx": mdx("Orphan"),
    });
    const { violations } = await buildInventory(
      dir,
      yamlOf({ pages: { index: entry({ diataxis: "landing" }) }, cohorts: {} }),
    );
    expect(violations).toEqual([
      expect.objectContaining({ kind: "unclassified-page", key: "concepts/orphan" }),
    ]);
  });

  it("flags generated pages with no covering cohort, and per-page entries on generated pages", async () => {
    const dir = await setup({
      "index.mdx": mdx("Home"),
      "meta.json": meta({ pages: [] }),
      "cli/commands/run.mdx": generatedMdx("run"),
      "sdk/resources/agent.mdx": generatedMdx("Agent"),
    });
    const { violations } = await buildInventory(
      dir,
      yamlOf({
        pages: {
          index: entry({ diataxis: "landing" }),
          // Wrong on purpose: classification of generated pages belongs
          // to the generator's cohort rule.
          "sdk/resources/agent": entry({ diataxis: "reference" }),
        },
        cohorts: {
          "sdk/resources/": {
            generator: "gen-proto-sdk-docs",
            diataxis: "reference",
            medium: "none",
          },
        },
      }),
    );
    expect(violations).toContainEqual(
      expect.objectContaining({
        kind: "uncovered-generated-page",
        key: "cli/commands/run",
      }),
    );
    expect(violations).toContainEqual(
      expect.objectContaining({
        kind: "generated-page-classified",
        key: "sdk/resources/agent",
      }),
    );
  });

  it("flags entries pointing at pages that do not exist", async () => {
    const dir = await setup({
      "index.mdx": mdx("Home"),
      "meta.json": meta({ pages: [] }),
    });
    const { violations } = await buildInventory(
      dir,
      yamlOf({
        pages: {
          index: entry({ diataxis: "landing" }),
          "concepts/deleted-page": entry(),
        },
        cohorts: {},
      }),
    );
    expect(violations).toEqual([
      expect.objectContaining({ kind: "unknown-page", key: "concepts/deleted-page" }),
    ]);
  });

  it("flags embed drift in both directions", async () => {
    const dir = await setup({
      "index.mdx": mdx("Home"),
      "meta.json": meta({ pages: ["concepts/tools"] }),
      "concepts/tools.mdx": mdx("Tools", "<DemoToolCallsPlayback />"),
    });
    const { violations } = await buildInventory(
      dir,
      yamlOf({
        pages: {
          index: entry({ diataxis: "landing" }),
          "concepts/tools": entry({
            medium: "animated-tour",
            why: "Sequenced tool calls must be seen firing.",
            embeds: { "some-other-tour": "replace" },
          }),
        },
        cohorts: {},
      }),
    );
    const drift = violations.filter((violation) => violation.kind === "embed-drift");
    expect(drift).toHaveLength(2);
    expect(drift.map((violation) => violation.message).join("\n")).toContain(
      'renders embed "DemoToolCallsPlayback"',
    );
    expect(drift.map((violation) => violation.message).join("\n")).toContain(
      'declares embed "some-other-tour"',
    );
  });

  it("covers a generated folder index page with its own cohort prefix", async () => {
    const dir = await setup({
      "index.mdx": mdx("Home"),
      "meta.json": meta({ pages: [] }),
      // cli/commands/index.mdx strips to key "cli/commands" — exactly the
      // cohort prefix minus its slash. The rule must still cover it.
      "cli/commands/index.mdx": generatedMdx("Commands"),
      "cli/commands/run.mdx": generatedMdx("run"),
    });
    const { violations } = await buildInventory(
      dir,
      yamlOf({
        pages: { index: entry({ diataxis: "landing" }) },
        cohorts: {
          "cli/commands/": {
            generator: "gen-cli-docs",
            diataxis: "reference",
            medium: "none",
          },
        },
      }),
    );
    expect(violations).toEqual([]);
  });

  it("keys the docs root as index, strips /index from folder pages, and skips _archive", async () => {
    const dir = await setup({
      "index.mdx": mdx("Home"),
      "meta.json": meta({ pages: [] }),
      "guides/workflows/index.mdx": mdx("Workflows"),
      "_archive/old.mdx": mdx("Old"),
    });
    const { pages, violations } = await buildInventory(
      dir,
      yamlOf({
        pages: {
          index: entry({ diataxis: "landing" }),
          "guides/workflows": entry({ diataxis: "landing" }),
        },
        cohorts: {},
      }),
    );
    expect(pages.map((page) => page.key).sort()).toEqual(["guides/workflows", "index"]);
    expect(violations).toEqual([]);
  });

  it("reports schema problems as violations instead of throwing", async () => {
    const dir = await setup({
      "index.mdx": mdx("Home"),
      "meta.json": meta({ pages: [] }),
    });
    const { violations } = await buildInventory(dir, "- not\n- a mapping\n");
    expect(violations).toContainEqual(
      expect.objectContaining({ kind: "schema", key: "classification.yaml" }),
    );
    // With no parseable classification, the page is also unclassified.
    expect(violations).toContainEqual(
      expect.objectContaining({ kind: "unclassified-page", key: "index" }),
    );
  });
});

describe("renderReport", () => {
  it("renders counts, violations, cohorts, and marks unclassified pages", async () => {
    const dir = await setup({
      "index.mdx": mdx("Home"),
      "meta.json": meta({ pages: ["concepts/agents", "concepts/skills"] }),
      "concepts/agents.mdx": mdx("Agents"),
      "concepts/skills.mdx": mdx("Skills"),
      "sdk/react/button.mdx": generatedMdx("button"),
    });
    const inventory = await buildInventory(
      dir,
      yamlOf({
        pages: {
          index: entry({ diataxis: "landing" }),
          "concepts/agents": entry({
            medium: "diagram",
            why: "Lifecycle is structure.",
          }),
        },
        cohorts: {
          "sdk/react/": {
            generator: "gen-react-sdk-docs",
            diataxis: "reference",
            medium: "none",
          },
        },
      }),
    );
    const report = renderReport(inventory);
    expect(report).toContain("4 pages: 3 hand-authored, 1 generated (1 cohorts).");
    expect(report).toContain("## Violations (1)");
    expect(report).toContain("`concepts/skills` — **UNCLASSIFIED**");
    expect(report).toContain("`sdk/react/` — 1 pages, `gen-react-sdk-docs`");
    expect(report).toContain("- **medium**: ");
    expect(report).toContain("Lifecycle is structure.");
  });
});
