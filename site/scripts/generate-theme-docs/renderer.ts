/**
 * Renderer: parsed token contract → MDX strings.
 *
 * Two pages are produced:
 * - tokens.mdx  — the full default `--stgm-*` contract, grouped by the
 *   `@group` headers in tokens.css, with light/dark values and swatches.
 * - presets.mdx — the built-in design-language presets and every token
 *   each one overrides.
 */

import type { ThemePreset } from "../../../sdk/theme/src/presets/index";
import type {
  ThemeFileTokens,
  TokenDeclaration,
} from "../../../sdk/theme/src/contract/parse";

export interface PresetDoc {
  readonly meta: ThemePreset;
  readonly tokens: ThemeFileTokens;
}

const GENERATED_BANNER =
  "{/* Auto-generated by the theme token docs generator (make gen-theme-docs). DO NOT EDIT. */}\n";

/**
 * Inline swatch-plus-value component emitted into each generated page.
 * Color values get a color chip; non-color values render as plain code.
 */
const TOKEN_VALUE_COMPONENT = `export function TokenValue({ v }) {
  const isColor = /^(oklch|rgb|hsl|#)/.test(v);
  return (
    <span style={{ whiteSpace: "nowrap" }}>
      {isColor && (
        <span
          aria-hidden
          style={{
            display: "inline-block",
            width: "0.7rem",
            height: "0.7rem",
            borderRadius: "3px",
            border: "1px solid rgba(128,128,128,0.45)",
            background: v,
            verticalAlign: "-1px",
            marginRight: "0.35rem",
          }}
        />
      )}
      <code>{v}</code>
    </span>
  );
}
`;

function escapeMdxText(text: string): string {
  return text
    .replace(/\{/g, "\\{")
    .replace(/\}/g, "\\}")
    .replace(/<(?=[a-zA-Z0-9/!])/g, "\\<")
    .replace(/\|/g, "\\|");
}

function valueCell(declaration: TokenDeclaration | undefined): string {
  if (!declaration) return "—";
  return `<TokenValue v="${declaration.value.replace(/"/g, "&quot;")}" />`;
}

/** Group tokens preserving the file's declaration order. */
function groupInOrder(
  tokens: ReadonlyMap<string, TokenDeclaration>,
): Map<string, TokenDeclaration[]> {
  const groups = new Map<string, TokenDeclaration[]>();
  for (const declaration of tokens.values()) {
    const group = declaration.group ?? "Other";
    const list = groups.get(group);
    if (list) list.push(declaration);
    else groups.set(group, [declaration]);
  }
  return groups;
}

export function renderTokensPage(defaults: ThemeFileTokens): string {
  let mdx = `---
title: Design Tokens
description: The complete --stgm-* CSS custom property contract read by every Stigmer component.
---

${GENERATED_BANNER}
${TOKEN_VALUE_COMPONENT}
Every visual property of every Stigmer component flows through the \`--stgm-*\`
CSS custom properties below — no component hardcodes a color, radius, font,
or shadow. Override any subset of these tokens (globally, per preset class,
or per \`data-stgm-color-mode\`) to adapt the components to a host design
system. See the [Theming guide](/docs/sdk/theme/theming) for the scoping
model and override recipes.

Tokens without a **Dark** value inherit their light value in dark mode.
`;

  for (const [group, declarations] of groupInOrder(defaults.light)) {
    mdx += `\n## ${group}\n\n`;
    mdx += `| Token | Light | Dark | Purpose |\n`;
    mdx += `|-------|-------|------|--------|\n`;
    for (const declaration of declarations) {
      const dark = defaults.dark.get(declaration.name);
      const purpose = declaration.description
        ? escapeMdxText(declaration.description)
        : "";
      mdx += `| \`${declaration.name}\` | ${valueCell(declaration)} | ${valueCell(dark)} | ${purpose} |\n`;
    }
  }

  return mdx;
}

export function renderPresetsPage(
  defaults: ThemeFileTokens,
  presets: readonly PresetDoc[],
): string {
  let mdx = `---
title: Presets
description: Built-in design-language presets and the tokens each one overrides.
---

${GENERATED_BANNER}
${TOKEN_VALUE_COMPONENT}
A preset is a CSS class that overrides a subset of the
[default tokens](/docs/sdk/theme/tokens); anything a preset does not override
falls through to the defaults. Apply one via the \`preset\` prop on
\`StigmerProvider\`, or import the CSS and add the class yourself.

| Preset | Class | Description |
|--------|-------|-------------|
| \`default\` | — | Stigmer's built-in palette (the token defaults) |
`;

  for (const { meta } of presets) {
    mdx += `| \`${meta.id}\` | \`${meta.className}\` | ${escapeMdxText(meta.description)} |\n`;
  }

  mdx += `
\`\`\`tsx
import "@stigmer/theme/tokens.css";
import "@stigmer/theme/presets/corporate.css";

<StigmerProvider client={client} preset="corporate" colorMode="dark">
\`\`\`
`;

  for (const { meta, tokens } of presets) {
    mdx += `\n## ${meta.name}\n\n`;
    mdx += `${escapeMdxText(meta.description)} — \`import "@stigmer/theme/presets/${meta.id}.css"\`, class \`${meta.className}\`.\n\n`;
    mdx += `| Token | Light | Dark |\n`;
    mdx += `|-------|-------|------|\n`;
    const names = new Set([...tokens.light.keys(), ...tokens.dark.keys()]);
    for (const name of defaults.light.keys()) {
      if (!names.has(name)) continue;
      mdx += `| \`${name}\` | ${valueCell(tokens.light.get(name))} | ${valueCell(tokens.dark.get(name))} |\n`;
    }
  }

  return mdx;
}
