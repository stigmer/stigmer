/**
 * Tests for the theme token docs renderer. The tokens page lists every
 * default token under its `@group` heading with its light and dark values;
 * the presets page tables each preset, shows a preset's CSS import from
 * `@stigmer/design-tokens` and its class, and lists only the tokens that
 * preset overrides, in the defaults' order. Both carry the do-not-edit
 * banner. The input is hand-built token maps.
 */

import { describe, expect, it } from "vitest";
import { renderPresetsPage, renderTokensPage, type PresetDoc } from "../renderer";
import type { ThemeFileTokens, TokenDeclaration } from "../../../../sdk/theme/src/contract/parse";

const BANNER = "{/* Auto-generated by the theme token docs generator (make gen-theme-docs). DO NOT EDIT. */}";

function tokens(light: TokenDeclaration[], dark: TokenDeclaration[] = []): ThemeFileTokens {
  return {
    light: new Map(light.map((t) => [t.name, t])),
    dark: new Map(dark.map((t) => [t.name, t])),
  };
}

const DEFAULTS = tokens(
  [
    { name: "--stgm-background", value: "oklch(0.98 0 0)", description: "Page {surface}", group: "Core colors" },
    { name: "--stgm-primary", value: "oklch(0.55 0.12 190)", group: "Core colors" },
    { name: "--stgm-radius", value: "0.5rem", group: "Shape" },
  ],
  [{ name: "--stgm-background", value: "oklch(0.145 0 0)", group: "Core colors" }],
);

const CORPORATE: PresetDoc = {
  meta: {
    id: "corporate",
    name: "Corporate",
    className: "stgm-theme-corporate",
    description: "Enterprise SaaS — tight radius",
    swatch: "oklch(0.48 0.15 250)",
  },
  tokens: tokens(
    [
      { name: "--stgm-radius", value: "0.25rem" },
      { name: "--stgm-primary", value: "oklch(0.48 0.15 250)" },
    ],
    [{ name: "--stgm-primary", value: "oklch(0.6 0.15 250)" }],
  ),
};

describe("renderTokensPage", () => {
  it("lists each token under its group with its light and dark values", () => {
    const mdx = renderTokensPage(DEFAULTS);
    expect(mdx).toContain(BANNER);
    expect(mdx).toContain(
      "\n## Core colors\n\n| Token | Light | Dark | Purpose |\n|-------|-------|------|--------|\n" +
        '| `--stgm-background` | <TokenValue v="oklch(0.98 0 0)" /> | <TokenValue v="oklch(0.145 0 0)" /> | Page \\{surface\\} |\n' +
        '| `--stgm-primary` | <TokenValue v="oklch(0.55 0.12 190)" /> | — |  |\n',
    );
    expect(mdx).toContain('\n## Shape\n\n');
    expect(mdx.indexOf("## Core colors")).toBeLessThan(mdx.indexOf("## Shape"));
  });
});

describe("renderPresetsPage", () => {
  it("tables each preset with its class and description", () => {
    const mdx = renderPresetsPage(DEFAULTS, [CORPORATE]);
    expect(mdx).toContain(BANNER);
    expect(mdx).toContain("| `corporate` | `stgm-theme-corporate` | Enterprise SaaS — tight radius |\n");
  });

  it("shows each preset's import from @stigmer/design-tokens and its class", () => {
    const mdx = renderPresetsPage(DEFAULTS, [CORPORATE]);
    expect(mdx).toContain(
      "\n## Corporate\n\n" +
        'Enterprise SaaS — tight radius — `import "@stigmer/design-tokens/presets/corporate.css"`, class `stgm-theme-corporate`.\n\n',
    );
    expect(mdx).toContain('import "@stigmer/design-tokens/tokens.css";');
  });

  it("lists only the tokens a preset overrides, in the defaults' order", () => {
    const mdx = renderPresetsPage(DEFAULTS, [CORPORATE]);
    const section = mdx.slice(mdx.indexOf("## Corporate"));
    expect(section).toContain(
      "| Token | Light | Dark |\n|-------|-------|------|\n" +
        '| `--stgm-primary` | <TokenValue v="oklch(0.48 0.15 250)" /> | <TokenValue v="oklch(0.6 0.15 250)" /> |\n' +
        '| `--stgm-radius` | <TokenValue v="0.25rem" /> | — |\n',
    );
    expect(section).not.toContain("--stgm-background");
  });
});
