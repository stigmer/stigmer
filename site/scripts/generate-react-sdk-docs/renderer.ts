/**
 * Renderer: Domain model → MDX strings.
 *
 * Each domain produces one .mdx page. Associated types (Props / Return
 * interfaces) are rendered inline under their hook or component. Standalone
 * types go in a trailing "Types" section.
 */

import type { Domain, Hook, Component, TypeDef, Field } from "./model";
import {
  escapeJsString,
  renderCommentParts,
} from "./mdx-utils";

// Hand-maintained page order grouped by adoption journey. Domains not listed
