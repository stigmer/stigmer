// ---------------------------------------------------------------------------
// Public API
// ---------------------------------------------------------------------------

export function renderDomainPage(domain: Domain): string {
  let mdx = "";

  mdx += renderFrontmatter(domain);
  mdx += "\n";
  mdx += "{/* Auto-generated by @stigmer/react docs generator. DO NOT EDIT. */}\n";

  if (domain.hooks.length > 0) {
    mdx += "\n## Hooks\n";
    for (const hook of domain.hooks) {
      mdx += "\n" + renderHookSection(hook);
    }
  }

  if (domain.components.length > 0) {
    mdx += "\n## Components\n";
    for (const component of domain.components) {
      mdx += "\n" + renderComponentSection(component);
    }
  }

  if (domain.types.length > 0) {
    mdx += "\n## Types\n";
    for (const typeDef of domain.types) {
      mdx += "\n" + renderTypeDefSection(typeDef);
    }
  }

  return mdx;
}

export function renderMetaJson(domains: Domain[]): string {
  const meta = {
    title: "React SDK",
    pages: domains.map((d) => d.slug).sort(),
  };
  return JSON.stringify(meta, null, 2) + "\n";
}

export interface DomainSummaryEntry {
  slug: string;
  title: string;
  description: string;
  hooks: number;
  components: number;
}

export function renderSummaryJson(domains: Domain[]): string {
  const entries: DomainSummaryEntry[] = domains
    .filter((d) => d.slug !== "core")
    .map((d) => ({
      slug: d.slug,
      title: d.title,
      description: d.description,
      hooks: d.hooks.length,
      components: d.components.length,
    }));

  const summary = { domains: entries };
  return JSON.stringify(summary, null, 2) + "\n";
}

// ---------------------------------------------------------------------------
// Frontmatter
// ---------------------------------------------------------------------------

function renderFrontmatter(domain: Domain): string {
  let s = "---\n";
  s += `title: ${domain.title}\n`;
  if (domain.description) {
    s += `description: ${domain.description}\n`;
  }
  s += "---\n";
  return s;
}

// ---------------------------------------------------------------------------
// Hook section
// ---------------------------------------------------------------------------

function renderHookSection(hook: Hook): string {
  let s = `### ${hook.name}\n\n`;

  if (hook.description.length > 0) {
    s += renderCommentParts(hook.description) + "\n\n";
  }

  // Signature
  const paramStr = hook.parameters
    .map((p) => {
      const opt = p.required ? "" : "?";
      return `${p.name}${opt}: ${p.typeString}`;
    })
    .join(", ");
  s += "**Signature**\n\n";
  s += `\`\`\`tsx\nfunction ${hook.name}(${paramStr}): ${hook.returnType.typeString}\n\`\`\`\n\n`;

  // Parameters table
  if (hook.parameters.length > 0) {
    const paramFields: Field[] = hook.parameters.map((p) => ({
      name: p.name,
      typeString: p.typeString,
      description: p.description,
      required: p.required,
      typeLink: null,
    }));
    s += renderTypeTable(paramFields) + "\n\n";
  }

  // Return type (inline TypeTable when interface is available)
  if (hook.returnInterface && hook.returnInterface.fields.length > 0) {
    s += `**Returns** — \`${hook.returnType.name}\`\n\n`;
    s += renderTypeTable(hook.returnInterface.fields) + "\n\n";
  }

  // Examples
  for (const example of hook.examples) {
    s += `\`\`\`tsx\n${example}\n\`\`\`\n\n`;
  }

  return s;
}

// ---------------------------------------------------------------------------
// Component section
// ---------------------------------------------------------------------------

function renderComponentSection(component: Component): string {
  let s = `### ${component.name}\n\n`;

  if (component.description.length > 0) {
    s += renderCommentParts(component.description) + "\n\n";
  }

  if (PREVIEW_COMPONENTS.has(component.name)) {
    s += `<ComponentPreview component="${component.name}" />\n\n`;
  }

  if (component.propsInterface && component.propsInterface.fields.length > 0) {
    s += `**Props** — \`${component.propsInterface.name}\`\n\n`;
    s += renderTypeTable(component.propsInterface.fields) + "\n\n";
  }

  for (const example of component.examples) {
    s += `\`\`\`tsx\n${example}\n\`\`\`\n\n`;
  }

  return s;
}

// ---------------------------------------------------------------------------
// Standalone type section
// ---------------------------------------------------------------------------

function renderTypeDefSection(typeDef: TypeDef): string {
  let s = `### ${typeDef.name}\n\n`;

  if (typeDef.description.length > 0) {
    s += renderCommentParts(typeDef.description) + "\n\n";
  }

  if (typeDef.signature) {
    s += `\`\`\`tsx\n${typeDef.signature}\n\`\`\`\n\n`;
  }

  if (typeDef.fields.length > 0) {
    s += renderTypeTable(typeDef.fields) + "\n\n";
  }

  for (const example of typeDef.examples) {
    s += `\`\`\`tsx\n${example}\n\`\`\`\n\n`;
  }

  return s;
}

// ---------------------------------------------------------------------------
// TypeTable
// ---------------------------------------------------------------------------

function renderTypeTable(fields: Field[]): string {
  if (fields.length === 0) return "";

  const lines: string[] = ["<TypeTable", "  type={{"];

  for (const field of fields) {
    const props: string[] = [
      `type: "${escapeJsString(field.typeString)}"`,
      `description: "${escapeJsString(field.description)}"`,
    ];
    if (field.required) props.push("required: true");
    if (field.typeLink) {
      props.push(`typeDescriptionLink: "${escapeJsString(field.typeLink)}"`);
    }
    const key = isValidJsIdentifier(field.name)
      ? field.name
      : `"${escapeJsString(field.name)}"`;
    lines.push(`    ${key}: { ${props.join(", ")} },`);
  }

  lines.push("  }}", "/>");
  return lines.join("\n");
}

const JS_IDENTIFIER_RE = /^[A-Za-z_$][A-Za-z0-9_$]*$/;

function isValidJsIdentifier(name: string): boolean {
  return JS_IDENTIFIER_RE.test(name);
}
