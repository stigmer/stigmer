/**
 * Tests for the Ink SDK reference page renderer: exports group under their
 * category's section heading, in the order the parser gave; an export the
 * Ink package re-exports from `@stigmer/client/node` says so and points at
 * the SDK overview, and its fields table is its Config rather than its
 * Props; a utility's table is its Parameters; and the page carries the
 * do-not-edit banner. The input is a hand-built reference model.
 */

import { describe, expect, it } from "vitest";
import { renderMetaJson, renderReferencePage } from "../renderer";
import type { InkExport, InkReference } from "../parser";

function inkExport(overrides: Partial<InkExport> & Pick<InkExport, "name" | "category">): InkExport {
  return {
    description: [],
    propsInterface: null,
    examples: [],
    sourceUrl: "",
    isReExport: false,
    ...overrides,
  };
}

function reference(exports: InkExport[]): InkReference {
  return { title: "Ink SDK Reference", description: "Every export of @stigmer/ink-ui.", exports };
}

describe("renderReferencePage", () => {
  it("opens with the frontmatter and the do-not-edit banner", () => {
    const mdx = renderReferencePage(reference([]));
    expect(mdx).toBe(
      "---\ntitle: Ink SDK Reference\ndescription: Every export of @stigmer/ink-ui.\n---\n\n" +
        "{/* Auto-generated by generate-ink-sdk-docs. DO NOT EDIT. */}\n",
    );
  });

  it("marks a re-export from @stigmer/client/node and titles its table Config", () => {
    const mdx = renderReferencePage(
      reference([
        inkExport({
          name: "createNodeClient",
          category: "transport",
          isReExport: true,
          description: [{ kind: "text", text: "Creates a client for Node." }],
          propsInterface: {
            name: "NodeClientConfig",
            description: [],
            fields: [{ name: "baseUrl", typeString: "string", description: "Server URL.", required: true, typeLink: null }],
          },
        }),
      ]),
    );

    expect(mdx).toContain(
      "### createNodeClient\n\n" +
        "Re-exported from `@stigmer/client/node`. See [SDK Overview](/docs/sdk/overview) for full documentation.\n\n" +
        "Creates a client for Node.\n\n" +
        "**Config** — `NodeClientConfig`\n\n",
    );
    expect(mdx).toContain('    baseUrl: { type: "string", description: "Server URL.", required: true },');
  });

  it("leaves the re-export note off the package's own exports", () => {
    const mdx = renderReferencePage(
      reference([
        inkExport({
          name: "SessionView",
          category: "composedView",
          propsInterface: {
            name: "SessionViewProps",
            description: [],
            fields: [{ name: "sessionId", typeString: "string", description: "", required: true, typeLink: null }],
          },
        }),
      ]),
    );

    expect(mdx).not.toContain("Re-exported from");
    expect(mdx).toContain("## Composed Views\n\n### SessionView\n\n**Props** — `SessionViewProps`\n\n");
  });

  it("groups exports under their section headings and titles a utility's table Parameters", () => {
    const mdx = renderReferencePage(
      reference([
        inkExport({ name: "InkStigmerProvider", category: "provider" }),
        inkExport({ name: "createNodeTransport", category: "transport", isReExport: true }),
        inkExport({
          name: "renderMarkdown",
          category: "utility",
          propsInterface: {
            name: "RenderMarkdownOptions",
            description: [],
            fields: [{ name: "width", typeString: "number", description: "", required: false, typeLink: null }],
          },
          examples: ['renderMarkdown("# Hi")'],
        }),
      ]),
    );

    const providerAt = mdx.indexOf("## Provider and Transport");
    expect(providerAt).toBeGreaterThan(0);
    expect(mdx.indexOf("## Provider and Transport", providerAt + 1)).toBe(-1);
    expect(mdx.indexOf("### InkStigmerProvider")).toBeLessThan(mdx.indexOf("### createNodeTransport"));
    expect(mdx).toContain("## Utilities\n\n### renderMarkdown\n\n**Parameters**\n\n");
    expect(mdx).toContain('```tsx\nrenderMarkdown("# Hi")\n```');
  });
});

describe("renderMetaJson", () => {
  it("lists the Ink SDK's two pages", () => {
    expect(JSON.parse(renderMetaJson())).toEqual({ title: "Ink SDK", pages: ["cli-integration", "reference"] });
  });
});
