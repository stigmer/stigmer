/**
 * Renderer: Ink SDK reference model → single MDX page.
 *
 * Produces one reference.mdx with sections for each category:
 *   Provider and Transport → Components → Composed Views → Utilities
 */

import type { InkReference, InkExport } from "./parser";
import type { Field } from "../generate-react-sdk-docs/model";
import { escapeJsString, renderCommentParts } from "../generate-react-sdk-docs/mdx-utils";

// ---------------------------------------------------------------------------
// Category → section heading
// ---------------------------------------------------------------------------

const CATEGORY_HEADINGS: Record<string, string> = {
  provider: "Provider and Transport",
  transport: "Provider and Transport",
  component: "Components",
  composedView: "Composed Views",
  utility: "Utilities",
};

// ---------------------------------------------------------------------------
// Public API
// ---------------------------------------------------------------------------

export function renderReferencePage(ref: InkReference): string {
  let mdx = "";

  mdx += renderFrontmatter(ref);
  mdx += "\n";
  mdx += "{/* Auto-generated by generate-ink-sdk-docs. DO NOT EDIT. */}\n";

  const grouped = groupBySection(ref.exports);

  for (const [heading, exports] of grouped) {
    mdx += `\n## ${heading}\n`;

    for (const exp of exports) {
      mdx += "\n" + renderExportSection(exp);
    }
  }

  return mdx;
}

export function renderMetaJson(): string {
  const meta = {
    title: "Ink SDK",
    pages: ["cli-integration", "reference"],
  };
  return JSON.stringify(meta, null, 2) + "\n";
}

// ---------------------------------------------------------------------------
// Internals
// ---------------------------------------------------------------------------

function renderFrontmatter(ref: InkReference): string {
  let s = "---\n";
  s += `title: ${ref.title}\n`;
  s += `description: ${ref.description}\n`;
  s += "---\n";
  return s;
}

function groupBySection(exports: InkExport[]): [string, InkExport[]][] {
  const sections = new Map<string, InkExport[]>();

  for (const exp of exports) {
    const heading = CATEGORY_HEADINGS[exp.category] ?? "Other";
    const list = sections.get(heading) ?? [];
    list.push(exp);
    sections.set(heading, list);
  }

  return [...sections.entries()];
}

function renderExportSection(exp: InkExport): string {
  let s = `### ${exp.name}\n\n`;

  if (exp.isReExport) {
    s += `Re-exported from \`@stigmer/sdk/node\`. See [SDK Overview](/docs/sdk/overview) for full documentation.\n\n`;
  }

  if (exp.description.length > 0) {
    s += renderCommentParts(exp.description) + "\n\n";
  }

  if (exp.propsInterface && exp.propsInterface.fields.length > 0) {
    if (exp.category === "utility") {
      s += `**Parameters**\n\n`;
    } else if (exp.isReExport) {
      s += `**Config** — \`${exp.propsInterface.name}\`\n\n`;
    } else {
      s += `**Props** — \`${exp.propsInterface.name}\`\n\n`;
    }
    s += renderTypeTable(exp.propsInterface.fields) + "\n\n";
  }

  for (const example of exp.examples) {
    s += `\`\`\`tsx\n${example}\n\`\`\`\n\n`;
  }

  return s;
}

function renderTypeTable(fields: Field[]): string {
  if (fields.length === 0) return "";

  const lines: string[] = ["<TypeTable", "  type={{"];

  for (const field of fields) {
    const props: string[] = [
      `type: "${escapeJsString(field.typeString)}"`,
      `description: "${escapeJsString(field.description)}"`,
    ];
    if (field.required) props.push("required: true");
    if (field.typeLink) {
      props.push(`typeDescriptionLink: "${escapeJsString(field.typeLink)}"`);
    }
    const key = isValidJsIdentifier(field.name)
      ? field.name
      : `"${escapeJsString(field.name)}"`;
    lines.push(`    ${key}: { ${props.join(", ")} },`);
  }

  lines.push("  }}", "/>");
  return lines.join("\n");
}

const JS_IDENTIFIER_RE = /^[A-Za-z_$][A-Za-z0-9_$]*$/;

function isValidJsIdentifier(name: string): boolean {
  return JS_IDENTIFIER_RE.test(name);
}
