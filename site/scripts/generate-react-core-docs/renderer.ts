/**
 * Renderer: the React core reference model → one MDX page, its sections in
 * the parser's order (contexts and providers, hooks, functions, constants),
 * each export with its description, its tables as TypeTables and its examples.
 */

import type { CoreExport, CoreReference, CoreCategory } from "./parser";
import type { Field } from "../generate-react-sdk-docs/model";
import { escapeJsString, renderCommentParts, renderExample } from "../generate-react-sdk-docs/mdx-utils";

const HEADINGS: Record<CoreCategory, string> = {
  context: "Contexts and providers",
  hook: "Hooks",
  function: "Functions",
  constant: "Constants",
};

const IDENTIFIER = /^[A-Za-z_$][A-Za-z0-9_$]*$/;

export function renderReferencePage(ref: CoreReference): string {
  let mdx = `---\ntitle: ${ref.title}\ndescription: ${ref.description}\n---\n\n`;
  mdx += "{/* Auto-generated by generate-react-core-docs. DO NOT EDIT. */}\n";
  let current: CoreCategory | null = null;
  for (const exp of ref.exports) {
    if (exp.category !== current) {
      current = exp.category;
      mdx += `\n## ${HEADINGS[current]}\n`;
    }
    mdx += `\n${renderExport(exp)}`;
  }
  return mdx;
}

/**
 * The folder's meta.json: the hand-written guide that builds a chat from the
 * hooks (build-a-chat.mdx), then the generated reference. Fumadocs lists only
 * the pages a meta.json names, and this is written whole, so the guide is
 * named here.
 */
export function renderMetaJson(): string {
  return `${JSON.stringify({ title: "React core", pages: ["build-a-chat", "reference"] }, null, 2)}\n`;
}

function renderExport(exp: CoreExport): string {
  let s = `### ${exp.name}\n\n`;
  if (exp.description.length > 0) s += `${renderCommentParts(exp.description)}\n\n`;
  for (const table of exp.tables) {
    s += `**${table.role}** — \`${table.name}\`\n\n${renderTypeTable(table.fields)}\n\n`;
  }
  for (const example of exp.examples) s += renderExample(example);
  return s;
}

function renderTypeTable(fields: Field[]): string {
  const lines = ["<TypeTable", "  type={{"];
  for (const field of fields) {
    const props = [`type: "${escapeJsString(field.typeString)}"`, `description: "${escapeJsString(field.description)}"`];
    if (field.required) props.push("required: true");
    const key = IDENTIFIER.test(field.name) ? field.name : `"${escapeJsString(field.name)}"`;
    lines.push(`    ${key}: { ${props.join(", ")} },`);
  }
  lines.push("  }}", "/>");
  return lines.join("\n");
}
