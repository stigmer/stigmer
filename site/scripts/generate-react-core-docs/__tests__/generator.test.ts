/**
 * Tests for the React core reference: contexts and providers come first, then
 * hooks, functions and constants, each sorted by name; a hook's Options and
 * Return interfaces become its tables, absent ones are skipped; a comment's
 * inline link renders as code; and the page carries its generator marker and
 * frontmatter. The input is a minimal TypeDoc JSON written to a temporary file.
 */

import * as fs from "node:fs/promises";
import * as os from "node:os";
import * as path from "node:path";
import { afterEach, beforeEach, describe, expect, it } from "vitest";
import { parseTypeDocJson } from "../parser";
import { renderMetaJson, renderReferencePage } from "../renderer";
import { ReflectionKind } from "../../generate-react-sdk-docs/typedoc-types";
import type { Reflection, TypeDocProject } from "../../generate-react-sdk-docs/typedoc-types";

let dir: string;

beforeEach(async () => {
  dir = await fs.mkdtemp(path.join(os.tmpdir(), "react-core-docs-"));
});

afterEach(async () => {
  await fs.rm(dir, { recursive: true, force: true });
});

const summary = (text: string) => ({ summary: [{ kind: "text" as const, text }] });

function fn(id: number, name: string, text = ""): Reflection {
  return { id, name, variant: "declaration", kind: ReflectionKind.Function, flags: {}, signatures: [{ id: id + 100, name, variant: "signature", kind: ReflectionKind.CallSignature, flags: {}, comment: summary(text) }] } as Reflection;
}

function variable(id: number, name: string, text = ""): Reflection {
  return { id, name, variant: "declaration", kind: ReflectionKind.Variable, flags: {}, comment: summary(text) } as Reflection;
}

function iface(id: number, name: string, fields: string[]): Reflection {
  return {
    id,
    name,
    variant: "declaration",
    kind: ReflectionKind.Interface,
    flags: {},
    children: fields.map((f, i) => ({ id: id * 10 + i, name: f, variant: "declaration", kind: ReflectionKind.Property, flags: { isOptional: f.endsWith("?") }, type: { type: "intrinsic", name: "string" } })),
  } as Reflection;
}

async function parse(children: Reflection[]) {
  const project: TypeDocProject = { schemaVersion: "2.0", id: 0, name: "@stigmer/react-core", variant: "project", kind: ReflectionKind.Project, children, symbolIdMap: {}, packageName: "@stigmer/react-core" };
  const file = path.join(dir, "api.json");
  await fs.writeFile(file, JSON.stringify(project));
  return parseTypeDocJson(file);
}

describe("the React core reference", () => {
  it("orders contexts, hooks, functions and constants, and tables a hook by its Options and Return", async () => {
    const ref = await parse([
      fn(1, "runPhaseOf", "The run phase of a turn phase."),
      fn(2, "useSessionList", "Lists sessions."),
      variable(3, "StigmerContext", "The client."),
      fn(4, "FetchCacheProvider"),
      variable(5, "DEFAULT_MODEL_ID"),
      fn(6, "useStigmer"),
      iface(7, "UseSessionListOptions", ["limit?"]),
      iface(8, "UseSessionListReturn", ["sessions"]),
    ]);
    expect(ref.exports.map((e) => [e.name, e.category])).toEqual([
      ["FetchCacheProvider", "context"],
      ["StigmerContext", "context"],
      ["useSessionList", "hook"],
      ["useStigmer", "hook"],
      ["runPhaseOf", "function"],
      ["DEFAULT_MODEL_ID", "constant"],
    ]);
    expect(ref.exports[2]!.tables.map((t) => [t.role, t.name, t.fields.map((f) => [f.name, f.required])])).toEqual([
      ["Options", "UseSessionListOptions", [["limit?", false]]],
      ["Returns", "UseSessionListReturn", [["sessions", true]]],
    ]);
    expect(ref.exports[3]!.tables).toEqual([]);
  });

  it("renders the page with its marker, its sections and its tables", async () => {
    const ref = await parse([fn(2, "useSessionList", "Lists sessions."), iface(8, "UseSessionListReturn", ["sessions"]), variable(3, "StigmerContext", "The client.")]);
    const mdx = renderReferencePage(ref);
    expect(mdx.startsWith("---\ntitle: React core reference\n")).toBe(true);
    expect(mdx).toContain("{/* Auto-generated by generate-react-core-docs. DO NOT EDIT. */}");
    expect(mdx).toContain("## Contexts and providers\n\n### StigmerContext\n\nThe client.");
    expect(mdx).toContain("## Hooks\n\n### useSessionList\n\nLists sessions.\n\n**Returns** — `UseSessionListReturn`\n\n<TypeTable");
    expect(mdx).toContain('sessions: { type: "string", description: "", required: true },');
    expect(JSON.parse(renderMetaJson())).toEqual({ title: "React core", pages: ["reference"] });
  });
});
