import { AbsoluteFill, Audio, Sequence, interpolate, staticFile, useCurrentFrame } from "remotion";
import type { Overlay, Scene } from "../../../films/intro/manifest";
import { FPS, MUSIC, SCENES } from "../../../films/intro/manifest";
import type { NarrationManifest } from "./durations";
import { sceneDurations, totalDuration } from "./durations";
import { GRAPHICS } from "./graphics";
import { Placeholder } from "./scenes/Placeholder";
import { PresenterScene } from "./scenes/PresenterScene";
import type { FilmData } from "./scenes/RecordedScene";
import { RecordedScene } from "./scenes/RecordedScene";

export type IntroFilmProps = {
  narration: NarrationManifest | null;
  /** Scene ids whose HeyGen presenter clip exists in assets/presenter/. */
  presenterScenes: string[];
  /** Captured footage + staged film data (see RecordedScene). */
  filmData: FilmData;
  /** True when assets/music/bed.mp3 exists (generated by scripts/music.mjs). */
  hasMusic: boolean;
};

/**
 * The Intro to Stigmer film: scenes laid out back to back, each carrying its
 * own narration audio when generated (assets/narration/<scene-id>.mp3).
 *
 * Scene visuals resolve in order: a presenter clip when one exists, the
 * manifest's editorial cuts when the scene declares them (real recordings +
 * rendered data panels + registered graphics, missing assets degrade to
 * slates), and the structured Placeholder otherwise — so a rough cut of the
 * full film is available at every stage of production. Manifest `overlays`
 * composite above the base visual (the S1b logo reveal over the presenter,
 * the S6b end card holding after her close).
 */
export const IntroFilm = ({ narration, presenterScenes, filmData, hasMusic }: IntroFilmProps) => {
  const durations = sceneDurations(narration);
  let cursor = 0;
  return (
    <AbsoluteFill style={{ background: "#000" }}>
      {SCENES.map((scene) => {
        const from = cursor;
        const duration = durations[scene.id];
        cursor += duration;
        const hasPresenterClip = presenterScenes.includes(scene.id);
        return (
          <Sequence key={scene.id} from={from} durationInFrames={duration} name={scene.id}>
            {hasPresenterClip ? (
              <PresenterScene
                sceneId={scene.id}
                clipFrames={
                  narration?.[scene.id]
                    ? Math.ceil((narration[scene.id].durationMs / 1000) * FPS)
                    : undefined
                }
              />
            ) : scene.cuts !== undefined ? (
              <RecordedScene cuts={scene.cuts} durationInFrames={duration} data={filmData} />
            ) : (
              <Placeholder scene={scene} />
            )}
            {scene.overlays?.map((overlay) => (
              <OverlaySlot key={overlay.graphic} overlay={overlay} sceneFrames={duration} data={filmData} />
            ))}
            {/* Presenter clips carry their own (lip-synced) narration audio. */}
            {!hasPresenterClip && narration?.[scene.id] ? (
              <Audio src={staticFile(`narration/${scene.id}.mp3`)} />
            ) : null}
          </Sequence>
        );
      })}
      {hasMusic ? <MusicBed narration={narration} /> : null}
    </AbsoluteFill>
  );
};

/**
 * One timed overlay. An unregistered graphic renders nothing rather than
 * a slate — an overlay must never blank the base visual it decorates.
 * Overlays receive FilmData like graphic cuts do, so an overlay can build
 * on real footage (the S1 embed flash-forward plays the s4d take).
 */
const OverlaySlot = ({
  overlay,
  sceneFrames,
  data,
}: {
  overlay: Overlay;
  sceneFrames: number;
  data: FilmData;
}) => {
  const Graphic = GRAPHICS[overlay.graphic];
  if (Graphic === undefined) return null;
  const from = Math.round(overlay.atSec * FPS);
  const frames =
    overlay.durationSec !== undefined ? Math.round(overlay.durationSec * FPS) : sceneFrames - from;
  if (frames <= 0) return null;
  return (
    <Sequence from={from} durationInFrames={frames} name={overlay.graphic}>
      <Graphic durationInFrames={frames} data={data} />
    </Sequence>
  );
};

/**
 * Bed level under voiceover scenes — present enough to register in the
 * gaps between sentences (v1 levels were inaudible; owner note at the v2
 * gate), still clearly under the voice.
 */
const BED_VOLUME = 0.28;
/** Quieter under the presenter — her room tone is part of the take. */
const PRESENTER_VOLUME = 0.16;
/** The bed swells when nobody is speaking (the end card's hold). */
const SWELL_VOLUME = 0.5;

/**
 * The film-length music bed (assets/music/bed.mp3, generated by
 * scripts/music.mjs). Volume is derived from the same scene layout the
 * picture uses: presenter scenes duck deepest, voiceover scenes hold the
 * bed level, and the end-card hold (after the close's narration ends)
 * swells and then fades to black with the film.
 */
const MusicBed = ({ narration }: { narration: NarrationManifest | null }) => {
  const frame = useCurrentFrame();
  const durations = sceneDurations(narration);
  const total = totalDuration(narration);

  let at = 0;
  let level = BED_VOLUME;
  for (const scene of SCENES) {
    const sceneEnd = at + durations[scene.id];
    if (frame < sceneEnd) {
      level = volumeForScene(scene, frame - at, durations[scene.id]);
      break;
    }
    at = sceneEnd;
  }

  // Ease the whole bed in at the top and resolve it with the final frames.
  const envelope =
    interpolate(frame, [0, FPS * 1.5], [0, 1], { extrapolateLeft: "clamp", extrapolateRight: "clamp" }) *
    interpolate(frame, [total - FPS * 2, total], [1, 0], { extrapolateLeft: "clamp", extrapolateRight: "clamp" });

  return (
    <Audio
      src={staticFile("music/bed.mp3")}
      startFrom={Math.round((MUSIC.startSec ?? 0) * FPS)}
      volume={level * envelope}
    />
  );
};

const volumeForScene = (scene: Scene, sceneFrame: number, sceneFrames: number): number => {
  const holdFrames = Math.round((scene.holdSec ?? 0) * FPS);
  const holdStart = sceneFrames - holdFrames;
  if (holdFrames > 0 && sceneFrame >= holdStart) {
    // Narration is over; let the bed carry the hold (the end card's beat).
    return interpolate(sceneFrame, [holdStart, holdStart + FPS], [PRESENTER_VOLUME, SWELL_VOLUME], {
      extrapolateLeft: "clamp",
      extrapolateRight: "clamp",
    });
  }
  return scene.mode === "presenter" ? PRESENTER_VOLUME : BED_VOLUME;
};
