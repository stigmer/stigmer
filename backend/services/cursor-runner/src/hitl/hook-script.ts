/**
 * Template for the preToolUse hook script that Cursor spawns.
 *
 * This module doesn't execute as a hook itself -- it generates the shell
 * script that is written to .cursor/hooks/stigmer-approval.sh. That script
 * is invoked by Cursor for every tool call via the preToolUse hook.
 *
 * The hook script:
 * 1. Reads the tool call JSON from stdin
 * 2. Reads the approval state file written by the cursor-runner
 * 3. Checks the approval policy (which tools need approval)
 * 4. Returns { "permission": "allow" } or { "permission": "deny" } on stdout
 *
 * The script is self-contained (no Node.js required) for portability.
 * It uses bash + jq for JSON parsing.
 */

import { requiresApproval } from "./approval-policy.js";

/**
 * Generates the bash hook script content.
 *
 * The script reads a JSON state file written by the cursor-runner before
 * each agent.send() call. The state file contains the list of pre-approved
 * tools (from the reinvocation flow) and the auto-approve-all flag.
 */
export function generateHookScript(stateFilePath: string): string {
  return `#!/bin/bash
# Stigmer HITL approval hook for Cursor preToolUse
# Generated by cursor-runner — do not edit manually.
#
# Reads tool call from stdin (JSON), checks approval state,
# returns permission decision on stdout (JSON).

set -euo pipefail

INPUT=$(cat)
TOOL_NAME=$(echo "$INPUT" | grep -o '"tool_name":"[^"]*"' | head -1 | cut -d'"' -f4)
STATE_FILE="${stateFilePath}"

# If state file doesn't exist, allow everything (failsafe)
if [ ! -f "$STATE_FILE" ]; then
  echo '{"permission":"allow"}'
  exit 0
fi

# Read auto-approve-all flag
AUTO_APPROVE=$(grep -o '"autoApproveAll":true' "$STATE_FILE" || true)
if [ -n "$AUTO_APPROVE" ]; then
  echo '{"permission":"allow"}'
  exit 0
fi

# Check if tool is in the pre-approved list (wildcard match for reinvocation)
APPROVED_ALL=$(grep -o '"name":"\\*"' "$STATE_FILE" || true)
if [ -n "$APPROVED_ALL" ]; then
  echo '{"permission":"allow"}'
  exit 0
fi

# Built-in policy: read-only tools are always allowed
case "$TOOL_NAME" in
  Read|Grep|Glob|SemanticSearch|WebSearch|WebFetch|Write|StrReplace|EditNotebook|Task|SwitchMode|AskQuestion|GenerateImage|ReadLints)
    echo '{"permission":"allow"}'
    exit 0
    ;;
esac

# Destructive tools and unknown tools require approval — deny
echo '{"permission":"deny","agent_message":"STIGMER_APPROVAL_REQUIRED: This tool call requires user approval before execution. Do not attempt alternative approaches or workarounds. The execution will resume after the user reviews and approves this tool call.","user_message":"Tool requires approval: '"$TOOL_NAME"'"}'
exit 0
`;
}

/**
 * List of built-in tool approval policies for documentation / testing.
 * The actual enforcement happens in the generated bash script above.
 */
export const BUILT_IN_POLICIES = {
  requireApproval: ["Shell", "Delete"],
  allowByDefault: [
    "Read", "Grep", "Glob", "SemanticSearch", "WebSearch", "WebFetch",
    "Write", "StrReplace", "EditNotebook", "Task", "SwitchMode",
    "AskQuestion", "GenerateImage", "ReadLints",
  ],
};
