/**
 * Template for the preToolUse hook script that Cursor spawns.
 *
 * This module doesn't execute as a hook itself — it generates the shell
 * script that is written to .cursor/hooks/stigmer-approval.sh. That script
 * is invoked by Cursor for every tool call via the preToolUse hook.
 *
 * The hook script:
 * 1. Reads the tool call JSON from stdin
 * 2. Reads the approval state JSON file written by the cursor-runner
 * 3. Evaluates the policy: auto-approve, built-in allow-list, MCP policies,
 *    approved tool call IDs (reinvocation)
 * 4. Returns { "permission": "allow" } or { "permission": "deny" } on stdout
 *
 * The script is self-contained (no Node.js required) for portability.
 * It uses bash + grep/cut for lightweight JSON field extraction.
 *
 * Policy evaluation order (first match wins):
 * 1. autoApproveAll → allow
 * 2. Tool call ID in approvedToolCallIds → allow (reinvocation)
 * 3. Tool name in builtInAllowList → allow
 * 4. Tool name in mcpToolPolicies with requiresApproval=false → allow
 * 5. Tool name in mcpToolPolicies with requiresApproval=true → deny
 * 6. Unknown tool → deny (fail-closed)
 */

/**
 * Generates the bash hook script content.
 *
 * The script reads a JSON state file written by the cursor-runner before
 * each agent.send() call. The state file is the single source of truth
 * for all approval decisions.
 */
export function generateHookScript(stateFilePath: string): string {
  return `#!/bin/bash
# Stigmer HITL approval hook for Cursor preToolUse
# Generated by cursor-runner — do not edit manually.
#
# Reads tool call from stdin (JSON), checks approval state file,
# returns permission decision on stdout (JSON).

set -euo pipefail

INPUT=$(cat)

# Extract tool_name and call_id from the hook input JSON.
# Cursor sends the actual tool name (e.g., "search_services" for MCP tools).
TOOL_NAME=$(echo "$INPUT" | grep -o '"tool_name":"[^"]*"' | head -1 | cut -d'"' -f4)
CALL_ID=$(echo "$INPUT" | grep -o '"tool_call_id":"[^"]*"' | head -1 | cut -d'"' -f4)

STATE_FILE="${stateFilePath}"

# --- Failsafe: missing state file → deny (fail-closed) ---
if [ ! -f "$STATE_FILE" ]; then
  echo '{"permission":"deny","agent_message":"STIGMER_APPROVAL_REQUIRED: Approval state file not found. Tool calls require approval.","user_message":"Tool requires approval: '"$TOOL_NAME"'"}'
  exit 0
fi

STATE=$(cat "$STATE_FILE")

# --- 1. Auto-approve all ---
if echo "$STATE" | grep -q '"autoApproveAll":true'; then
  echo '{"permission":"allow"}'
  exit 0
fi

# --- 2. Check approved tool call IDs (reinvocation after SubmitApproval) ---
if [ -n "$CALL_ID" ]; then
  if echo "$STATE" | grep -q "\\"$CALL_ID\\""; then
    echo '{"permission":"allow"}'
    exit 0
  fi
fi

# --- 3. Check built-in allow list ---
if echo "$STATE" | grep -q "\\"builtInAllowList\\"" && echo "$STATE" | grep -q "\\"$TOOL_NAME\\""; then
  # Verify it's actually in the builtInAllowList array (not elsewhere in the JSON)
  ALLOW_LIST=$(echo "$STATE" | grep -o '"builtInAllowList":\\[[^]]*\\]' | head -1)
  if echo "$ALLOW_LIST" | grep -q "\\"$TOOL_NAME\\""; then
    echo '{"permission":"allow"}'
    exit 0
  fi
fi

# --- 4/5. Check MCP tool policies ---
if echo "$STATE" | grep -q "\\"mcpToolPolicies\\""; then
  # Check if this tool has a policy entry
  TOOL_POLICY=$(echo "$STATE" | grep -o "\\"$TOOL_NAME\\":{[^}]*}" | head -1)
  if [ -n "$TOOL_POLICY" ]; then
    if echo "$TOOL_POLICY" | grep -q '"requiresApproval":false'; then
      echo '{"permission":"allow"}'
      exit 0
    fi
    # requiresApproval is true (or absent = true by presence in policy list)
    MSG=$(echo "$TOOL_POLICY" | grep -o '"message":"[^"]*"' | head -1 | cut -d'"' -f4)
    if [ -z "$MSG" ]; then
      MSG="Tool requires approval: $TOOL_NAME"
    fi
    echo '{"permission":"deny","agent_message":"STIGMER_APPROVAL_REQUIRED: This tool call requires user approval before execution. Do not attempt alternative approaches or workarounds. The execution will resume after the user reviews and approves this tool call.","user_message":"'"$MSG"'"}'
    exit 0
  fi
fi

# --- 6. Unknown tool → deny (fail-closed) ---
echo '{"permission":"deny","agent_message":"STIGMER_APPROVAL_REQUIRED: This tool call requires user approval before execution. Do not attempt alternative approaches or workarounds. The execution will resume after the user reviews and approves this tool call.","user_message":"Tool requires approval: '"$TOOL_NAME"'"}'
exit 0
`;
}
