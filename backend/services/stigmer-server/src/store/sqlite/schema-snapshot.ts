/**
 * The schema the SQLite chain leaves, printed as SQL a reviewer reads: every
 * table and virtual table `sqlite_master` holds in name order, each followed
 * by its indexes in name order, with whitespace normalized and a table's columns and
 * constraints one per line. The committed `schema.snapshot.sql` is this
 * text for a fresh replay, compared by a test (the Postgres twin,
 * postgres/schema-snapshot.ts, says why a chain keeps one).
 *
 * SQLite keeps each object's CREATE text as written and amended by ALTER,
 * so that text is the schema; `pragma` alone could not show `WITHOUT
 * ROWID` or a CHECK. An FTS table's shadow tables are the engine's and are
 * left out, as is the chain's own ledger.
 */
import type { DatabaseSync } from "node:sqlite";

const HEADER =
  "-- The schema this chain leaves on a fresh database, printed from sqlite_master.\n" +
  "-- Generated by `npm run schema:snapshot`; a test compares it with a fresh replay.\n";

/** The suffixes FTS5 gives the shadow tables of a virtual table. */
const FTS5_SHADOW_SUFFIXES = [
  "_data",
  "_idx",
  "_content",
  "_docsize",
  "_config",
];

/** Prints every table, virtual table and index, in a stable order. */
export function snapshotSqliteSchema(db: DatabaseSync): string {
  const rows = db
    .prepare(
      `SELECT type, name, tbl_name, sql FROM sqlite_master
        WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite_%' AND name <> 'schema_version'
        ORDER BY name`,
    )
    .all() as Array<{
    type: string;
    name: string;
    tbl_name: string;
    sql: string;
  }>;
  const virtual = rows
    .filter(
      (row) => row.type === "table" && /^CREATE VIRTUAL TABLE/i.test(row.sql),
    )
    .map((row) => row.name);
  const shadow = new Set(
    virtual.flatMap((name) =>
      FTS5_SHADOW_SUFFIXES.map((suffix) => `${name}${suffix}`),
    ),
  );
  const parts = [HEADER];
  for (const table of rows.filter(
    (row) => row.type === "table" && !shadow.has(row.name),
  )) {
    const group = [
      table,
      ...rows.filter(
        (row) => row.type !== "table" && row.tbl_name === table.name,
      ),
    ];
    parts.push(
      `${group.map((row) => `${formatStatement(row.sql)};`).join("\n")}\n`,
    );
  }
  return parts.join("\n");
}

/** Collapses whitespace; a CREATE TABLE's top-level list gets one item per line. */
function formatStatement(sql: string): string {
  const flat = sql
    .replace(/\s+/g, " ")
    .replace(/\( /g, "(")
    .replace(/ \)/g, ")")
    .trim();
  if (!/^CREATE TABLE/i.test(flat)) {
    return flat;
  }
  const open = flat.indexOf("(");
  const close = flat.lastIndexOf(")");
  const items = splitTopLevel(flat.slice(open + 1, close));
  return `${flat.slice(0, open).trimEnd()} (\n${items.map((item) => `  ${item}`).join(",\n")}\n)${flat.slice(close + 1)}`;
}

/** Splits on commas outside parentheses and quotes. */
function splitTopLevel(body: string): string[] {
  const items: string[] = [];
  let depth = 0;
  let quote: string | undefined;
  let start = 0;
  for (let i = 0; i < body.length; i++) {
    const ch = body[i]!;
    if (quote !== undefined) {
      if (ch === quote) {
        quote = undefined;
      }
    } else if (ch === "'" || ch === '"' || ch === "`") {
      quote = ch;
    } else if (ch === "(") {
      depth++;
    } else if (ch === ")") {
      depth--;
    } else if (ch === "," && depth === 0) {
      items.push(body.slice(start, i).trim());
      start = i + 1;
    }
  }
  items.push(body.slice(start).trim());
  return items;
}
