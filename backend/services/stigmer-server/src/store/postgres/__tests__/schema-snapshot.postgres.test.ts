/**
 * Pins the Postgres schema printer (../schema-snapshot.ts) on a schema of
 * its own: a table's columns in physical order with their collation,
 * generated expression, identity, default and NOT NULL; its constraints by
 * name, the primary key included; then the indexes no constraint owns, a
 * partial one with its predicate; tables in name order, the chain's ledger
 * left out, quoted names kept quoted, and another schema's tables never
 * read.
 *
 * Gated on TEST_DATABASE_URL (support.ts).
 */
import pg from "pg";
import { afterEach, beforeEach, describe, expect, it } from "vitest";

import { snapshotPostgresSchema } from "../schema-snapshot.js";
import {
  createTestDatabase,
  testDatabaseAdminUrl,
  type TestDatabase,
} from "./support.js";

describe.skipIf(testDatabaseAdminUrl() === undefined)(
  "snapshotPostgresSchema",
  () => {
    let db: TestDatabase;
    let pool: pg.Pool;

    beforeEach(async () => {
      db = await createTestDatabase();
      pool = new pg.Pool({ connectionString: db.databaseUrl, max: 1 });
    });

    afterEach(async () => {
      await pool.end();
      await db.drop();
    });

    it("prints every table's columns, constraints and free indexes, in a stable order", async () => {
      await pool.query(`
        CREATE SCHEMA printed;
        CREATE TABLE printed.schema_version (version INTEGER PRIMARY KEY);
        CREATE TABLE printed.zeta (
          id TEXT COLLATE "C" PRIMARY KEY,
          seq BIGINT GENERATED BY DEFAULT AS IDENTITY,
          serial BIGINT GENERATED ALWAYS AS IDENTITY,
          state TEXT NOT NULL DEFAULT 'open' CHECK (state IN ('open', 'shut')),
          words TEXT,
          shout TEXT GENERATED ALWAYS AS (upper(words)) STORED,
          "order" INTEGER
        );
        CREATE INDEX zeta_open ON printed.zeta (seq) WHERE state = 'open';
        CREATE TABLE printed.alpha (a INTEGER NOT NULL, b INTEGER, UNIQUE (a, b));
        CREATE TABLE public.elsewhere (x INTEGER);
      `);
      const client = await pool.connect();
      try {
        const printed = await snapshotPostgresSchema(client, "printed");
        expect(printed.split("\n").slice(3).join("\n")).toBe(
          [
            "CREATE TABLE printed.alpha (",
            "  a integer NOT NULL,",
            "  b integer,",
            "  CONSTRAINT alpha_a_b_key UNIQUE (a, b)",
            ");",
            "",
            "CREATE TABLE printed.zeta (",
            '  id text COLLATE "C" NOT NULL,',
            "  seq bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,",
            "  serial bigint GENERATED ALWAYS AS IDENTITY NOT NULL,",
            "  state text DEFAULT 'open'::text NOT NULL,",
            "  words text,",
            "  shout text GENERATED ALWAYS AS (upper(words)) STORED,",
            '  "order" integer,',
            "  CONSTRAINT zeta_pkey PRIMARY KEY (id),",
            "  CONSTRAINT zeta_state_check CHECK (state = ANY (ARRAY['open'::text, 'shut'::text]))",
            ");",
            "CREATE INDEX zeta_open ON printed.zeta USING btree (seq) WHERE (state = 'open'::text);",
            "",
          ].join("\n"),
        );
        expect(printed).not.toContain("schema_version");
        expect(printed).not.toContain("elsewhere");
      } finally {
        client.release();
      }
    });
  },
);
