/**
 * The schema a Postgres chain leaves, printed from the catalogue as SQL a
 * reviewer reads: one CREATE TABLE per table (columns in their physical
 * order, then every constraint by name), then every index that no
 * constraint owns, each table's in name order. A chain's committed
 * `schema.snapshot.sql` is this text for a fresh replay; a test replays the
 * chain and compares, so a schema change reaches review as a diff of the
 * schema itself, not only as the step that makes it.
 *
 * Only the catalogue speaks: the text is what Postgres holds, not what a
 * step's SQL said, so two spellings of one schema print the same. The
 * chain's own ledger (`schema_version`) is left out; the runner owns it.
 * Tables, constraints and indexes are what every chain holds; a step that
 * adds a view, trigger, function or type extends this printer with it.
 */
import type { PoolClient } from "pg";

/** The ledger table every chain keeps in its schema; not part of a snapshot. */
const LEDGER_TABLE = "schema_version";

const HEADER =
  "-- The schema this chain leaves on a fresh database, printed from the catalogue.\n" +
  "-- Generated by `npm run schema:snapshot`; a test compares it with a fresh replay.\n";

/** Prints every table, constraint and index of `schema`, in a stable order. */
export async function snapshotPostgresSchema(
  client: PoolClient,
  schema: string,
): Promise<string> {
  const tables = await client.query<{ name: string; oid: number }>(
    `SELECT quote_ident(c.relname) AS name, c.oid::int AS oid
       FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
      WHERE n.nspname = $1 AND c.relkind IN ('r', 'p') AND c.relname <> $2
      ORDER BY c.relname COLLATE "C"`,
    [schema, LEDGER_TABLE],
  );
  const parts: string[] = [HEADER];
  const quotedSchema = await client.query<{ name: string }>(
    "SELECT quote_ident($1) AS name",
    [schema],
  );
  for (const table of tables.rows) {
    parts.push(
      await tableText(
        client,
        quotedSchema.rows[0]!.name,
        table.name,
        table.oid,
      ),
    );
  }
  return parts.join("\n");
}

async function tableText(
  client: PoolClient,
  schema: string,
  table: string,
  oid: number,
): Promise<string> {
  const columns = await client.query<{
    name: string;
    type: string;
    notnull: boolean;
    def: string | null;
    generated: string;
    identity: string;
    collation: string | null;
  }>(
    `SELECT quote_ident(a.attname) AS name,
            format_type(a.atttypid, a.atttypmod) AS type,
            a.attnotnull AS notnull,
            pg_get_expr(d.adbin, d.adrelid) AS def,
            a.attgenerated AS generated,
            a.attidentity AS identity,
            CASE WHEN a.attcollation <> t.typcollation THEN quote_ident(co.collname) END AS collation
       FROM pg_attribute a
       JOIN pg_type t ON t.oid = a.atttypid
       LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
       LEFT JOIN pg_collation co ON co.oid = a.attcollation
      WHERE a.attrelid = $1 AND a.attnum > 0 AND NOT a.attisdropped
      ORDER BY a.attnum`,
    [oid],
  );
  // Postgres 18 also lists a column's NOT NULL as a constraint (contype
  // 'n'); the column's own line prints it.
  const constraints = await client.query<{ name: string; def: string }>(
    `SELECT quote_ident(conname) AS name, pg_get_constraintdef(oid, true) AS def
       FROM pg_constraint
      WHERE conrelid = $1 AND contype <> 'n'
      ORDER BY conname COLLATE "C"`,
    [oid],
  );
  const indexes = await client.query<{ def: string }>(
    `SELECT pg_get_indexdef(i.indexrelid) AS def
       FROM pg_index i JOIN pg_class c ON c.oid = i.indexrelid
      WHERE i.indrelid = $1
        AND NOT EXISTS (SELECT 1 FROM pg_constraint k WHERE k.conindid = i.indexrelid AND k.conrelid = $1)
      ORDER BY c.relname COLLATE "C"`,
    [oid],
  );

  const lines = columns.rows.map((column) => {
    let line = `  ${column.name} ${column.type}`;
    if (column.collation !== null) {
      line += ` COLLATE ${column.collation}`;
    }
    if (column.generated === "s") {
      line += ` GENERATED ALWAYS AS (${column.def ?? ""}) STORED`;
    } else if (column.identity === "a") {
      line += " GENERATED ALWAYS AS IDENTITY";
    } else if (column.identity === "d") {
      line += " GENERATED BY DEFAULT AS IDENTITY";
    } else if (column.def !== null) {
      line += ` DEFAULT ${column.def}`;
    }
    if (column.notnull) {
      line += " NOT NULL";
    }
    return line;
  });
  for (const constraint of constraints.rows) {
    lines.push(`  CONSTRAINT ${constraint.name} ${constraint.def}`);
  }
  const name = `${schema}.${table}`;
  const out = [`CREATE TABLE ${name} (\n${lines.join(",\n")}\n);`];
  for (const index of indexes.rows) {
    out.push(`${index.def};`);
  }
  return `${out.join("\n")}\n`;
}
