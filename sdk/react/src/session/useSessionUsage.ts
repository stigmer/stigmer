"use client";

/**
 * Session-level token usage and working time, read from the server's session usage report.
 *
 * The report is the one source: the server counts each run from the
 * deployment's meter, or, for a run the meter has not seen, from the run's
 * own runner report, and says so with `is_estimated`. This hook therefore
 * never sums run statuses itself, so the console and the server cannot
 * disagree about which runs count or how. Usage is tokens and calls, never
 * money. While any run is in flight the report is polled, because metered
 * calls and runner reports land during the run; when the last run settles
 * one final fetch picks up its closing numbers. The suite in
 * `__tests__/useSessionUsage.test.ts` pins the mapping, the polling and the
 * final refetch.
 */

import { useCallback, useEffect, useMemo, useRef } from "react";
import { create } from "@bufbuild/protobuf";
import type { Run } from "@stigmer/protos/ai/stigmer/agentic/run/v1/api_pb";
import {
  GetSessionUsageReportInputSchema,
  type GetSessionUsageReportOutput,
} from "@stigmer/protos/ai/stigmer/agentic/run/v1/io_pb";
import type {
  ModelUsage,
  ProviderKeySource,
} from "@stigmer/protos/ai/stigmer/agentic/run/v1/usage_pb";
import { useStigmer } from "../hooks.js";
import { isTerminalPhase } from "../run/run-phases.js";
import { useFetch } from "../internal/useFetch.js";

/** Poll cadence for the session usage report while a run is in flight. */
const ACTIVE_POLL_INTERVAL_MS = 2500;

/** Per-model token breakdown. */
export interface ModelUsageEntry {
  /** Model identifier (e.g. "claude-sonnet-4-6"). */
  readonly model: string;
  /** Provider name (e.g. "anthropic", "cursor"); empty when not known. */
  readonly provider: string;
  /** Total tokens for this model (cache-inclusive). */
  readonly totalTokens: number;
  /** Non-cached input tokens consumed by this model. */
  readonly inputTokens: number;
  /** Output tokens generated by this model. */
  readonly outputTokens: number;
  /** Tokens used to create cache entries. */
  readonly cacheCreationTokens: number;
  /** Tokens served from cache. */
  readonly cacheReadTokens: number;
  /** Number of metered LLM calls to this model (0 for estimated runs). */
  readonly callCount: number;
}

/** Per-run token usage and model provenance (stigmer/stigmer#362). */
export interface RunUsageEntry {
  /** Run identifier (`metadata.id`). */
  readonly runId: string;
  /**
   * The run's primary model — the model with the most tokens. For a
   * metered run it is what the provider actually served, which for a
   * Cursor Auto run answers "which model did Auto pick"; for an estimated
   * run it is the model the runner reported.
   */
  readonly resolvedModel: string;
  /** Total tokens for this run (cache-inclusive). */
  readonly totalTokens: number;
  /** `true` when this run is counted from its runner's own report. */
  readonly isEstimated: boolean;
  /** Seconds an agent worked in the stretches this run started. */
  readonly workingSeconds: number;
}

/** Tokens and calls served by one kind of provider credential. */
export interface ServedByEntry {
  /** Whose credential served the calls; UNSPECIFIED when not known. */
  readonly providerKeySource: ProviderKeySource;
  /** Total tokens served this way. */
  readonly totalTokens: number;
  /** Metered LLM calls served this way. */
  readonly llmCallCount: number;
}

/** Return value of {@link useSessionUsage}. */
export interface UseSessionUsageReturn {
  /** Total tokens across all models (cache-inclusive: input + output + cache). */
  readonly totalTokens: number;
  /** Total non-cached input tokens across all models. */
  readonly inputTokens: number;
  /** Total output tokens across all models. */
  readonly outputTokens: number;
  /** Total tokens served from cache across all models. */
  readonly cacheReadTokens: number;
  /** Total tokens used to create cache entries across all models. */
  readonly cacheCreationTokens: number;
  /** Total number of metered LLM calls in this session. */
  readonly llmCallCount: number;
  /** Seconds an agent worked on this session; waiting for a person is never counted. */
  readonly workingSeconds: number;
  /** Per-model token breakdown, most tokens first. */
  readonly modelBreakdown: readonly ModelUsageEntry[];
  /** Per-run tokens and primary model, chronological. */
  readonly runBreakdown: readonly RunUsageEntry[];
  /** The session's tokens by whose provider credential served them. */
  readonly servedBy: readonly ServedByEntry[];
  /** Model with the most tokens in this session. */
  readonly primaryModel: string;
  /** Provider of the primary model. */
  readonly primaryProvider: string;
  /** `true` when the session has any tokens, calls or working time. */
  readonly hasUsage: boolean;
  /**
   * `true` when any run is counted from its runner's own report rather
   * than the deployment's meter. The UI shows an "Estimated" badge.
   */
  readonly isEstimated: boolean;
}

const EMPTY: UseSessionUsageReturn = {
  totalTokens: 0,
  inputTokens: 0,
  outputTokens: 0,
  cacheReadTokens: 0,
  cacheCreationTokens: 0,
  llmCallCount: 0,
  workingSeconds: 0,
  modelBreakdown: [],
  runBreakdown: [],
  servedBy: [],
  primaryModel: "",
  primaryProvider: "",
  hasUsage: false,
  isEstimated: false,
};

function mapModelUsage(m: ModelUsage): ModelUsageEntry {
  return {
    model: m.model,
    provider: m.provider,
    totalTokens: Number(m.totalTokens),
    inputTokens: Number(m.inputTokens),
    outputTokens: Number(m.outputTokens),
    cacheCreationTokens: Number(m.cacheCreationInputTokens),
    cacheReadTokens: Number(m.cacheReadInputTokens),
    callCount: m.callCount,
  };
}

/** Map the session usage report to the hook's plain-number shape. */
function mapSessionUsageReport(
  report: GetSessionUsageReportOutput,
): UseSessionUsageReturn {
  const agg = report.totalUsage;
  if (!agg) return EMPTY;

  const llmCallCount = agg.llmCallCount;
  const totalTokens = Number(agg.totalTokens);
  const workingSeconds = Number(agg.workingSeconds);

  return {
    totalTokens,
    inputTokens: Number(agg.inputTokens),
    outputTokens: Number(agg.outputTokens),
    cacheReadTokens: Number(agg.cacheReadInputTokens),
    cacheCreationTokens: Number(agg.cacheCreationInputTokens),
    llmCallCount,
    workingSeconds,
    modelBreakdown: report.modelBreakdown.map(mapModelUsage),
    runBreakdown: report.runs.map((r) => ({
      runId: r.runId,
      resolvedModel: r.primaryModel,
      totalTokens: Number(r.totalTokens),
      isEstimated: r.isEstimated,
      workingSeconds: Number(r.workingSeconds),
    })),
    servedBy: agg.servedBy.map((s) => ({
      providerKeySource: s.providerKeySource,
      totalTokens: Number(s.totalTokens),
      llmCallCount: s.llmCallCount,
    })),
    primaryModel: agg.primaryModel,
    primaryProvider: agg.primaryProvider,
    hasUsage: llmCallCount > 0 || totalTokens > 0 || workingSeconds > 0,
    isEstimated: report.isEstimated,
  };
}

/**
 * Usage hook for session-level token aggregation.
 *
 * Reads `getSessionUsageReport` for the session the runs belong to, polling
 * while any run is in flight. Returns zeros with `hasUsage: false` until the
 * report has tokens.
 *
 * @param runs - All runs for a session (completed + active). The session is
 *   taken from the first run's target; the phases decide whether to poll.
 */
export function useSessionUsage(
  runs: readonly Run[],
): UseSessionUsageReturn {
  const stigmer = useStigmer();

  const sessionId = useMemo(
    () => {
      const target = runs[0]?.spec?.target;
      return target?.case === "sessionId" ? target.value : null;
    },
    [runs],
  );

  // Any run still in flight means more usage is coming, so the report must
  // be polled to stay current during the run.
  const hasActiveRun = useMemo(
    () =>
      runs.some((r) => {
        const phase = r.status?.phase;
        return phase !== undefined && !isTerminalPhase(phase);
      }),
    [runs],
  );

  // Stable fetch identity so the poll timer in useFetch is not torn down and
  // recreated on every streaming re-render (which would prevent it firing).
  const fetchReport = useCallback(
    () =>
      stigmer.run.getSessionUsageReport(
        create(GetSessionUsageReportInputSchema, { sessionId: sessionId! }),
      ),
    [sessionId, stigmer],
  );

  const { data: report, refetch } = useFetch(
    sessionId ? fetchReport : null,
    [sessionId, stigmer],
    null as GetSessionUsageReportOutput | null,
    {
      cacheKey: sessionId ? `session-usage:${sessionId}` : undefined,
      refetchInterval: hasActiveRun ? ACTIVE_POLL_INTERVAL_MS : false,
    },
  );

  // When the last run settles, polling stops — do one final fetch so the
  // closing numbers (incl. the final turn) land promptly instead of waiting
  // for a remount.
  const wasActiveRef = useRef(hasActiveRun);
  useEffect(() => {
    if (wasActiveRef.current && !hasActiveRun) {
      refetch();
    }
    wasActiveRef.current = hasActiveRun;
  }, [hasActiveRun, refetch]);

  return useMemo(
    () => (report ? mapSessionUsageReport(report) : EMPTY),
    [report],
  );
}
