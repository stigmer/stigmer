"use client";

import { useMemo } from "react";
import { create } from "@bufbuild/protobuf";
import type { AgentExecution } from "@stigmer/protos/ai/stigmer/agentic/agentexecution/v1/api_pb";
import {
  GetSessionUsageReportInputSchema,
  type GetSessionUsageReportOutput,
} from "@stigmer/protos/ai/stigmer/agentic/agentexecution/v1/io_pb";
import type { ModelUsage, StreamingUsageSummary } from "@stigmer/protos/ai/stigmer/agentic/agentexecution/v1/usage_pb";
import { useStigmer } from "../hooks";
import { useFetch } from "../internal/useFetch";

/**
 * Per-model cost breakdown.
 */
export interface ModelCostEntry {
  /** Model identifier (e.g. "claude-sonnet-4-20250514"). */
  readonly model: string;
  /** Provider name (e.g. "anthropic", "openai"). */
  readonly provider: string;
  /** Estimated cost in USD for this model's usage. */
  readonly estimatedCostUsd: number;
  /** Total input tokens consumed by this model. */
  readonly inputTokens: number;
  /** Total output tokens generated by this model. */
  readonly outputTokens: number;
  /** Tokens used to create cache entries. */
  readonly cacheCreationTokens: number;
  /** Tokens served from cache. */
  readonly cacheReadTokens: number;
  /** Number of LLM calls made to this model. */
  readonly callCount: number;
}

/** Return value of {@link useSessionUsage}. */
export interface UseSessionUsageReturn {
  /** Aggregate estimated cost in USD across all models. */
  readonly totalCostUsd: number;
  /** Total tokens (input + output) across all models. */
  readonly totalTokens: number;
  /** Total input tokens across all models. */
  readonly inputTokens: number;
  /** Total output tokens across all models. */
  readonly outputTokens: number;
  /** Total tokens served from cache across all models. */
  readonly cacheReadTokens: number;
  /** Total tokens used to create cache entries across all models. */
  readonly cacheCreationTokens: number;
  /** Total number of LLM calls in this session. */
  readonly llmCallCount: number;
  /** Per-model cost and token breakdown. */
  readonly modelBreakdown: readonly ModelCostEntry[];
  /** Model with the highest usage in this session. */
  readonly primaryModel: string;
  /** Provider of the primary model. */
  readonly primaryProvider: string;
  /** `true` when usage data is available. */
  readonly hasUsage: boolean;
}

const EMPTY: UseSessionUsageReturn = {
  totalCostUsd: 0,
  totalTokens: 0,
  inputTokens: 0,
  outputTokens: 0,
  cacheReadTokens: 0,
  cacheCreationTokens: 0,
  llmCallCount: 0,
  modelBreakdown: [],
  primaryModel: "",
  primaryProvider: "",
  hasUsage: false,
};

function microsToUsd(micros: bigint): number {
  return Number(micros) / 1_000_000;
}

function mapModelUsage(m: ModelUsage): ModelCostEntry {
  return {
    model: m.model,
    provider: m.provider,
    estimatedCostUsd: microsToUsd(m.billableCostMicros),
    inputTokens: Number(m.inputTokens),
    outputTokens: Number(m.outputTokens),
    cacheCreationTokens: Number(m.cacheCreationInputTokens),
    cacheReadTokens: Number(m.cacheReadInputTokens),
    callCount: m.callCount,
  };
}

function mapReport(report: GetSessionUsageReportOutput): UseSessionUsageReturn {
  const agg = report.totalUsage;
  if (!agg) return EMPTY;

  const llmCallCount = agg.llmCallCount;
  const totalTokens = Number(agg.totalTokens);
  const billableCost = microsToUsd(agg.billableCostMicros);

  return {
    totalCostUsd: billableCost,
    totalTokens,
    inputTokens: Number(agg.inputTokens),
    outputTokens: Number(agg.outputTokens),
    cacheReadTokens: Number(agg.cacheReadInputTokens),
    cacheCreationTokens: Number(agg.cacheCreationInputTokens),
    llmCallCount,
    modelBreakdown: report.modelBreakdown.map(mapModelUsage),
    primaryModel: agg.primaryModel,
    primaryProvider: agg.primaryProvider,
    hasUsage: llmCallCount > 0 || totalTokens > 0 || billableCost > 0,
  };
}

/**
 * Aggregate streaming-reported usage from execution status objects.
 * Used as a fallback when the server-side session usage report is empty
 * (e.g., Cursor harness where the proxy does not capture main agent turns).
 */
function aggregateStreamingUsage(
  executions: readonly AgentExecution[],
): UseSessionUsageReturn {
  let inputTokens = 0;
  let outputTokens = 0;
  let cacheReadTokens = 0;
  let cacheCreationTokens = 0;
  let totalTokens = 0;
  let turnCount = 0;
  let estimatedCost = 0;
  let model = "";

  for (const exec of executions) {
    const ru = exec.status?.streamingUsage;
    if (!ru || ru.turnCount === 0) continue;
    inputTokens += Number(ru.inputTokens);
    outputTokens += Number(ru.outputTokens);
    cacheReadTokens += Number(ru.cacheReadTokens);
    cacheCreationTokens += Number(ru.cacheWriteTokens);
    totalTokens += Number(ru.totalTokens);
    turnCount += ru.turnCount;
    estimatedCost += ru.estimatedCostUsd;
    if (!model && ru.model) model = ru.model;
  }

  if (turnCount === 0) return EMPTY;

  return {
    totalCostUsd: estimatedCost,
    totalTokens,
    inputTokens,
    outputTokens,
    cacheReadTokens,
    cacheCreationTokens,
    llmCallCount: turnCount,
    modelBreakdown: model
      ? [
          {
            model,
            provider: "cursor",
            estimatedCostUsd: estimatedCost,
            inputTokens,
            outputTokens,
            cacheCreationTokens,
            cacheReadTokens,
            callCount: turnCount,
          },
        ]
      : [],
    primaryModel: model,
    primaryProvider: model ? "cursor" : "",
    hasUsage: true,
  };
}

/**
 * Merge billing-authoritative data with live streaming data.
 *
 * Billing is the source of truth for settled costs (completed executions).
 * Streaming supplements it with live token/cost accrual from in-flight
 * executions whose billing records have not yet been written.
 */
function mergeWithStreaming(
  billing: UseSessionUsageReturn,
  streaming: UseSessionUsageReturn,
): UseSessionUsageReturn {
  if (!streaming.hasUsage) return billing;

  const billingTokens = billing.totalTokens;
  const streamingTokens = streaming.totalTokens;

  if (streamingTokens <= billingTokens) return billing;

  const extraTokens = streamingTokens - billingTokens;
  const extraCost = streaming.totalCostUsd - billing.totalCostUsd;

  if (extraTokens <= 0 && extraCost <= 0) return billing;

  const mergedBreakdown = [...billing.modelBreakdown];
  for (const streamEntry of streaming.modelBreakdown) {
    const existsInBilling = mergedBreakdown.some(
      (b) => b.model === streamEntry.model && b.provider === streamEntry.provider,
    );
    if (!existsInBilling) {
      mergedBreakdown.push(streamEntry);
    }
  }

  return {
    totalCostUsd: Math.max(billing.totalCostUsd, streaming.totalCostUsd),
    totalTokens: Math.max(billingTokens, streamingTokens),
    inputTokens: Math.max(billing.inputTokens, streaming.inputTokens),
    outputTokens: Math.max(billing.outputTokens, streaming.outputTokens),
    cacheReadTokens: Math.max(billing.cacheReadTokens, streaming.cacheReadTokens),
    cacheCreationTokens: Math.max(billing.cacheCreationTokens, streaming.cacheCreationTokens),
    llmCallCount: Math.max(billing.llmCallCount, streaming.llmCallCount),
    modelBreakdown: mergedBreakdown,
    primaryModel: billing.primaryModel || streaming.primaryModel,
    primaryProvider: billing.primaryProvider || streaming.primaryProvider,
    hasUsage: true,
  };
}

/**
 * Usage hook for session-level cost and token aggregation.
 *
 * Merges two data sources:
 * - Server-side billing report (authoritative, from LlmCallUsageRecord)
 * - Streaming usage from execution status (live, DISPLAY_ONLY trust)
 *
 * Billing takes precedence for settled costs. Streaming supplements with
 * live token/cost accrual from in-flight executions (especially Cursor
 * harness where billing records are written post-execution).
 *
 * @param executions - All executions for a session (completed + active).
 */
export function useSessionUsage(
  executions: readonly AgentExecution[],
): UseSessionUsageReturn {
  const stigmer = useStigmer();

  const sessionId = useMemo(
    () => executions[0]?.spec?.sessionId ?? null,
    [executions],
  );

  const { data: report } = useFetch(
    sessionId
      ? () =>
          stigmer.agentExecution.getSessionUsageReport(
            create(GetSessionUsageReportInputSchema, { sessionId }),
          )
      : null,
    [sessionId, stigmer],
    null as GetSessionUsageReportOutput | null,
    { cacheKey: sessionId ? `session-usage:${sessionId}` : undefined },
  );

  const streamingFallback = useMemo(
    () => aggregateStreamingUsage(executions),
    [executions],
  );

  return useMemo(() => {
    const billingReport = report ? mapReport(report) : EMPTY;

    if (billingReport.hasUsage && billingReport.llmCallCount > 0) {
      return mergeWithStreaming(billingReport, streamingFallback);
    }

    if (streamingFallback.hasUsage) return streamingFallback;

    return billingReport.hasUsage ? billingReport : EMPTY;
  }, [report, streamingFallback]);
}
