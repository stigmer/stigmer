"use client";

import type { Session } from "@stigmer/apis/ai/stigmer/agentic/session/v1/api_pb";
import { useStigmer } from "../hooks.js";
import { useFetch } from "../internal/useFetch.js";

/** Return value of {@link useSession}. */
export interface UseSessionReturn {
  /** The fetched Session, or `null` while loading or on error. */
  readonly session: Session | null;
  /** `true` while the initial fetch is in flight. */
  readonly isLoading: boolean;
  /** `true` while a background refetch is in flight. */
  readonly isRefetching: boolean;
  /** Error from the last failed request, or `null` when healthy. */
  readonly error: Error | null;
  /** Discard cached data and re-fetch the session from the server. */
  readonly refetch: () => void;
}

/**
 * Data hook that fetches a single Session by ID.
 *
 * Pass `null` to skip fetching (stable no-op). When the `id` changes,
 * the previous in-flight request is discarded and a fresh fetch begins.
 *
 * Call `refetch()` to re-query after the backend has modified the
 * session (e.g., after a run completes or the subject is
 * generated by the LLM).
 *
 * Returns the full proto {@link Session} resource so consumers have
 * access to metadata, spec, and status without additional calls.
 *
 * @example
 * ```tsx
 * function SessionTitle({ sessionId }: { sessionId: string }) {
 *   const { session, isLoading, error, refetch } = useSession(sessionId);
 *   if (isLoading) return <p>Loading…</p>;
 *   if (error) return <p role="alert">{error.message}</p>;
 *   if (!session) return <p>No such conversation.</p>;
 *   return (
 *     <header>
 *       <h1>{session.spec?.subject || "Untitled conversation"}</h1>
 *       <button onClick={refetch}>Refresh</button>
 *     </header>
 *   );
 * }
 * ```
 *
 * @example
 * ```tsx
 * // Skip fetching until a conversation is selected.
 * function Selected({ sessionId }: { sessionId?: string }) {
 *   const { session } = useSession(sessionId ?? null);
 *   return session ? <h2>{session.spec?.subject}</h2> : <p>Pick a conversation.</p>;
 * }
 * ```
 */
export function useSession(id: string | null): UseSessionReturn {
  const stigmer = useStigmer();

  const { data: session, isLoading, isRefetching, error, refetch } = useFetch(
    id ? () => stigmer.session.get(id) : null,
    [id, stigmer],
    null as Session | null,
    { cacheKey: id ? `session:${id}` : undefined },
  );

  return { session, isLoading, isRefetching, error, refetch };
}
