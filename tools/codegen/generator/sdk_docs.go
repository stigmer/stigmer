func docWriteTab(buf *bytes.Buffer, lang, syntax, code string) {
	fmt.Fprintf(buf, "<Tab value=\"%s\">\n%s%s\n%s\n%s\n</Tab>\n", lang, mdFence, syntax, code, mdFence)
}

