func taskDocsWriteOutputSchema(buf *bytes.Buffer, schema map[string]interface{}) {
	data, err := json.MarshalIndent(schema, "", "  ")
	if err != nil {
		buf.WriteString("_Output schema could not be rendered._\n\n")
		return
	}
	buf.WriteString("```json\n")
	buf.Write(data)
	buf.WriteString("\n```\n\n")
}

// =========================================================================
// Index page generation
// =========================================================================

func taskDocsGenerateIndex(schemas []*TaskConfigSchema, sidecars map[string]*SidecarMeta) []byte {
	var buf bytes.Buffer

	buf.WriteString("---\ntitle: Task Type Reference\ndescription: \"Auto-generated field-level reference for all 20 workflow task types.\"\n---\n\n")
	buf.WriteString("{/* Auto-generated by stigmer-codegen. DO NOT EDIT. */}\n\n")
	buf.WriteString("This section provides exhaustive field-level reference for every workflow task type.\n")
	buf.WriteString("For narrative guidance on when and how to use each task, see the [Task Type Overview](/docs/guides/workflows/task-types).\n\n")

	// Group schemas by category.
	byCategory := make(map[string][]*TaskConfigSchema)
	for _, schema := range schemas {
		kind := taskDocsKindString(schema)
		cat := "unspecified"
		if meta, ok := sidecars[kind]; ok {
			cat = meta.Category
		}
		byCategory[cat] = append(byCategory[cat], schema)
	}

	for _, cm := range taskDocsCategoryOrder {
		group := byCategory[cm.id]
		if len(group) == 0 {
			continue
		}

		fmt.Fprintf(&buf, "## %s\n\n", cm.displayName)
		buf.WriteString(cm.description)
		buf.WriteString("\n\n")

		buf.WriteString("<Cards>\n")
		for _, schema := range group {
			kind := taskDocsKindString(schema)
			slug := taskDocsSlug(kind)
			displayName := toDisplayName(kind)
			desc := ""
			if meta, ok := sidecars[kind]; ok {
				displayName = meta.DisplayName
				desc = meta.Description
			}
			fmt.Fprintf(&buf, "  <Card\n    title=\"%s\"\n    description=\"%s\"\n    href=\"/docs/guides/workflows/task-types/%s\"\n  />\n",
				displayName, docEscapeJSString(desc), slug)
		}
		buf.WriteString("</Cards>\n\n")
	}

	// Handle any uncategorized tasks.
	if uncategorized := byCategory["unspecified"]; len(uncategorized) > 0 {
		buf.WriteString("## Other\n\n")
		buf.WriteString("<Cards>\n")
		for _, schema := range uncategorized {
			kind := taskDocsKindString(schema)
			slug := taskDocsSlug(kind)
			displayName := toDisplayName(kind)
			fmt.Fprintf(&buf, "  <Card\n    title=\"%s\"\n    href=\"/docs/guides/workflows/task-types/%s\"\n  />\n",
				displayName, slug)
		}
		buf.WriteString("</Cards>\n\n")
	}

	return buf.Bytes()
}

// =========================================================================
// Navigation metadata
// =========================================================================

func taskDocsWriteMetaJSON(outputDir string, pages []string) error {
	meta := struct {
		Title string   `json:"title"`
		Pages []string `json:"pages"`
	}{
		Title: "Task Reference",
		Pages: pages,
	}
	data, err := json.MarshalIndent(meta, "", "  ")
	if err != nil {
		return err
	}
	data = append(data, '\n')
	return os.WriteFile(filepath.Join(outputDir, "meta.json"), data, 0644)
}

// =========================================================================
// Helpers
// =========================================================================

func taskDocsKindString(schema *TaskConfigSchema) string {
	if schema.DiscriminatorValue != "" {
		return schema.DiscriminatorValue
	}
	return strings.ToLower(schema.Kind)
}

func taskDocsSlug(kind string) string {
	return strings.ReplaceAll(kind, "_", "-")
}
