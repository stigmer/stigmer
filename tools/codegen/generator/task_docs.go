// taskDocsCategoryCardsMarker is the insertion point in the enrichment
// template where the generated per-category card grid is injected, following
// the {/* AUTO_* */} convention from client-apps/cli/scripts/gen-cli-docs.ts.
const taskDocsCategoryCardsMarker = "{/* AUTO_TASK_CATEGORY_CARDS */}"

// taskDocsOverviewPath derives the path to the hand-written enrichment
// template for the task-types index page, mirroring docOverviewFilePath's
// role for sdk-docs.
func taskDocsOverviewPath(apisDir string) string {
	return filepath.Join(apisDir, "ai", "stigmer", "agentic", "workflow", "v1", "tasks", "docs", "overview.mdx")
}

// taskDocsGenerateIndex emits the task-types index page: the hand-written
// enrichment prose with the generated per-category card grid injected at the
// AUTO_TASK_CATEGORY_CARDS marker. Cross-task prose lives in the enrichment;
// everything per-task comes from the sidecars, so a new task kind appears on
// the index without a hand edit.
//
// Fails loudly — rather than degrading the page — when the enrichment file or
// its marker is missing, or when any task's category is not declared in
// taskDocsCategoryOrder (exact-partition contract; no silent "Other" bucket).
func taskDocsGenerateIndex(schemas []*TaskConfigSchema, sidecars map[string]*SidecarMeta, overviewPath string) ([]byte, error) {
	enrichment, err := os.ReadFile(overviewPath)
	if err != nil {
		return nil, fmt.Errorf("index enrichment template is required: %w", err)
	}
	if !bytes.Contains(enrichment, []byte(taskDocsCategoryCardsMarker)) {
		return nil, fmt.Errorf("enrichment template %s is missing the %s marker", overviewPath, taskDocsCategoryCardsMarker)
	}

	// Group schemas by category, failing on anything outside the declared set.
	known := make(map[string]bool, len(taskDocsCategoryOrder))
	for _, cm := range taskDocsCategoryOrder {
		known[cm.id] = true
	}
	byCategory := make(map[string][]*TaskConfigSchema)
	for _, schema := range schemas {
		kind := taskDocsKindString(schema)
		meta := sidecars[kind]
		if meta == nil || meta.Category == "" {
			return nil, fmt.Errorf("task %q has no category in its sidecar metadata", kind)
		}
		if !known[meta.Category] {
			return nil, fmt.Errorf("task %q has category %q, which is not declared in taskDocsCategoryOrder", kind, meta.Category)
		}
		byCategory[meta.Category] = append(byCategory[meta.Category], schema)
	}

	var cards bytes.Buffer
	for _, cm := range taskDocsCategoryOrder {
		group := byCategory[cm.id]
		if len(group) == 0 {
			continue
		}

		fmt.Fprintf(&cards, "## %s\n\n", cm.displayName)
		cards.WriteString(cm.description)
		cards.WriteString("\n\n")

		cards.WriteString("<Cards>\n")
		for _, schema := range group {
			kind := taskDocsKindString(schema)
			meta := sidecars[kind]
			fmt.Fprintf(&cards, "  <Card\n    title=\"%s\"\n    description=\"%s\"\n    href=\"/docs/guides/workflows/task-types/%s\"\n  />\n",
				meta.DisplayName, docEscapeJSString(meta.Description), taskDocsSlug(kind))
		}
		cards.WriteString("</Cards>\n\n")
	}

	page := bytes.Replace(enrichment, []byte(taskDocsCategoryCardsMarker), bytes.TrimRight(cards.Bytes(), "\n"), 1)

	// Insert the generated-file notice after the frontmatter so readers land
	// on the enrichment source, not this output, when they want to edit prose.
	notice := []byte("\n{/* Autogenerated by stigmer-codegen. DO NOT EDIT. */}\n{/* To edit the prose on this page, edit " + taskDocsOverviewPathForComment + " */}\n")
	end := bytes.Index(page[3:], []byte("\n---\n"))
	if !bytes.HasPrefix(page, []byte("---\n")) || end < 0 {
		return nil, fmt.Errorf("enrichment template %s must start with YAML frontmatter", overviewPath)
	}
	insertAt := 3 + end + len("\n---\n")
	var out bytes.Buffer
	out.Write(page[:insertAt])
	out.Write(notice)
	out.Write(page[insertAt:])
	return out.Bytes(), nil
}

// taskDocsOverviewPathForComment is the repo-relative enrichment path named in
// the generated index's pointer comment.
const taskDocsOverviewPathForComment = "apis/ai/stigmer/agentic/workflow/v1/tasks/docs/overview.mdx"

// =========================================================================
// Navigation metadata
// =========================================================================

func taskDocsWriteMetaJSON(outputDir string, pages []string) error {
	meta := struct {
		Title string   `json:"title"`
		Pages []string `json:"pages"`
	}{
		Title: "Task Types",
		Pages: pages,
	}
	data, err := json.MarshalIndent(meta, "", "  ")
	if err != nil {
		return err
	}
	data = append(data, '\n')
	return os.WriteFile(filepath.Join(outputDir, "meta.json"), data, 0644)
}

// =========================================================================
// Helpers
// =========================================================================

func taskDocsKindString(schema *TaskConfigSchema) string {
	if schema.DiscriminatorValue != "" {
		return schema.DiscriminatorValue
	}
	return strings.ToLower(schema.Kind)
}

func taskDocsSlug(kind string) string {
	return strings.ReplaceAll(kind, "_", "-")
}
