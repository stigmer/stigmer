// categoryMeta holds presentation metadata for a task category.
type categoryMeta struct {
	id          string
	displayName string
	description string
}

// taskDocsCategoryOrder defines the display order and labels for categories.
var taskDocsCategoryOrder = []categoryMeta{
	{id: "ai", displayName: "AI", description: "LLM inference, agent invocation, and LLM-as-judge evaluation."},
	{id: "control_flow", displayName: "Control Flow", description: "Branching, loops, parallelism, and error handling."},
	{id: "data", displayName: "Data", description: "Variables, data transformation, and schema validation."},
	{id: "governance", displayName: "Governance", description: "Human-in-the-loop approvals, notifications, and quality gates."},
	{id: "invocation", displayName: "External Invocation", description: "HTTP, gRPC, and Temporal activity calls, plus sub-workflow runs."},
	{id: "event", displayName: "Events", description: "Signal handling, event emission, notifications, and raised errors."},
}

func runTaskDocsGeneration(schemaDir, outputDir, metaDir, apisDir string) error {
	tasksSchemaDir := filepath.Join(schemaDir, "tasks")
	typesDir := filepath.Join(tasksSchemaDir, "types")

	fmt.Printf("Task Docs Generation\n")
	fmt.Printf("  Schema dir: %s\n", tasksSchemaDir)
	fmt.Printf("  Meta dir:   %s\n", metaDir)
	fmt.Printf("  Output dir: %s\n\n", outputDir)

	schemas, err := loadTaskSchemas(tasksSchemaDir)
	if err != nil {
		return fmt.Errorf("loading task schemas: %w", err)
	}
	fmt.Printf("  Loaded %d task schemas\n", len(schemas))

	sharedTypes, err := loadSharedTypes(typesDir)
	if err != nil {
		fmt.Printf("  Warning: could not load shared types: %v\n", err)
		sharedTypes = make(map[string]*TypeSchema)
	}
	fmt.Printf("  Loaded %d shared types\n", len(sharedTypes))

	sidecars, err := loadSidecarMetadata(metaDir)
	if err != nil {
		return fmt.Errorf("loading sidecar metadata: %w", err)
	}
	fmt.Printf("  Loaded %d sidecar metadata files\n\n", len(sidecars))

	if err := validateSidecarExamples(schemas, sidecars); err != nil {
		return err
	}

	if err := os.MkdirAll(outputDir, 0755); err != nil {
		return fmt.Errorf("creating output dir: %w", err)
	}

	// Sort schemas by kindOrder for deterministic output.
	sort.Slice(schemas, func(i, j int) bool {
		ki := taskDocsKindString(schemas[i])
		kj := taskDocsKindString(schemas[j])
		return kindOrder(ki) < kindOrder(kj)
	})

	var slugs []string

	for _, schema := range schemas {
		kind := taskDocsKindString(schema)
		meta := sidecars[kind]

		page := taskDocsGeneratePage(schema, meta, sharedTypes)
		slug := taskDocsSlug(kind)
		outPath := filepath.Join(outputDir, slug+".mdx")
		if err := os.WriteFile(outPath, page, 0644); err != nil {
			return fmt.Errorf("writing %s: %w", outPath, err)
		}
		fmt.Printf("  -> %s.mdx\n", slug)
		slugs = append(slugs, slug)
	}

	// Generate the index page from the hand-written enrichment template.
	index, err := taskDocsGenerateIndex(schemas, sidecars, taskDocsOverviewPath(apisDir))
	if err != nil {
		return fmt.Errorf("generating index.mdx: %w", err)
	}
	if err := os.WriteFile(filepath.Join(outputDir, "index.mdx"), index, 0644); err != nil {
		return fmt.Errorf("writing index.mdx: %w", err)
	}
	fmt.Printf("  -> index.mdx\n")

	// Generate meta.json for navigation. "index" is deliberately NOT listed:
	// an explicitly-listed index turns the folder into an unlinked label,
	// while omitting it lets Fumadocs' setIndexIfUnused keep the folder URL
	// a real, clickable page (see site/src/lib/__tests__/breadcrumb.test.ts).
	if err := taskDocsWriteMetaJSON(outputDir, slugs); err != nil {
		return fmt.Errorf("writing meta.json: %w", err)
	}
	fmt.Printf("  -> meta.json\n")

	return nil
}

// =========================================================================
// Per-task page generation
// =========================================================================

func taskDocsGeneratePage(schema *TaskConfigSchema, meta *SidecarMeta, sharedTypes map[string]*TypeSchema) []byte {
	var buf bytes.Buffer
	kind := taskDocsKindString(schema)

	displayName := toDisplayName(kind)
	description := ""
	if meta != nil {
		displayName = meta.DisplayName
		description = meta.Description
	}
	if description == "" {
		description = docFirstSentence(schema.Description)
	}

	// Frontmatter.
	fmt.Fprintf(&buf, "---\ntitle: %s\ndescription: \"%s\"\n---\n\n", displayName, docEscapeJSString(description))
	buf.WriteString("{/* Autogenerated by stigmer-codegen. DO NOT EDIT. */}\n\n")

	// Overview section.
	overview := docSDKContent(schema.Description)
	if overview != "" {
		buf.WriteString(docEscapeMDX(overview))
		buf.WriteString("\n\n")
	}

	// Kind section.
	buf.WriteString("## Kind\n\n")
	fmt.Fprintf(&buf, "`%s`\n\n", kind)

	// YAML examples.
	if meta != nil && len(meta.YamlExamples) > 0 {
		if len(meta.YamlExamples) == 1 {
			buf.WriteString("## YAML Example\n\n")
		} else {
			buf.WriteString("## YAML Examples\n\n")
		}
		for _, example := range meta.YamlExamples {
			buf.WriteString("```yaml\n")
			buf.WriteString(strings.TrimRight(example, "\n"))
			buf.WriteString("\n```\n\n")
		}
	}

	// Collect documented types for cross-linking.
	documentedTypes := make(map[string]bool)
	for _, f := range schema.Fields {
		taskDocsCollectNestedTypeNames(f, sharedTypes, documentedTypes)
	}

	// Collect enums for cross-linking.
	var enumSpecs []taskDocsEnumSpec
	enumVisited := make(map[string]bool)
	for _, f := range schema.Fields {
		taskDocsCollectEnums(f, sharedTypes, &enumSpecs, documentedTypes, enumVisited)
	}

	// task_config fields.
	buf.WriteString("## task\\_config Fields\n\n")
	buf.WriteString("<TypeTable\n  type={{\n")
	for _, f := range schema.Fields {
		taskDocsWriteField(&buf, f, documentedTypes)
	}
	buf.WriteString("  }}\n/>\n\n")

	// Nested types.
	emitted := make(map[string]bool)
	hasNestedTypes := false
	for _, f := range schema.Fields {
		if taskDocsHasNestedType(f) {
			hasNestedTypes = true
			break
		}
	}
	if hasNestedTypes {
		buf.WriteString("## Nested Types\n\n")
		for _, f := range schema.Fields {
			taskDocsWriteNestedType(&buf, f, sharedTypes, emitted, documentedTypes)
		}
	}

	// Enums.
	if len(enumSpecs) > 0 {
		buf.WriteString("## Enums\n\n")
		for _, es := range enumSpecs {
			if emitted[es.name] {
				continue
			}
			emitted[es.name] = true
			fmt.Fprintf(&buf, "### %s\n\n", es.name)
			buf.WriteString("| Value | Description |\n")
			buf.WriteString("|-------|-------------|\n")
			for _, v := range es.values {
				fmt.Fprintf(&buf, "| `%s` | |\n", v)
			}
			buf.WriteString("\n")
		}
	}

	// Output shape.
	if meta != nil && meta.OutputSchema != nil {
		buf.WriteString("## Output Shape\n\n")
		taskDocsWriteOutputSchema(&buf, meta.OutputSchema)
	}

	// See also.
	buf.WriteString("## See Also\n\n")
	buf.WriteString("- [Workflow Authoring Guide](/docs/guides/workflows/authoring)\n")
	buf.WriteString("- [Task Type Overview](/docs/guides/workflows/task-types)\n")
	buf.WriteString("- [Workflow Patterns](/docs/guides/workflows/patterns)\n")

	return buf.Bytes()
}

// =========================================================================
// Field rendering
// =========================================================================

func taskDocsWriteField(buf *bytes.Buffer, f *FieldSchema, documentedTypes map[string]bool) {
	fieldName := f.ProtoField
	fieldType := taskDocsTypeString(&f.Type)
	desc := docEscapeJSString(docFirstSentence(f.Description))

	link := taskDocsFieldTypeLink(&f.Type, documentedTypes)

	var props []string
	props = append(props, fmt.Sprintf("type: \"%s\"", fieldType))
	props = append(props, fmt.Sprintf("description: \"%s\"", desc))
	if link != "" {
		props = append(props, fmt.Sprintf("typeDescriptionLink: \"%s\"", link))
	}
	if f.Required {
		props = append(props, "required: true")
	}
	fmt.Fprintf(buf, "    %s: { %s },\n", fieldName, strings.Join(props, ", "))
}

// =========================================================================
// Nested type rendering
// =========================================================================

func taskDocsHasNestedType(f *FieldSchema) bool {
	switch {
	case f.Type.Kind == "message":
		return true
	case f.Type.Kind == "array" && f.Type.ElementType != nil && f.Type.ElementType.Kind == "message":
		return true
	default:
		return false
	}
}

func taskDocsWriteNestedType(buf *bytes.Buffer, f *FieldSchema, typeMap map[string]*TypeSchema, emitted map[string]bool, documentedTypes map[string]bool) {
	var msgName string
	switch {
	case f.Type.Kind == "message":
		msgName = f.Type.MessageType
	case f.Type.Kind == "array" && f.Type.ElementType != nil && f.Type.ElementType.Kind == "message":
		msgName = f.Type.ElementType.MessageType
	default:
		return
	}

	if emitted[msgName] || msgName == "" {
		return
	}
	ts, ok := typeMap[msgName]
	if !ok {
		return
	}
	emitted[msgName] = true

	fmt.Fprintf(buf, "### %s\n\n", msgName)

	if ts.Description != "" {
		content := docFirstSentence(ts.Description)
		if content != "" {
			buf.WriteString(docEscapeMDX(content))
			buf.WriteString("\n\n")
		}
	}

	if len(ts.Fields) > 0 {
		buf.WriteString("<TypeTable\n  type={{\n")
		for _, field := range ts.Fields {
			taskDocsWriteField(buf, field, documentedTypes)
		}
		buf.WriteString("  }}\n/>\n\n")
	}

	// Recurse into nested types of this type.
	for _, field := range ts.Fields {
		taskDocsWriteNestedType(buf, field, typeMap, emitted, documentedTypes)
	}
}

func taskDocsCollectNestedTypeNames(f *FieldSchema, typeMap map[string]*TypeSchema, set map[string]bool) {
	var msgName string
	switch {
	case f.Type.Kind == "message":
		msgName = f.Type.MessageType
	case f.Type.Kind == "array" && f.Type.ElementType != nil && f.Type.ElementType.Kind == "message":
		msgName = f.Type.ElementType.MessageType
	default:
		return
	}

	if set[msgName] || msgName == "" {
		return
	}
	ts, ok := typeMap[msgName]
	if !ok {
		return
	}
	set[msgName] = true

	for _, field := range ts.Fields {
		taskDocsCollectNestedTypeNames(field, typeMap, set)
	}
}

// =========================================================================
// Enum collection
// =========================================================================

type taskDocsEnumSpec struct {
	name   string
	values []string
}

func taskDocsCollectEnums(f *FieldSchema, typeMap map[string]*TypeSchema, out *[]taskDocsEnumSpec, documentedTypes map[string]bool, visited map[string]bool) {
	if f.Type.EnumType != "" && len(f.Type.EnumValues) > 0 {
		name := taskDocsEnumShortName(f.Type.EnumType)
		documentedTypes[name] = true
		var values []string
		for _, v := range f.Type.EnumValues {
			if !strings.HasSuffix(v, "_UNSPECIFIED") {
				values = append(values, v)
			}
		}
		*out = append(*out, taskDocsEnumSpec{name: name, values: values})
	}

	var msgName string
	switch {
	case f.Type.Kind == "message":
		msgName = f.Type.MessageType
	case f.Type.Kind == "array" && f.Type.ElementType != nil && f.Type.ElementType.Kind == "message":
		msgName = f.Type.ElementType.MessageType
	}
	if msgName == "" || visited[msgName] {
		return
	}
	visited[msgName] = true
	ts, ok := typeMap[msgName]
	if !ok {
		return
	}
	for _, field := range ts.Fields {
		taskDocsCollectEnums(field, typeMap, out, documentedTypes, visited)
	}
}

func taskDocsEnumShortName(fqn string) string {
	parts := strings.Split(fqn, ".")
	return parts[len(parts)-1]
}

// =========================================================================
// Type formatting
// =========================================================================

func taskDocsTypeString(ts *TypeSpec) string {
	switch ts.Kind {
	case "string":
		if ts.EnumType != "" {
			return taskDocsEnumShortName(ts.EnumType)
		}
		return "string"
	case "int32", "uint32", "int64":
		return "number"
	case "float", "double":
		return "number"
	case "bool":
		return "boolean"
	case "struct":
		return "object"
	case "value":
		return "any"
	case "map":
		key := "string"
		val := "string"
		if ts.KeyType != nil {
			key = taskDocsTypeString(ts.KeyType)
		}
		if ts.ValueType != nil {
			val = taskDocsTypeString(ts.ValueType)
		}
		return fmt.Sprintf("Record<%s, %s>", key, val)
	case "array":
		if ts.ElementType != nil {
			return taskDocsTypeString(ts.ElementType) + "[]"
		}
		return "string[]"
	case "message":
		return ts.MessageType
	case "timestamp":
		return "string"
	case "bytes":
		return "Uint8Array"
	default:
		return "string"
	}
}

func taskDocsFieldTypeLink(ts *TypeSpec, documentedTypes map[string]bool) string {
	// Check enum first.
	if ts.EnumType != "" {
		name := taskDocsEnumShortName(ts.EnumType)
		if documentedTypes[name] {
			return "#" + strings.ToLower(name)
		}
		return ""
	}

	var msgName string
	switch {
	case ts.Kind == "message":
		msgName = ts.MessageType
	case ts.Kind == "array" && ts.ElementType != nil && ts.ElementType.Kind == "message":
		msgName = ts.ElementType.MessageType
	default:
		return ""
	}

	if documentedTypes[msgName] {
		return "#" + strings.ToLower(msgName)
	}
	return ""
}

