package main

import (
	"bytes"
	"fmt"
	"os"
	"path/filepath"
	"sort"

	apiresourcekind "github.com/stigmer/stigmer/apis/stubs/go/ai/stigmer/commons/apiresource/apiresourcekind"
	iamv1 "github.com/stigmer/stigmer/apis/stubs/go/ai/stigmer/iam/v1"
	"google.golang.org/protobuf/proto"
)

type kindMetaEntry struct {
	enumName       string
	enumNumber     int32
	tier           apiresourcekind.ResourceTier
	grantableRoles []iamv1.IamRole
}

// extractKindMetaEntries reads the kind_meta extension from every
// ApiResourceKind enum value in the compiled Go proto stubs.
func extractKindMetaEntries() []kindMetaEntry {
	var entries []kindMetaEntry

	enumDesc := apiresourcekind.ApiResourceKind(0).Descriptor()
	values := enumDesc.Values()
	for i := 0; i < values.Len(); i++ {
		val := values.Get(i)
		if val.Number() == 0 {
			continue
		}
		opts := val.Options()
		if opts == nil {
			continue
		}
		if !proto.HasExtension(opts, apiresourcekind.E_KindMeta) {
			continue
		}
		meta, ok := proto.GetExtension(opts, apiresourcekind.E_KindMeta).(*apiresourcekind.ApiResourceKindMeta)
		if !ok || meta == nil {
			continue
		}

		var roles []iamv1.IamRole
		if auth := meta.GetAuthorization(); auth != nil {
			roles = auth.GetGrantableRoles()
		}

		entries = append(entries, kindMetaEntry{
			enumName:       string(val.Name()),
			enumNumber:     int32(val.Number()),
			tier:           meta.GetTier(),
			grantableRoles: roles,
		})
	}

	sort.Slice(entries, func(i, j int) bool {
		return entries[i].enumNumber < entries[j].enumNumber
	})

	return entries
}

// generateTSKindMeta emits TypeScript files derived from ApiResourceKind
// kind_meta options: resource availability (tier) and authorization config
// (grantable_roles). Called as part of runSDKClientTSGeneration.
func generateTSKindMeta(outputDir string) error {
	entries := extractKindMetaEntries()

	if err := generateTSResourceAvailability(outputDir, entries); err != nil {
		return fmt.Errorf("failed to generate resource-availability.ts: %w", err)
	}
	fmt.Printf("   -> resource-availability.ts\n")

	if err := generateTSAuthorizationConfig(outputDir, entries); err != nil {
		return fmt.Errorf("failed to generate authorization-config.ts: %w", err)
	}
	fmt.Printf("   -> authorization-config.ts\n")

	return nil
}

func generateTSResourceAvailability(outputDir string, entries []kindMetaEntry) error {
	var buf bytes.Buffer

	buf.WriteString("// Code generated by stigmer-codegen from api_resource_kind.proto kind_meta. DO NOT EDIT.\n\n")
	buf.WriteString("import { ApiResourceKind } from \"@stigmer/protos/ai/stigmer/commons/apiresource/apiresourcekind/api_resource_kind_pb\";\n\n")

	buf.WriteString("/**\n")
	buf.WriteString(" * Resource kinds whose proto kind_meta.tier is cloud_only.\n")
	buf.WriteString(" *\n")
	buf.WriteString(" * Source of truth: api_resource_kind.proto — each ApiResourceKind enum\n")
	buf.WriteString(" * value carries a ResourceTier in its kind_meta options.\n")
	buf.WriteString(" */\n")
	buf.WriteString("export const CLOUD_ONLY_KINDS: ReadonlySet<ApiResourceKind> = new Set([\n")

	for _, entry := range entries {
		if entry.tier == apiresourcekind.ResourceTier_cloud_only {
			fmt.Fprintf(&buf, "  ApiResourceKind.%s,\n", entry.enumName)
		}
	}

	buf.WriteString("]);\n")

	return os.WriteFile(filepath.Join(outputDir, "resource-availability.ts"), buf.Bytes(), 0644)
}

func generateTSAuthorizationConfig(outputDir string, entries []kindMetaEntry) error {
	var buf bytes.Buffer

	buf.WriteString("// Code generated by stigmer-codegen from api_resource_kind.proto kind_meta. DO NOT EDIT.\n\n")
	buf.WriteString("import { ApiResourceKind } from \"@stigmer/protos/ai/stigmer/commons/apiresource/apiresourcekind/api_resource_kind_pb\";\n")
	buf.WriteString("import { IamRole } from \"@stigmer/protos/ai/stigmer/iam/v1/enum_pb\";\n\n")

	buf.WriteString("/**\n")
	buf.WriteString(" * Roles that can be granted on each resource kind via IAM policies.\n")
	buf.WriteString(" *\n")
	buf.WriteString(" * Source of truth: api_resource_kind.proto — each ApiResourceKind enum\n")
	buf.WriteString(" * value carries an AuthorizationConfig with grantable_roles in its\n")
	buf.WriteString(" * kind_meta options.\n")
	buf.WriteString(" *\n")
	buf.WriteString(" * Kinds not in this map have no user-grantable roles (system-managed,\n")
	buf.WriteString(" * owner-only, inherited, or no authorization).\n")
	buf.WriteString(" */\n")
	buf.WriteString("export const GRANTABLE_ROLES: ReadonlyMap<ApiResourceKind, readonly IamRole[]> = new Map([\n")

	for _, entry := range entries {
		if len(entry.grantableRoles) == 0 {
			continue
		}
		fmt.Fprintf(&buf, "  [ApiResourceKind.%s, [", entry.enumName)
		for i, role := range entry.grantableRoles {
			if i > 0 {
				buf.WriteString(", ")
			}
			roleName := iamv1.IamRole_name[int32(role)]
			fmt.Fprintf(&buf, "IamRole.%s", roleName)
		}
		buf.WriteString("]],\n")
	}

	buf.WriteString("]);\n")

	return os.WriteFile(filepath.Join(outputDir, "authorization-config.ts"), buf.Bytes(), 0644)
}
