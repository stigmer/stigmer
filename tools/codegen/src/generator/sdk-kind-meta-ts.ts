// TypeScript files derived from ApiResourceKind kind_meta options: resource
// availability (tier) and authorization config (grantable_roles,
// team_grantable_roles and role_descriptions, with each IamRole's role_meta
// name and kindless sentence). Port of
// sdk_kind_meta_ts.go; the data comes from @stigmer/protos' descriptors via
// resource-kind.ts.

import * as fs from "node:fs";
import * as path from "node:path";

import { iamRoleMetaEntries, iamRoleName, kindMetaEntries, ResourceTier } from "./resource-kind.js";

export function generateTSKindMeta(outputDir: string): void {
  const entries = kindMetaEntries();
  generateTSResourceAvailability(outputDir, entries);
  generateTSAuthorizationConfig(outputDir, entries);
}

function generateTSResourceAvailability(outputDir: string, entries: ReturnType<typeof kindMetaEntries>): void {
  const buf: string[] = [];

  buf.push("// Code generated by stigmer-codegen from api_resource_kind.proto kind_meta. DO NOT EDIT.\n\n");
  buf.push('import { ApiResourceKind, ResourceTier } from "@stigmer/protos/ai/stigmer/commons/apiresource/apiresourcekind/api_resource_kind_pb";\n\n');

  buf.push("/**\n");
  buf.push(" * The minimum edition that serves each resource kind (kind_meta.tier).\n");
  buf.push(" *\n");
  buf.push(" * Every kind with kind_meta is present, in enum-number order; a kind\n");
  buf.push(" * absent here has no tier and is a programming error to ask about.\n");
  buf.push(" *\n");
  buf.push(" * Source of truth: api_resource_kind.proto — each ApiResourceKind enum\n");
  buf.push(" * value carries a ResourceTier in its kind_meta options.\n");
  buf.push(" */\n");
  buf.push("export const KIND_TIERS: ReadonlyMap<ApiResourceKind, ResourceTier> = new Map([\n");

  for (const entry of entries) {
    buf.push(`  [ApiResourceKind.${entry.enumName}, ResourceTier.${tierName(entry.tier)}],\n`);
  }

  buf.push("]);\n");

  fs.writeFileSync(path.join(outputDir, "resource-availability.ts"), buf.join(""));
}

/** ResourceTier number → enum value name, so the emitted file reads as the proto does. */
function tierName(tier: ResourceTier): string {
  const name = ResourceTier[tier];
  if (name === undefined) {
    throw new Error(`kind_meta.tier ${tier} has no ResourceTier name — regenerate @stigmer/protos first`);
  }
  return name;
}

function generateTSAuthorizationConfig(outputDir: string, entries: ReturnType<typeof kindMetaEntries>): void {
  const buf: string[] = [];

  buf.push("// Code generated by stigmer-codegen from api_resource_kind.proto kind_meta. DO NOT EDIT.\n\n");
  buf.push('import { ApiResourceKind } from "@stigmer/protos/ai/stigmer/commons/apiresource/apiresourcekind/api_resource_kind_pb";\n');
  buf.push('import { IamRole } from "@stigmer/protos/ai/stigmer/iam/v1/enum_pb";\n\n');

  buf.push("/**\n");
  buf.push(" * Roles that can be granted on each resource kind via IAM policies.\n");
  buf.push(" *\n");
  buf.push(" * Source of truth: api_resource_kind.proto — each ApiResourceKind enum\n");
  buf.push(" * value carries an AuthorizationConfig with grantable_roles in its\n");
  buf.push(" * kind_meta options.\n");
  buf.push(" *\n");
  buf.push(" * Kinds not in this map have no user-grantable roles (system-managed,\n");
  buf.push(" * owner-only, inherited, or no authorization).\n");
  buf.push(" */\n");
  buf.push("export const GRANTABLE_ROLES: ReadonlyMap<ApiResourceKind, readonly IamRole[]> = new Map([\n");

  pushRoleMapEntries(buf, entries, (entry) => entry.grantableRoles);

  buf.push("]);\n\n");

  buf.push("/**\n");
  buf.push(" * Roles that can be granted on each resource kind to a team, so every\n");
  buf.push(" * member of the team holds the role.\n");
  buf.push(" *\n");
  buf.push(" * Source of truth: api_resource_kind.proto — team_grantable_roles in each\n");
  buf.push(" * kind's AuthorizationConfig, always a subset of grantable_roles.\n");
  buf.push(" *\n");
  buf.push(" * Kinds not in this map cannot be shared with a team. Teams are served by\n");
  buf.push(" * the Enterprise and Cloud editions.\n");
  buf.push(" */\n");
  buf.push("export const TEAM_GRANTABLE_ROLES: ReadonlyMap<ApiResourceKind, readonly IamRole[]> = new Map([\n");

  pushRoleMapEntries(buf, entries, (entry) => entry.teamGrantableRoles);

  buf.push("]);\n\n");

  buf.push("/**\n");
  buf.push(" * What each grantable role means on each resource kind, one sentence per\n");
  buf.push(" * role, shown beside the role wherever a person picks or reads one.\n");
  buf.push(" *\n");
  buf.push(" * Source of truth: api_resource_kind.proto — role_descriptions in each\n");
  buf.push(" * kind's AuthorizationConfig, one entry per grantable role.\n");
  buf.push(" */\n");
  buf.push("export const ROLE_DESCRIPTIONS: ReadonlyMap<ApiResourceKind, ReadonlyMap<IamRole, string>> = new Map([\n");
  for (const entry of entries) {
    if (entry.roleDescriptions.length === 0) continue;
    buf.push(`  [ApiResourceKind.${entry.enumName}, new Map<IamRole, string>([\n`);
    for (const { role, description } of entry.roleDescriptions) {
      buf.push(`    [IamRole.${iamRoleName(role)}, ${JSON.stringify(description)}],\n`);
    }
    buf.push("  ])],\n");
  }
  buf.push("]);\n\n");

  const roles = iamRoleMetaEntries();
  buf.push("/**\n");
  buf.push(" * Each role's name as people read it.\n");
  buf.push(" *\n");
  buf.push(" * Source of truth: enum.proto — each IamRole value's role_meta.display_name.\n");
  buf.push(" */\n");
  buf.push("export const ROLE_DISPLAY_NAMES: ReadonlyMap<IamRole, string> = new Map([\n");
  for (const role of roles) {
    buf.push(`  [IamRole.${role.name}, ${JSON.stringify(role.displayName)}],\n`);
  }
  buf.push("]);\n\n");

  buf.push("/**\n");
  buf.push(" * What each role means when no resource kind is known. A picker shows the\n");
  buf.push(" * kind's own sentence instead (ROLE_DESCRIPTIONS).\n");
  buf.push(" *\n");
  buf.push(" * Source of truth: enum.proto — each IamRole value's role_meta.description.\n");
  buf.push(" */\n");
  buf.push("export const ROLE_KINDLESS_DESCRIPTIONS: ReadonlyMap<IamRole, string> = new Map([\n");
  for (const role of roles) {
    buf.push(`  [IamRole.${role.name}, ${JSON.stringify(role.description)}],\n`);
  }
  buf.push("]);\n");

  fs.writeFileSync(path.join(outputDir, "authorization-config.ts"), buf.join(""));
}

/** One `[kind, [roles]]` line per kind with a non-empty role list, in enum-number order. */
function pushRoleMapEntries(
  buf: string[],
  entries: ReturnType<typeof kindMetaEntries>,
  rolesOf: (entry: ReturnType<typeof kindMetaEntries>[number]) => number[],
): void {
  for (const entry of entries) {
    const roles = rolesOf(entry);
    if (roles.length === 0) continue;
    buf.push(`  [ApiResourceKind.${entry.enumName}, [`);
    buf.push(roles.map((role) => `IamRole.${iamRoleName(role)}`).join(", "));
    buf.push("]],\n");
  }
}
