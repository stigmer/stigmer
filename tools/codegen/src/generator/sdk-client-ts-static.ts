import * as fs from "node:fs";
import * as path from "node:path";

export function generateTSErrors(outputDir: string): void {
  const content = `// Code generated by stigmer-codegen. DO NOT EDIT.

import { ConnectError, Code } from "@connectrpc/connect";

/** Error codes mapped from gRPC/Connect status codes. */
export type ErrorCode =
  | "unknown"
  | "not-found"
  | "permission-denied"
  | "unauthenticated"
  | "invalid-argument"
  | "already-exists"
  | "resource-exhausted"
  | "failed-precondition"
  | "internal"
  | "unavailable"
  | "cancelled";

const CODE_MAP: Record<number, ErrorCode> = {
  [Code.NotFound]: "not-found",
  [Code.PermissionDenied]: "permission-denied",
  [Code.Unauthenticated]: "unauthenticated",
  [Code.InvalidArgument]: "invalid-argument",
  [Code.AlreadyExists]: "already-exists",
  [Code.ResourceExhausted]: "resource-exhausted",
  [Code.FailedPrecondition]: "failed-precondition",
  [Code.Internal]: "internal",
  [Code.Unavailable]: "unavailable",
  [Code.Canceled]: "cancelled",
};

/** Structured error type returned by all SDK operations. */
export class StigmerError extends Error {
  readonly code: ErrorCode;
  readonly connectCode: number;

  constructor(code: ErrorCode, message: string, connectCode: number, options?: ErrorOptions) {
    super(message, options);
    this.name = "StigmerError";
    this.code = code;
    this.connectCode = connectCode;
  }
}

/** @internal Convert any thrown value to a StigmerError. */
export function wrapError(err: unknown): StigmerError {
  if (err instanceof ConnectError) {
    const code = CODE_MAP[err.code] ?? "unknown";
    // Chain the ConnectError so structured error details
    // (e.g. google.rpc.ErrorInfo) stay reachable via getErrorReason.
    return new StigmerError(code, err.rawMessage || err.message, err.code, { cause: err });
  }
  if (err instanceof StigmerError) {
    return err;
  }
  if (err instanceof Error) {
    return new StigmerError("unknown", err.message, Code.Unknown, { cause: err });
  }
  return new StigmerError("unknown", String(err), Code.Unknown);
}

export function isNotFound(err: unknown): boolean {
  return err instanceof StigmerError && err.code === "not-found";
}

export function isUnauthenticated(err: unknown): boolean {
  return err instanceof StigmerError && err.code === "unauthenticated";
}

export function isPermissionDenied(err: unknown): boolean {
  return err instanceof StigmerError && err.code === "permission-denied";
}

export function isRetryable(err: unknown): boolean {
  return err instanceof StigmerError && (err.code === "internal" || err.code === "unavailable");
}

/**
 * The server does not implement the called RPC — the code clients key
 * capability fallbacks on (e.g. the skill artifact transfer lane's unary
 * fallback, stigmer#675/#701). Checks the raw connect code: Unimplemented
 * deliberately has no ErrorCode mapping, so it surfaces as "unknown".
 */
export function isUnimplemented(err: unknown): boolean {
  return err instanceof StigmerError && err.connectCode === Code.Unimplemented;
}
`;
  fs.writeFileSync(path.join(outputDir, "errors.ts"), content);
}

export function generateTSProtoUtils(outputDir: string): void {
  const content = `// Code generated by stigmer-codegen. DO NOT EDIT.

import { timestampFromDate, type Timestamp } from "@bufbuild/protobuf/wkt";
import type { ApiResourceReference } from "@stigmer/protos/ai/stigmer/commons/apiresource/io_pb";
import type { EnvironmentSpec, EnvironmentValue } from "@stigmer/protos/ai/stigmer/agentic/environment/v1/spec_pb";
import type { ExecutionValue } from "@stigmer/protos/ai/stigmer/agentic/executioncontext/v1/spec_pb";
import type { EnvSpecInput, EnvVarInput, ResourceRef } from "./types.js";

/**
 * Remove keys whose values are \`undefined\` so that \`Object.assign\`
 * does not overwrite protobuf default values (empty maps, empty arrays).
 */
export function stripUndefined<T extends Record<string, unknown>>(obj: T): Partial<T> {
  const result: Record<string, unknown> = {};
  for (const key of Object.keys(obj)) {
    if (obj[key] !== undefined) {
      result[key] = obj[key];
    }
  }
  return result as Partial<T>;
}

/**
 * Convert a Date or ISO-8601 string to a protobuf Timestamp message.
 * Accepts both \`Date\` objects and ISO string representations.
 */
export function toTimestamp(value: Date | string): Timestamp {
  const date = value instanceof Date ? value : new Date(value);
  return timestampFromDate(date);
}

/**
 * Narrow a fetched ApiResourceReference to the ResourceRef input shape,
 * or \`undefined\` when the reference is absent/empty (the builders treat a
 * ref without org and slug as "no reference"). \`version\` is preserved —
 * dropping it would reset a pinned reference to "latest". \`kind\` is also
 * preserved: builders overwrite it where the proto annotates a reference
 * kind, but refs without that annotation (e.g. an organization's
 * identityProviderRef) carry the stored kind, so dropping it would be
 * lossy.
 */
export function toResourceRefInput(ref: ApiResourceReference | undefined): ResourceRef | undefined {
  if (!ref || (!ref.org && !ref.slug)) return undefined;
  return {
    org: ref.org,
    slug: ref.slug,
    ...(ref.version && { version: ref.version }),
    ...(ref.kind && { kind: ref.kind }),
  };
}

/**
 * Map a repeated ApiResourceReference to ResourceRef inputs, or \`undefined\`
 * when the list is absent/empty (the mappers' canonical shape for empty
 * lists).
 */
export function toResourceRefInputs(refs: ApiResourceReference[] | undefined): ResourceRef[] | undefined {
  if (!refs || refs.length === 0) return undefined;
  return refs.map((r) => toResourceRefInput(r) ?? { org: "", slug: "" });
}

/**
 * Convert a fetched EnvironmentSpec to the EnvSpecInput shape, or
 * \`undefined\` when absent/empty.
 */
export function toEnvSpecInput(spec: EnvironmentSpec | undefined): EnvSpecInput | undefined {
  if (!spec) return undefined;
  const variables = toEnvVarInputMap(spec.data);
  return variables ? { variables } : undefined;
}

/**
 * Convert a map of EnvironmentValue to EnvVarInput entries, or \`undefined\`
 * when the map is absent/empty.
 */
export function toEnvVarInputMap(data: Record<string, EnvironmentValue> | undefined): Record<string, EnvVarInput> | undefined {
  if (!data || Object.keys(data).length === 0) return undefined;
  return Object.fromEntries(Object.entries(data).map(([k, v]) =>
    [k, { value: v.value, isSecret: v.isSecret || undefined, description: v.description || undefined }]));
}

/**
 * Convert a map of ExecutionValue to EnvVarInput entries, or \`undefined\`
 * when the map is absent/empty.
 */
export function toExecVarInputMap(data: Record<string, ExecutionValue> | undefined): Record<string, EnvVarInput> | undefined {
  if (!data || Object.keys(data).length === 0) return undefined;
  return Object.fromEntries(Object.entries(data).map(([k, v]) =>
    [k, { value: v.value, isSecret: v.isSecret || undefined }]));
}
`;
  fs.writeFileSync(path.join(outputDir, "proto-utils.ts"), content);
}

