// task-docs target: per-task MDX reference pages plus the category-card
// index page assembled from the hand-written enrichment template. Byte-
// parity port of task_docs.go (the committed pages additionally pass
// through Prettier in the Makefile — that post-processing stays in make).

import * as fs from "node:fs";
import * as path from "node:path";

import type { GoJsonValue } from "../gojson.js";
import { marshalIndent } from "../gojson.js";
import { goTrimSpace } from "../internalcomment/internalcomment.js";
import { validateSidecarExamples } from "./example-validation.js";
import type { FieldSchema, TaskConfigSchema, TypeSchema, TypeSpec } from "./schema.js";
import { kindOrder, loadSharedTypes, loadTaskSchemas, taskKindString, toDisplayName } from "./schema.js";
import type { SidecarMeta } from "./sidecar.js";
import { loadSidecarMetadata } from "./sidecar.js";

// Presentation metadata and display order for task categories. The index
// generation enforces an exact partition: every task's category must be
// declared here (no silent "Other" bucket).
const TASK_DOCS_CATEGORY_ORDER: Array<{ id: string; displayName: string; description: string }> = [
  { id: "ai", displayName: "AI", description: "LLM inference, agent invocation, and LLM-as-judge evaluation." },
  { id: "control_flow", displayName: "Control Flow", description: "Branching, loops, parallelism, and error handling." },
  { id: "data", displayName: "Data", description: "Variables, data transformation, and schema validation." },
  { id: "governance", displayName: "Governance", description: "Human-in-the-loop approvals, notifications, and quality gates." },
  { id: "invocation", displayName: "External Invocation", description: "HTTP, gRPC, and Temporal activity calls, plus sub-workflow runs." },
  { id: "event", displayName: "Events", description: "Signal handling, event emission, notifications, and raised errors." },
];

const CATEGORY_CARDS_MARKER = "{/* AUTO_TASK_CATEGORY_CARDS */}";
const OVERVIEW_PATH_FOR_COMMENT = "apis/ai/stigmer/agentic/workflow/v1/tasks/docs/overview.mdx";

/** Port of runTaskDocsGeneration. */
export function runTaskDocsGeneration(schemaDir: string, outputDir: string, metaDir: string, apisDir: string): void {
  const tasksSchemaDir = path.join(schemaDir, "tasks");
  const typesDir = path.join(tasksSchemaDir, "types");

  const schemas = loadTaskSchemas(tasksSchemaDir);
  const sharedTypes = loadSharedTypes(typesDir);
  const sidecars = loadSidecarMetadata(metaDir);

  validateSidecarExamples(schemas, sidecars);

  fs.mkdirSync(outputDir, { recursive: true });

  schemas.sort((a, b) => kindOrder(taskKindString(a)) - kindOrder(taskKindString(b)));

  const slugs: string[] = [];

  for (const schema of schemas) {
    const kind = taskKindString(schema);
    const meta = sidecars.get(kind) ?? null;

    const page = taskDocsGeneratePage(schema, meta, sharedTypes);
    const slug = taskDocsSlug(kind);
    fs.writeFileSync(path.join(outputDir, slug + ".mdx"), page);
    slugs.push(slug);
  }

  const index = taskDocsGenerateIndex(schemas, sidecars, taskDocsOverviewPath(apisDir));
  fs.writeFileSync(path.join(outputDir, "index.mdx"), index);

  // "index" is deliberately NOT listed in meta.json: omitting it lets
  // Fumadocs' setIndexIfUnused keep the folder URL a real, clickable page.
  const meta = { title: "Task Types", pages: slugs };
  fs.writeFileSync(path.join(outputDir, "meta.json"), marshalIndent(meta) + "\n");
  process.stderr.write(`task-docs: generated ${slugs.length} pages in ${outputDir}\n`);
}

// =========================================================================
// Per-task page generation
// =========================================================================

function taskDocsGeneratePage(schema: TaskConfigSchema, meta: SidecarMeta | null, sharedTypes: Map<string, TypeSchema>): string {
  const buf: string[] = [];
  const kind = taskKindString(schema);

  let displayName = toDisplayName(kind);
  let description = "";
  if (meta !== null) {
    displayName = meta.displayName;
    description = meta.description;
  }
  if (description === "") {
    description = docFirstSentence(schema.description);
  }

  buf.push(`---\ntitle: ${displayName}\ndescription: "${docEscapeJSString(description)}"\n---\n\n`);
  buf.push("{/* Autogenerated by stigmer-codegen. DO NOT EDIT. */}\n\n");

  const overview = docSDKContent(schema.description);
  if (overview !== "") {
    buf.push(docEscapeMDX(overview));
    buf.push("\n\n");
  }

  buf.push("## Kind\n\n");
  buf.push(`\`${kind}\`\n\n`);

  if (meta !== null && meta.yamlExamples.length > 0) {
    buf.push(meta.yamlExamples.length === 1 ? "## YAML Example\n\n" : "## YAML Examples\n\n");
    for (const example of meta.yamlExamples) {
      buf.push("```yaml\n");
      buf.push(example.replace(/\n+$/, ""));
      buf.push("\n```\n\n");
    }
  }

  const documentedTypes = new Set<string>();
  for (const f of schema.fields) {
    taskDocsCollectNestedTypeNames(f, sharedTypes, documentedTypes);
  }

  const enumSpecs: Array<{ name: string; values: string[] }> = [];
  const enumVisited = new Set<string>();
  for (const f of schema.fields) {
    taskDocsCollectEnums(f, sharedTypes, enumSpecs, documentedTypes, enumVisited);
  }

  buf.push("## task\\_config Fields\n\n");
  buf.push("<TypeTable\n  type={{\n");
  for (const f of schema.fields) {
    taskDocsWriteField(buf, f, documentedTypes);
  }
  buf.push("  }}\n/>\n\n");

  const emitted = new Set<string>();
  const hasNestedTypes = schema.fields.some(taskDocsHasNestedType);
  if (hasNestedTypes) {
    buf.push("## Nested Types\n\n");
    for (const f of schema.fields) {
      taskDocsWriteNestedType(buf, f, sharedTypes, emitted, documentedTypes);
    }
  }

  if (enumSpecs.length > 0) {
    buf.push("## Enums\n\n");
    for (const es of enumSpecs) {
      if (emitted.has(es.name)) continue;
      emitted.add(es.name);
      buf.push(`### ${es.name}\n\n`);
      buf.push("| Value | Description |\n");
      buf.push("|-------|-------------|\n");
      for (const v of es.values) {
        buf.push(`| \`${v}\` | |\n`);
      }
      buf.push("\n");
    }
  }

  if (meta !== null && meta.outputSchema !== undefined) {
    buf.push("## Output Shape\n\n");
    taskDocsWriteOutputSchema(buf, meta.outputSchema);
  }

  buf.push("## See Also\n\n");
  buf.push("- [Workflow Authoring Guide](/docs/guides/workflows/authoring)\n");
  buf.push("- [Task Type Overview](/docs/guides/workflows/task-types)\n");
  buf.push("- [Workflow Patterns](/docs/guides/workflows/patterns)\n");

  return buf.join("");
}

// =========================================================================
// Field + nested type rendering
// =========================================================================

function taskDocsWriteField(buf: string[], f: FieldSchema, documentedTypes: Set<string>): void {
  const fieldType = taskDocsTypeString(f.type);
  const desc = docEscapeJSString(docFirstSentence(f.description));
  const link = taskDocsFieldTypeLink(f.type, documentedTypes);

  const props: string[] = [];
  props.push(`type: "${fieldType}"`);
  props.push(`description: "${desc}"`);
  if (link !== "") props.push(`typeDescriptionLink: "${link}"`);
  if (f.required) props.push("required: true");
  buf.push(`    ${f.protoField}: { ${props.join(", ")} },\n`);
}

function taskDocsHasNestedType(f: FieldSchema): boolean {
  if (f.type.kind === "message") return true;
  if (f.type.kind === "array" && f.type.elementType?.kind === "message") return true;
  return false;
}

function taskDocsWriteNestedType(
  buf: string[],
  f: FieldSchema,
  typeMap: Map<string, TypeSchema>,
  emitted: Set<string>,
  documentedTypes: Set<string>,
): void {
  let msgName: string;
  if (f.type.kind === "message") {
    msgName = f.type.messageType ?? "";
  } else if (f.type.kind === "array" && f.type.elementType?.kind === "message") {
    msgName = f.type.elementType.messageType ?? "";
  } else {
    return;
  }

  if (emitted.has(msgName) || msgName === "") return;
  const ts = typeMap.get(msgName);
  if (ts === undefined) return;
  emitted.add(msgName);

  buf.push(`### ${msgName}\n\n`);

  if (ts.description !== "") {
    const content = docFirstSentence(ts.description);
    if (content !== "") {
      buf.push(docEscapeMDX(content));
      buf.push("\n\n");
    }
  }

  if (ts.fields.length > 0) {
    buf.push("<TypeTable\n  type={{\n");
    for (const field of ts.fields) {
      taskDocsWriteField(buf, field, documentedTypes);
    }
    buf.push("  }}\n/>\n\n");
  }

  for (const field of ts.fields) {
    taskDocsWriteNestedType(buf, field, typeMap, emitted, documentedTypes);
  }
}

function taskDocsCollectNestedTypeNames(f: FieldSchema, typeMap: Map<string, TypeSchema>, set: Set<string>): void {
  let msgName: string;
  if (f.type.kind === "message") {
    msgName = f.type.messageType ?? "";
  } else if (f.type.kind === "array" && f.type.elementType?.kind === "message") {
    msgName = f.type.elementType.messageType ?? "";
  } else {
    return;
  }

  if (set.has(msgName) || msgName === "") return;
  const ts = typeMap.get(msgName);
  if (ts === undefined) return;
  set.add(msgName);

  for (const field of ts.fields) {
    taskDocsCollectNestedTypeNames(field, typeMap, set);
  }
}

// =========================================================================
// Enum collection
// =========================================================================

function taskDocsCollectEnums(
  f: FieldSchema,
  typeMap: Map<string, TypeSchema>,
  out: Array<{ name: string; values: string[] }>,
  documentedTypes: Set<string>,
  visited: Set<string>,
): void {
  if (f.type.enumType !== undefined && f.type.enumType !== "" && (f.type.enumValues?.length ?? 0) > 0) {
    const name = taskDocsEnumShortName(f.type.enumType);
    documentedTypes.add(name);
    const values = (f.type.enumValues ?? []).filter((v) => !v.endsWith("_UNSPECIFIED"));
    out.push({ name, values });
  }

  let msgName = "";
  if (f.type.kind === "message") {
    msgName = f.type.messageType ?? "";
  } else if (f.type.kind === "array" && f.type.elementType?.kind === "message") {
    msgName = f.type.elementType.messageType ?? "";
  }
  if (msgName === "" || visited.has(msgName)) return;
  visited.add(msgName);
  const ts = typeMap.get(msgName);
  if (ts === undefined) return;
  for (const field of ts.fields) {
    taskDocsCollectEnums(field, typeMap, out, documentedTypes, visited);
  }
}

function taskDocsEnumShortName(fqn: string): string {
  const parts = fqn.split(".");
  return parts[parts.length - 1];
}

// =========================================================================
// Type formatting
// =========================================================================

function taskDocsTypeString(ts: TypeSpec): string {
  switch (ts.kind) {
    case "string":
      if (ts.enumType !== undefined && ts.enumType !== "") {
        return taskDocsEnumShortName(ts.enumType);
      }
      return "string";
    case "int32":
    case "uint32":
    case "int64":
    case "float":
    case "double":
      return "number";
    case "bool":
      return "boolean";
    case "struct":
      return "object";
    case "value":
      return "any";
    case "map": {
      const key = ts.keyType !== undefined ? taskDocsTypeString(ts.keyType) : "string";
      const val = ts.valueType !== undefined ? taskDocsTypeString(ts.valueType) : "string";
      return `Record<${key}, ${val}>`;
    }
    case "array":
      if (ts.elementType !== undefined) {
        return taskDocsTypeString(ts.elementType) + "[]";
      }
      return "string[]";
    case "message":
      return ts.messageType ?? "";
    case "timestamp":
      return "string";
    case "bytes":
      return "Uint8Array";
    default:
      return "string";
  }
}

function taskDocsFieldTypeLink(ts: TypeSpec, documentedTypes: Set<string>): string {
  if (ts.enumType !== undefined && ts.enumType !== "") {
    const name = taskDocsEnumShortName(ts.enumType);
    if (documentedTypes.has(name)) {
      return "#" + name.toLowerCase();
    }
    return "";
  }

  let msgName: string;
  if (ts.kind === "message") {
    msgName = ts.messageType ?? "";
  } else if (ts.kind === "array" && ts.elementType?.kind === "message") {
    msgName = ts.elementType.messageType ?? "";
  } else {
    return "";
  }

  if (documentedTypes.has(msgName)) {
    return "#" + msgName.toLowerCase();
  }
  return "";
}

