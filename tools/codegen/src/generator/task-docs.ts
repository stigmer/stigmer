function taskDocsWriteOutputSchema(buf: string[], schema: GoJsonValue): void {
  buf.push("```json\n");
  buf.push(marshalIndent(schema));
  buf.push("\n```\n\n");
}

// =========================================================================
// Index page generation
// =========================================================================

function taskDocsOverviewPath(apisDir: string): string {
  return path.join(apisDir, "ai", "stigmer", "agentic", "workflow", "v1", "tasks", "docs", "overview.mdx");
}

// The hand-written enrichment prose with the generated per-category card
// grid injected at the marker. Fails loudly when the enrichment file or its
// marker is missing, or a task's category is undeclared.
function taskDocsGenerateIndex(
  schemas: TaskConfigSchema[],
  sidecars: Map<string, SidecarMeta>,
  overviewPath: string,
): string {
  let enrichment: string;
  try {
    enrichment = fs.readFileSync(overviewPath, "utf8");
  } catch (err) {
    throw new Error(`index enrichment template is required: ${err instanceof Error ? err.message : String(err)}`);
  }
  if (!enrichment.includes(CATEGORY_CARDS_MARKER)) {
    throw new Error(`enrichment template ${overviewPath} is missing the ${CATEGORY_CARDS_MARKER} marker`);
  }

  const known = new Set(TASK_DOCS_CATEGORY_ORDER.map((cm) => cm.id));
  const byCategory = new Map<string, TaskConfigSchema[]>();
  for (const schema of schemas) {
    const kind = taskKindString(schema);
    const meta = sidecars.get(kind);
    if (meta === undefined || meta.category === "") {
      throw new Error(`task "${kind}" has no category in its sidecar metadata`);
    }
    if (!known.has(meta.category)) {
      throw new Error(`task "${kind}" has category "${meta.category}", which is not declared in taskDocsCategoryOrder`);
    }
    const group = byCategory.get(meta.category);
    if (group === undefined) byCategory.set(meta.category, [schema]);
    else group.push(schema);
  }

  const cards: string[] = [];
  for (const cm of TASK_DOCS_CATEGORY_ORDER) {
    const group = byCategory.get(cm.id) ?? [];
    if (group.length === 0) continue;

    cards.push(`## ${cm.displayName}\n\n`);
    cards.push(cm.description);
    cards.push("\n\n");

    cards.push("<Cards>\n");
    for (const schema of group) {
      const kind = taskKindString(schema);
      const meta = sidecars.get(kind)!;
      cards.push(`  <Card\n    title="${meta.displayName}"\n    description="${docEscapeJSString(meta.description)}"\n    href="/docs/guides/workflows/task-types/${taskDocsSlug(kind)}"\n  />\n`);
    }
    cards.push("</Cards>\n\n");
  }

  const page = enrichment.replace(CATEGORY_CARDS_MARKER, cards.join("").replace(/\n+$/, ""));

  // Insert the generated-file notice after the frontmatter so readers land
  // on the enrichment source when they want to edit prose.
  const notice = `\n{/* Autogenerated by stigmer-codegen. DO NOT EDIT. */}\n{/* To edit the prose on this page, edit ${OVERVIEW_PATH_FOR_COMMENT} */}\n`;
  const end = page.slice(3).indexOf("\n---\n");
  if (!page.startsWith("---\n") || end < 0) {
    throw new Error(`enrichment template ${overviewPath} must start with YAML frontmatter`);
  }
  const insertAt = 3 + end + "\n---\n".length;
  return page.slice(0, insertAt) + notice + page.slice(insertAt);
}

function taskDocsSlug(kind: string): string {
  return kind.replaceAll("_", "-");
}

// =========================================================================
// Description helpers (shared shapes with sdk-docs; duplicated in Go too)
// =========================================================================

function docCleanDesc(desc: string): string {
  desc = goTrimSpace(desc);
  const paragraphs = desc.split("\n\n");
  for (let i = 0; i < paragraphs.length; i++) {
    const lines = goTrimSpace(paragraphs[i]).split("\n");
    for (let j = 0; j < lines.length; j++) {
      lines[j] = goTrimSpace(lines[j]);
    }
    paragraphs[i] = lines.join(" ");
  }
  return paragraphs.join("\n\n");
}

function docEscapeMDX(s: string): string {
  s = s.replaceAll("{", "\\{");
  s = s.replaceAll("}", "\\}");
  s = s.replaceAll("<", "&lt;");
  s = s.replaceAll(">", "&gt;");
  return s;
}

function docFirstSentence(desc: string): string {
  if (desc === "") return "";
  desc = docCleanDesc(desc);
  const idx = desc.indexOf("\n\n");
  if (idx >= 0) desc = desc.slice(0, idx);
  const end = docSentenceEnd(desc);
  if (end >= 0) return desc.slice(0, end + 1);
  if (desc.endsWith(".")) return desc;
  return desc + ".";
}

function docSentenceEnd(s: string): number {
  const abbrevs = ["e.g.", "i.e.", "etc.", "vs.", "approx.", "incl.", "resp."];
  let offset = 0;
  for (;;) {
    const idx = s.slice(offset).indexOf(". ");
    if (idx < 0) return -1;
    const pos = offset + idx;
    let isAbbrev = false;
    for (const abbr of abbrevs) {
      if (pos + 1 >= abbr.length && s.slice(pos + 1 - abbr.length, pos + 1).toLowerCase() === abbr.toLowerCase()) {
        isAbbrev = true;
        break;
      }
    }
    if (!isAbbrev) return pos;
    offset = pos + 2;
  }
}

function docEscapeJSString(s: string): string {
  s = s.replaceAll("\\", "\\\\");
  s = s.replaceAll('"', '\\"');
  s = s.replaceAll("\n", " ");
  return s;
}

function docSDKContent(desc: string): string {
  if (desc === "") return "";
  desc = goTrimSpace(desc);
  desc = docStripSince(desc);

  if (desc.startsWith("## ")) return "";

  const paragraphs: string[] = [];
  for (let p of desc.split("\n\n")) {
    p = goTrimSpace(p);
    if (p.startsWith("## ")) break;
    if (p === "") continue;
    const lines = p.split("\n");
    for (let i = 0; i < lines.length; i++) {
      lines[i] = goTrimSpace(lines[i]);
    }
    paragraphs.push(lines.join(" "));
  }
  return goTrimSpace(paragraphs.join("\n\n"));
}

function docStripSince(desc: string): string {
  const result: string[] = [];
  for (const line of desc.split("\n")) {
    if (goTrimSpace(line).startsWith("@since")) continue;
    result.push(line);
  }
  return result.join("\n");
}
