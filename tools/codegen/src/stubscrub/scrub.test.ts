// Byte-parity pins for the stubscrub port. Samples are taken byte-for-byte
// from real generated stubs (apis/stubs/go, apis/stubs/ts,
// apis/stubs/python) — carried verbatim from the Go tool's tests — so these
// pin the exact shapes protoc-gen-go, protoc-gen-es, and grpc-python emit.
// The Java samples come from apis/stubs/java and pin the javadoc shapes
// protoc-java and grpc-java emit, including their &#64; escape of the marker.
import { describe, expect, it } from "vitest";

import { scrubberFor, scrubGo, scrubJava, scrubPy, scrubTs, type Scrubber } from "./scrub.js";

interface ScrubCase {
  name: string;
  input: string;
  want?: string;
  changed: boolean;
}

function runScrubTests(scrub: Scrubber, cases: ScrubCase[]): void {
  for (const tc of cases) {
    it(tc.name, () => {
      const [got, changed] = scrub(tc.input);
      expect(changed).toBe(tc.changed);
      expect(got).toBe(tc.changed ? tc.want : tc.input);
    });
  }
}

describe("scrubGo", () => {
  runScrubTests(scrubGo, [
    {
      name: "field-level internal section is cut, doc prefix kept",
      input:
        "type McpServerSpec struct {\n" +
        "\t// Default tools to enable from this MCP server.\n" +
        "\t// Empty list means all tools are enabled by default.\n" +
        "\t//\n" +
        "\t// @internal\n" +
        "\t// Tool names must match exactly what the MCP server reports via tools/list.\n" +
        "\t// Only names from discovered_capabilities.tools are valid here.\n" +
        '\tEnabledTools []string `protobuf:"bytes,4,rep,name=enabled_tools"`\n' +
        "}\n",
      want:
        "type McpServerSpec struct {\n" +
        "\t// Default tools to enable from this MCP server.\n" +
        "\t// Empty list means all tools are enabled by default.\n" +
        '\tEnabledTools []string `protobuf:"bytes,4,rep,name=enabled_tools"`\n' +
        "}\n",
      changed: true,
    },
    {
      name: "message-level doc with @since after marker drops both",
      input:
        "// AgentVersionEntry represents a single historical version of an agent.\n" +
        "//\n" +
        "// @internal\n" +
        "// NOT YET IMPLEMENTED — design placeholder for the agent versioning phase.\n" +
        "//\n" +
        "// @since Agent Versioning (future)\n" +
        "type AgentVersionEntry struct {\n",
      want:
        "// AgentVersionEntry represents a single historical version of an agent.\n" +
        "type AgentVersionEntry struct {\n",
      changed: true,
    },
    {
      name: "fully internal block is removed entirely",
      input:
        "\t// @internal\n" +
        "\t// The authorization and state-operation are determined at request execution.\n" +
        "\tApply(ctx context.Context) error\n",
      want: "\tApply(ctx context.Context) error\n",
      changed: true,
    },
    {
      name: "inline mention in prose is untouched",
      input: "// See the @internal tag convention for details.\nvar x int\n",
      changed: false,
    },
    {
      name: "marker-free file is untouched",
      input: "// Code generated by protoc-gen-go. DO NOT EDIT.\npackage v1\n",
      changed: false,
    },
  ]);
});

describe("scrubTs", () => {
  runScrubTests(scrubTs, [
    {
      name: "field JSDoc keeps @generated trailer past the internal section",
      input:
        'export type WorkflowExecution = Message<"a.b.WorkflowExecution"> & {\n' +
        "  /**\n" +
        "   * API version for this resource type.\n" +
        "   *\n" +
        "   * @internal\n" +
        "   * Format: 'agentic.stigmer.ai/v1'\n" +
        "   * Validated as const to ensure version consistency.\n" +
        "   *\n" +
        "   * @generated from field: string api_version = 1;\n" +
        "   */\n" +
        "  apiVersion: string;\n" +
        "};\n",
      want:
        'export type WorkflowExecution = Message<"a.b.WorkflowExecution"> & {\n' +
        "  /**\n" +
        "   * API version for this resource type.\n" +
        "   *\n" +
        "   * @generated from field: string api_version = 1;\n" +
        "   */\n" +
        "  apiVersion: string;\n" +
        "};\n",
      changed: true,
    },
    {
      name: "fully internal JSDoc with trailer keeps only the trailer",
      input:
        "/**\n" +
        " * @internal\n" +
        " * Storage strategy notes.\n" +
        " *\n" +
        " * @generated from message a.b.C\n" +
        " */\n" +
        'export type C = Message<"a.b.C">;\n',
      want:
        "/**\n" +
        " * @generated from message a.b.C\n" +
        " */\n" +
        'export type C = Message<"a.b.C">;\n',
      changed: true,
    },
    {
      name: "marker-free JSDoc is untouched",
      input: "/**\n * Plain doc.\n *\n * @generated from field: string x = 1;\n */\nexport const x = 1;\n",
      changed: false,
    },
  ]);
});

