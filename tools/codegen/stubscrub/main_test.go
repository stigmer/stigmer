package main

import "testing"

// Samples below are taken byte-for-byte from real generated stubs
// (apis/stubs/go, apis/stubs/ts, apis/stubs/python) so the tests pin the
// exact shapes protoc-gen-go, protoc-gen-es, and grpc-python emit.

func TestScrubGo(t *testing.T) {
	tests := []struct {
		name    string
		in      string
		want    string
		changed bool
	}{
		{
			name: "field-level internal section is cut, doc prefix kept",
			in: "type McpServerSpec struct {\n" +
				"\t// Default tools to enable from this MCP server.\n" +
				"\t// Empty list means all tools are enabled by default.\n" +
				"\t//\n" +
				"\t// @internal\n" +
				"\t// Tool names must match exactly what the MCP server reports via tools/list.\n" +
				"\t// Only names from discovered_capabilities.tools are valid here.\n" +
				"\tEnabledTools []string `protobuf:\"bytes,4,rep,name=enabled_tools\"`\n" +
				"}\n",
			want: "type McpServerSpec struct {\n" +
				"\t// Default tools to enable from this MCP server.\n" +
				"\t// Empty list means all tools are enabled by default.\n" +
				"\tEnabledTools []string `protobuf:\"bytes,4,rep,name=enabled_tools\"`\n" +
				"}\n",
			changed: true,
		},
		{
			name: "message-level doc with @since after marker drops both",
			in: "// AgentVersionEntry represents a single historical version of an agent.\n" +
				"//\n" +
				"// @internal\n" +
				"// NOT YET IMPLEMENTED — design placeholder for the agent versioning phase.\n" +
				"//\n" +
				"// @since Agent Versioning (future)\n" +
				"type AgentVersionEntry struct {\n",
			want: "// AgentVersionEntry represents a single historical version of an agent.\n" +
				"type AgentVersionEntry struct {\n",
			changed: true,
		},
		{
			name: "fully internal block is removed entirely",
			in: "\t// @internal\n" +
				"\t// The authorization and state-operation are determined at request execution.\n" +
				"\tApply(ctx context.Context) error\n",
			want:    "\tApply(ctx context.Context) error\n",
			changed: true,
		},
		{
			name:    "inline mention in prose is untouched",
			in:      "// See the @internal tag convention for details.\nvar x int\n",
			changed: false,
		},
		{
			name:    "marker-free file is untouched",
			in:      "// Code generated by protoc-gen-go. DO NOT EDIT.\npackage v1\n",
			changed: false,
		},
	}
	runScrubTests(t, scrubGo, tests)
}

func TestScrubTs(t *testing.T) {
	tests := []struct {
		name    string
		in      string
		want    string
		changed bool
	}{
		{
			name: "field JSDoc keeps @generated trailer past the internal section",
			in: "export type WorkflowExecution = Message<\"a.b.WorkflowExecution\"> & {\n" +
				"  /**\n" +
				"   * API version for this resource type.\n" +
				"   *\n" +
				"   * @internal\n" +
				"   * Format: 'agentic.stigmer.ai/v1'\n" +
				"   * Validated as const to ensure version consistency.\n" +
				"   *\n" +
				"   * @generated from field: string api_version = 1;\n" +
				"   */\n" +
				"  apiVersion: string;\n" +
				"};\n",
			want: "export type WorkflowExecution = Message<\"a.b.WorkflowExecution\"> & {\n" +
				"  /**\n" +
				"   * API version for this resource type.\n" +
				"   *\n" +
				"   * @generated from field: string api_version = 1;\n" +
				"   */\n" +
				"  apiVersion: string;\n" +
				"};\n",
			changed: true,
		},
		{
			name: "fully internal JSDoc with trailer keeps only the trailer",
			in: "/**\n" +
				" * @internal\n" +
				" * Storage strategy notes.\n" +
				" *\n" +
				" * @generated from message a.b.C\n" +
				" */\n" +
				"export type C = Message<\"a.b.C\">;\n",
			want: "/**\n" +
				" * @generated from message a.b.C\n" +
				" */\n" +
				"export type C = Message<\"a.b.C\">;\n",
			changed: true,
		},
		{
			name:    "marker-free JSDoc is untouched",
			in:      "/**\n * Plain doc.\n *\n * @generated from field: string x = 1;\n */\nexport const x = 1;\n",
			changed: false,
		},
	}
	runScrubTests(t, scrubTs, tests)
}

func TestScrubPy(t *testing.T) {
	tests := []struct {
		name    string
		in      string
		want    string
		changed bool
	}{
		{
			name: "grpc method docstring internal section is cut",
			in: "    def list(self, request, context):\n" +
				"        \"\"\"List all sessions with pagination and optional filtering.\n" +
				"\n" +
				"        @internal\n" +
				"        Authorization is handled in-handler via FGA-filtered queries.\n" +
				"        \"\"\"\n" +
				"        context.set_code(grpc.StatusCode.UNIMPLEMENTED)\n",
			want: "    def list(self, request, context):\n" +
				"        \"\"\"List all sessions with pagination and optional filtering.\n" +
				"        \"\"\"\n" +
				"        context.set_code(grpc.StatusCode.UNIMPLEMENTED)\n",
			changed: true,
		},
		{
			name:    "single-line docstring is untouched",
			in:      "    def f(self):\n        \"\"\"One liner.\"\"\"\n        pass\n",
			changed: false,
		},
		{
			name:    "marker-free docstring is untouched",
			in:      "    def f(self):\n        \"\"\"Doc.\n\n        More doc.\n        \"\"\"\n        pass\n",
			changed: false,
		},
	}
	runScrubTests(t, scrubPy, tests)
}

func runScrubTests(t *testing.T, scrub func([]byte) ([]byte, bool), tests []struct {
	name    string
	in      string
	want    string
	changed bool
}) {
	t.Helper()
	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			got, changed := scrub([]byte(tc.in))
			if changed != tc.changed {
				t.Fatalf("changed = %v, want %v", changed, tc.changed)
			}
			if !tc.changed {
				if string(got) != tc.in {
					t.Errorf("unchanged file was modified:\ngot:  %q\nwant: %q", got, tc.in)
				}
				return
			}
			if string(got) != tc.want {
				t.Errorf("scrub mismatch:\ngot:  %q\nwant: %q", got, tc.want)
			}
		})
	}
}
