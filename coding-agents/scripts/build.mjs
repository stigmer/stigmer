#!/usr/bin/env node

/**
 * Builds `@stigmer/coding-agent-plugin` into dist/:
 *
 *   dist/plugin/   the plugin, laid out as the published repository
 *                  (stigmer/coding-agent-plugin) holds it: the guide under
 *                  skills/stigmer/, .mcp.json, and the Claude Code, Cursor and
 *                  Codex manifests and marketplace files, each manifest's
 *                  `version` stamped with this package's;
 *   dist/index.js  `GUIDE` (the guide's text without its frontmatter, what
 *                  `stigmer coding-agent` prints), `VERSION`, and
 *                  `PLUGIN_REPOSITORY`, with its .d.ts.
 *
 * Then the pack check: npm decides what a tarball carries by rules of its own
 * (dot-folders are kept, but a `.gitignore` or `.npmrc` would not be), and the
 * reconcile lane copies the published tarball's dist/plugin/ as the plugin
 * repository's tree, so npm itself is asked (`npm pack --dry-run --json`) and
 * any staged file it would leave out fails the build by name.
 */

import { execFileSync } from "node:child_process";
import { cpSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const source = join(root, "plugin");
const dist = join(root, "dist");
const staged = join(dist, "plugin");
const { version } = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));

/** The manifests whose `version` is the package's. */
const MANIFESTS = [".claude-plugin/plugin.json", ".cursor-plugin/plugin.json", ".codex-plugin/plugin.json"];
const PLUGIN_REPOSITORY = "stigmer/coding-agent-plugin";
const GUIDE_PATH = "skills/stigmer/SKILL.md";

rmSync(dist, { recursive: true, force: true });
mkdirSync(dist, { recursive: true });
cpSync(source, staged, { recursive: true });
for (const manifest of MANIFESTS) {
  const path = join(staged, manifest);
  const json = JSON.parse(readFileSync(path, "utf8"));
  json.version = version;
  writeFileSync(path, `${JSON.stringify(json, null, 2)}\n`);
}

const guide = withoutFrontmatter(readFileSync(join(source, GUIDE_PATH), "utf8"));
writeFileSync(
  join(dist, "index.js"),
  [
    "// Generated by scripts/build.mjs from plugin/skills/stigmer/SKILL.md. Do not edit.",
    `export const GUIDE = ${JSON.stringify(guide)};`,
    `export const VERSION = ${JSON.stringify(version)};`,
    `export const PLUGIN_REPOSITORY = ${JSON.stringify(PLUGIN_REPOSITORY)};`,
    "",
  ].join("\n"),
);
writeFileSync(
  join(dist, "index.d.ts"),
  [
    "/** The guide a coding agent follows to set Stigmer up for a project (the skill's text, without its frontmatter). */",
    "export declare const GUIDE: string;",
    "/** This package's version, the CLI's own at a release. */",
    "export declare const VERSION: string;",
    "/** The GitHub repository the plugin installs from (`owner/name`). */",
    "export declare const PLUGIN_REPOSITORY: string;",
    "",
  ].join("\n"),
);

const packed = JSON.parse(execFileSync("npm", ["pack", "--dry-run", "--json", "--ignore-scripts"], { cwd: root, encoding: "utf8" }));
const inTarball = new Set(packed[0].files.map((file) => file.path));
const missing = filesUnder(dist).map((path) => relative(root, path)).filter((path) => !inTarball.has(path));
if (missing.length > 0) {
  console.error(`build: npm would leave out of the tarball: ${missing.join(", ")}`);
  process.exit(1);
}
console.log(`  built dist/ (${filesUnder(dist).length} files, plugin ${version})`);

/** The text after a leading `---` frontmatter block, trimmed at its start. */
function withoutFrontmatter(text) {
  const match = /^---\n[\s\S]*?\n---\n/.exec(text);
  return (match === null ? text : text.slice(match[0].length)).replace(/^\s+/, "");
}

function filesUnder(dir) {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    return statSync(path).isDirectory() ? filesUnder(path) : [path];
  });
}
