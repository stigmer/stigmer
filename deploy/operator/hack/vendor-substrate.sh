#!/usr/bin/env bash
# Fetches Agent Substrate's install files at one release into
# internal/manifests/substrate, unmodified, and writes the pin table that names
# every image the install runs by its multi-arch index digest.
#
#   vendor-substrate.sh <version> <output dir>
#
# Substrate publishes no install manifest, only the source tree its own
# installer reads, so this takes the release's source archive and copies the
# files that installer applies for one shape: bundled Postgres, gVisor and the
# Envoy dataplane. Everything specific to one cloud, the microVM class and the
# other dataplanes stays behind. The digests are resolved here, at vendor time,
# so the operator never calls a registry at run time and a given operator
# version always runs the same bytes. Needs curl, tar and docker buildx.
set -euo pipefail

version="${1:?usage: vendor-substrate.sh <version> <output dir>}"
out="${2:?usage: vendor-substrate.sh <version> <output dir>}"
[[ "$version" =~ ^v[0-9]+\.[0-9]+\.[0-9]+$ ]] || { echo "not a release version: $version" >&2; exit 2; }

repository="ghcr.io/agent-substrate/substrate"
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

curl -fsSL "https://github.com/agent-substrate/substrate/archive/refs/tags/${version}.tar.gz" | tar -xz -C "$work"
src="$work/substrate-${version#v}"
install="$src/manifests/ate-install"

rm -rf "$out"
mkdir -p "$out/generated"
cp "$install/ate-system-namespace.yaml" \
  "$install/sandboxconfig-validation.yaml" \
  "$install/sandboxconfig-gvisor.yaml" \
  "$install/pod-certificate-controller.yaml" \
  "$install/ate-api-server.yaml" \
  "$install/ate-idp-server.yaml" \
  "$install/ate-controller.yaml" \
  "$install/atelet.yaml" \
  "$install/atenet-router.yaml" \
  "$install/atenet-egress.yaml" \
  "$install/ate-system-networkpolicies.yaml" \
  "$out/"
cp "$install/postgres/postgres.yaml" "$out/postgres.yaml"
cp "$install"/generated/*.yaml "$out/generated/"
cp "$src/pkg/postgressetup/setup.sql" "$out/postgres-setup.sql"

# The images a release publishes that this shape runs: the ko-built
# components the files name as ko://go.ate.dev/substrate/cmd/<name>, the Envoy
# dataplane they name as ${ENVOY_DATAPLANE_IMAGE}, and the gVisor worker a
# WorkerPool names.
images=(ate-idp-server ateapi atecontroller atelet atenet objectstore-plugin podcertcontroller envoy-dataplane ateworker-gvisor)
{
  echo "# Generated by make vendor-substrate; do not edit. Each image Agent Substrate"
  echo "# ${version} runs in the operator's install, by its multi-arch index digest."
  echo "version: ${version}"
  echo "images:"
  for name in "${images[@]}"; do
    ref="${repository}/${name}:${version}"
    # An index's digest is the SHA-256 of its raw bytes.
    sum="$(docker buildx imagetools inspect --raw "$ref" | { sha256sum 2>/dev/null || shasum -a 256; } | cut -d' ' -f1)"
    [[ "$sum" =~ ^[0-9a-f]{64}$ ]] || { echo "no digest for $ref" >&2; exit 1; }
    echo "  ${name}: ${ref}@sha256:${sum}"
  done
} >"$out/images.yaml"
