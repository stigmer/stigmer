// ---------------------------------------------------------------------------
// Runtime configuration loader
//
// All configuration uses NEXT_PUBLIC_* environment variables as the single
// canonical set of names. Two producers write /config.json with the same
// field names: the cloud container's Docker entrypoint (from these
// variables, at startup) and the self-hosted stigmer-server's console lane
// (from the server's own configuration, per request). The web app fetches
// the file on initialization to obtain deployment-specific settings.
//
// During local development (`next dev`), /config.json does not exist —
// `.env` files are the documented mechanism (see .env.example) — so the
// loader skips the fetch entirely and reads the same NEXT_PUBLIC_*
// variables directly. This keeps a recurring 404 out of dev logs.
//
// An EMPTY `apiUrl` or `appUrl` in /config.json means "the browser's own
// origin": the server that serves the console also serves its API on the
// same port, and the file cannot know the scheme and host the browser
// reached it by (a TLS proxy in front, a LAN address, a self-host name).
// Resolved once here, so every reader holds a full URL.
//
// Usage:
//   await loadRuntimeConfig();    // call once during app initialization
//   const cfg = getRuntimeConfig(); // synchronous access after loading
// ---------------------------------------------------------------------------

import type { AuthMode } from "@/auth/types";

/**
 * Deployment-agnostic application configuration.
 *
 * All fields have sensible defaults for local OSS development. Container
 * deployments override them via /config.json generated by entrypoint.sh.
 */
export interface RuntimeConfig {
  /**
   * Backend API base URL (gRPC-Web endpoint), always a full URL here: an
   * empty value in /config.json is resolved to the browser's own origin
   * at load time (the server that serves the console serves its API on
   * the same port).
   */
  readonly apiUrl: string;

  /**
   * Public web app URL used when generating externally shareable links
   * (e.g. the hosted agent chat page). Empty means "use the browser's
   * own origin" — correct whenever the app is served at its public URL.
   * Set it when share links must point somewhere other than where the
   * console is rendered (e.g. a dedicated chat domain).
   */
  readonly appUrl: string;

  /**
   * Authentication strategy: `"disabled"` when the server trusts every
   * request (the single-user laptop), `"oidc"` when it requires a bearer
   * from the configured issuer (Stigmer Cloud, or a self-host with
   * `STIGMER_OIDC_ISSUER` set).
   */
  readonly authMode: AuthMode;

  /** OIDC issuer URL. Required when `authMode` is `"oidc"`. */
  readonly oidcIssuer: string;

  /**
   * OAuth 2.0 public client ID for the console's PKCE flow. Required when
   * `authMode` is `"oidc"`: a self-hosted server publishes it from
   * `STIGMER_OIDC_CONSOLE_CLIENT_ID`; a container build from
   * `NEXT_PUBLIC_OIDC_CLIENT_ID`.
   */
  readonly oidcClientId: string;

  /** API audience for access token scoping. Required when `authMode` is `"oidc"`. */
  readonly oidcAudience: string;
}

const DEFAULTS: RuntimeConfig = {
  apiUrl: "http://localhost:7234",
  appUrl: "",
  authMode: "disabled",
  oidcIssuer: "",
  oidcClientId: "",
  oidcAudience: "https://api.stigmer.com/",
};

let _config: RuntimeConfig | null = null;

/**
 * Load runtime configuration. Fetches `/config.json` (container deployment)
 * and falls back to `process.env.NEXT_PUBLIC_*`. In local development the
 * fetch is skipped — env vars are the only supported source.
 *
 * Must be called exactly once before any call to {@link getRuntimeConfig}.
 * Subsequent calls return the cached result without re-fetching.
 */
export async function loadRuntimeConfig(): Promise<RuntimeConfig> {
  if (_config) return _config;

  // Next.js inlines NODE_ENV into client bundles: `next dev` gets
  // "development", `next build` (static export) gets "production". In dev
  // /config.json never exists, so skip the fetch instead of logging a 404
  // on every session.
  const isDev = process.env.NODE_ENV === "development";
  const fromFile = isDev ? null : await fetchConfigJson();
  const merged = fromFile ?? buildFromEnv();

  if (merged.authMode === "oidc") {
    validateOidcFields(merged);
  }

  _config = Object.freeze(merged);
  return _config;
}

/**
 * Synchronous access to the loaded configuration.
 *
 * @throws if called before {@link loadRuntimeConfig} resolves.
 */
export function getRuntimeConfig(): RuntimeConfig {
  if (!_config) {
    throw new Error(
      "getRuntimeConfig() called before loadRuntimeConfig(). " +
        "Ensure <ConfigGate> wraps the component tree.",
    );
  }
  return _config;
}

// ---------------------------------------------------------------------------
// Internal helpers
// ---------------------------------------------------------------------------

async function fetchConfigJson(): Promise<RuntimeConfig | null> {
  try {
    const res = await fetch("/config.json");
    if (!res.ok) return null;

    const json: Record<string, unknown> = await res.json();
    return {
      // Empty means "my own origin" — the server-served console's case; a
      // container's explicit URL passes through verbatim.
      apiUrl: asString(json.apiUrl, window.location.origin),
      appUrl: asString(json.appUrl, DEFAULTS.appUrl),
      authMode: asAuthMode(json.authMode),
      oidcIssuer: asString(json.oidcIssuer, DEFAULTS.oidcIssuer),
      oidcClientId: asString(json.oidcClientId, DEFAULTS.oidcClientId),
      oidcAudience: asString(json.oidcAudience, DEFAULTS.oidcAudience),
    };
  } catch {
    return null;
  }
}

function buildFromEnv(): RuntimeConfig {
  return {
    apiUrl: process.env.NEXT_PUBLIC_API_URL ?? DEFAULTS.apiUrl,
    appUrl: process.env.NEXT_PUBLIC_APP_URL ?? DEFAULTS.appUrl,
    authMode: asAuthMode(process.env.NEXT_PUBLIC_AUTH_MODE),
    oidcIssuer: process.env.NEXT_PUBLIC_OIDC_ISSUER ?? DEFAULTS.oidcIssuer,
    oidcClientId:
      process.env.NEXT_PUBLIC_OIDC_CLIENT_ID ?? DEFAULTS.oidcClientId,
    oidcAudience:
      process.env.NEXT_PUBLIC_OIDC_AUDIENCE ?? DEFAULTS.oidcAudience,
  };
}

function asString(value: unknown, fallback: string): string {
  return typeof value === "string" && value.length > 0 ? value : fallback;
}

function asAuthMode(value: unknown): AuthMode {
  if (value === "oidc") return "oidc";
  return "disabled";
}

/**
 * The one incomplete OIDC configuration a person is likely to meet is a
 * self-hosted server whose operator set the issuer but never registered a
 * client for the console: the server publishes `authMode: "oidc"` with an
 * empty client id on purpose (it must not lie and say `disabled`), and
 * this refusal is where the operator learns what to do. The loader cannot
 * tell a server-synthesized file from a container's, so the copy names
 * both knobs. The Configuration Error screen renders it verbatim.
 */
function validateOidcFields(config: RuntimeConfig): void {
  if (!config.oidcClientId) {
    throw new Error(
      "This server requires sign-in, but no OIDC client is configured for the console. " +
        "Set STIGMER_OIDC_CONSOLE_CLIENT_ID on the server (or NEXT_PUBLIC_OIDC_CLIENT_ID for a container build) " +
        "to the public PKCE client you registered for the console at your identity provider.",
    );
  }

  const missing: string[] = [];
  if (!config.oidcIssuer) missing.push("oidcIssuer (NEXT_PUBLIC_OIDC_ISSUER)");
  if (!config.oidcAudience)
    missing.push("oidcAudience (NEXT_PUBLIC_OIDC_AUDIENCE)");

  if (missing.length > 0) {
    throw new Error(
      `Auth mode is "oidc" but required fields are missing: ${missing.join(", ")}. ` +
        "Check /config.json (container) or NEXT_PUBLIC_* env vars (.env).",
    );
  }
}
