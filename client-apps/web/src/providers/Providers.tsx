"use client";

import { Suspense, useEffect, useState } from "react";
import { usePathname } from "next/navigation";
import { ThemeProvider } from "next-themes";
import { QueryClient, QueryClientProvider } from "@tanstack/react-query";
import { Loader2 } from "lucide-react";
import { isRetryableError } from "@stigmer/sdk";
import { OrgProvider } from "@stigmer/react";
import { AuthProvider, AuthGuard } from "@/auth";
import { StigmerTransportBridge } from "@/providers/StigmerTransportBridge";
import { Toaster } from "@/domain/_shared/ui/sonner";
import { OrgGate } from "@/domain/_shared/org/OrgGate";
import { IdentityAccountGate } from "@/domain/_shared/identity/IdentityAccountGate";
import { loadRuntimeConfig } from "@/config/runtime-config";

/**
 * Routes rendered without the authenticated provider chain.
 *
 * Public routes receive only ConfigGate + ThemeProvider. They do NOT
 * receive AuthProvider, AuthGuard, StigmerTransportBridge, OrgProvider,
 * or OrgGate — those assume an authenticated user and would fail or
 * redirect on pre-authentication pages.
 *
 * Each public page creates its own StigmerProvider (unauthenticated for
 * the initial load, optionally authenticated after an OIDC return).
 */
const PUBLIC_ROUTES = ["/login", "/invite/"] as const;

const queryClient = new QueryClient({
  defaultOptions: {
    queries: {
      staleTime: 30_000,
      retry: (failureCount, error) => {
        if (!isRetryableError(error)) return false;
        return failureCount < 1;
      },
      refetchOnWindowFocus: true,
    },
    mutations: {
      retry: false,
    },
  },
});

/**
 * Application-level provider composition root.
 *
 * Establishes the provider nesting order for authenticated routes:
 * 0. ConfigGate              — loads /config.json before anything else runs
 * 1. ThemeProvider            — manages dark/light/system class on <html>
 * 2. AuthProvider             — resolves auth mode and provides AuthContext
 * 3. AuthGuard                — blocks rendering until auth is resolved
 * 4. QueryClientProvider      — TanStack Query cache and state management
 * 5. StigmerTransportBridge   — bridges console auth to @stigmer/* library transport
 * 6. IdentityAccountGate      — ensures the caller's identity account exists (provisions on first signup)
 * 7. OrgProvider              — fetches organizations and provides OrgContext
 * 8. OrgGate                  — blocks app until user has at least one organization
 * 9. Toaster                  — sonner toast container (themed, top-right)
 *
 * Public routes (e.g. `/login`, `/invite/`) receive only ConfigGate +
 * ThemeProvider. They manage their own SDK client and provider.
 *
 * Query retry strategy:
 * - Only transient errors (server / unavailable) are retried once
 * - Auth, permission, not-found, and validation errors fail immediately
 * - Mutations are never retried (not idempotent by default)
 *
 * This component is rendered once in layout.tsx and wraps the entire app.
 */
export function Providers({ children }: { children: React.ReactNode }) {
  return (
    <ConfigGate>
      <ThemeProvider attribute="class" defaultTheme="system" enableSystem>
        <ProvidersInner>{children}</ProvidersInner>
      </ThemeProvider>
    </ConfigGate>
  );
}

/**
 * Switches between the full authenticated chain and a passthrough for
 * public routes. Separated from {@link Providers} so `usePathname()` is
 * called inside the ConfigGate / ThemeProvider tree.
 */
function ProvidersInner({ children }: { children: React.ReactNode }) {
  const pathname = usePathname();
  const isPublic = PUBLIC_ROUTES.some((r) => pathname.startsWith(r));

  if (isPublic) {
    return <>{children}</>;
  }

  return (
    <AuthProvider>
      <Suspense fallback={<SuspenseFallback />}>
        <AuthGuard>
          <QueryClientProvider client={queryClient}>
            <StigmerTransportBridge>
              <IdentityAccountGate>
                <OrgProvider>
                  <OrgGate>
                    {children}
                    <Toaster />
                  </OrgGate>
                </OrgProvider>
              </IdentityAccountGate>
            </StigmerTransportBridge>
          </QueryClientProvider>
        </AuthGuard>
      </Suspense>
    </AuthProvider>
  );
}

/**
 * Loads runtime configuration before rendering the app.
 *
 * In container deployments, fetches `/config.json` generated by the Docker
 * entrypoint from environment variables. During local development, falls
 * back to `NEXT_PUBLIC_*` env vars baked into the bundle by Next.js.
 *
 * Children are not rendered until configuration is available, ensuring that
 * downstream consumers (auth, transport, etc.) can call `getRuntimeConfig()`
 * synchronously without race conditions.
 */
function ConfigGate({ children }: { children: React.ReactNode }) {
  const [ready, setReady] = useState(false);
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    loadRuntimeConfig()
      .then(() => setReady(true))
      .catch((err: unknown) => {
        const message =
          err instanceof Error ? err.message : "Failed to load configuration";
        setError(message);
      });
  }, []);

  if (error) {
    return (
      <div className="flex min-h-screen flex-col items-center justify-center gap-3 p-8">
        <p className="text-destructive text-sm font-medium">
          Configuration Error
        </p>
        <p className="text-muted-foreground max-w-md text-center text-sm">
          {error}
        </p>
      </div>
    );
  }

  if (!ready) {
    return <SuspenseFallback />;
  }

  return <>{children}</>;
}

function SuspenseFallback() {
  return (
    <div className="flex min-h-screen flex-col items-center justify-center gap-3">
      <Loader2 className="text-muted-foreground size-8 animate-spin" />
    </div>
  );
}
