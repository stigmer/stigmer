package webconsole

import (
	"io/fs"
	"net/http"
	"path"
	"strings"
)

// NewSPAHandler returns an http.Handler that serves the embedded web console
// as a single-page application.
//
// Routing:
//  1. If the request path matches a file in the embedded FS, serve it directly.
//  2. If the path matches a Next.js dynamic route, rewrite it to the
//     pre-rendered __placeholder__ variant (see [spaHandler.resolveDynamicRoute]).
//  3. Otherwise, serve index.html (client-side routing fallback).
//
// Cache control:
//   - Hashed assets (.js, .css with content hashes): immutable, 1-year max-age.
//   - index.html and dynamic-route rewrites: no-cache.
//   - Other files: standard browser caching (no explicit header).
func NewSPAHandler() http.Handler {
	assets := FS()
	if assets == nil {
		return http.NotFoundHandler()
	}

	spa := &spaHandler{fs: assets}

	mux := http.NewServeMux()
	mux.Handle("/", spa)

	return mux
}

type spaHandler struct {
	fs fs.FS
}

func (h *spaHandler) ServeHTTP(w http.ResponseWriter, r *http.Request) {
	reqPath := path.Clean(r.URL.Path)
	if reqPath == "/" {
		h.serveIndex(w, r)
		return
	}
	fsPath := strings.TrimPrefix(reqPath, "/")

	// 1. Direct file/directory lookup.
	f, err := h.fs.Open(fsPath)
	if err == nil {
		f.Close()
		if isHashedAsset(fsPath) {
			w.Header().Set("Cache-Control", "public, max-age=31536000, immutable")
		}
		http.ServeFileFS(w, r, h.fs, fsPath)
		return
	}

	// 2. Static route with .html extension (e.g. /auth/github/callback → auth/github/callback.html).
	if path.Ext(fsPath) == "" && h.isFile(fsPath+".html") {
		w.Header().Set("Cache-Control", "no-cache")
		http.ServeFileFS(w, r, h.fs, fsPath+".html")
		return
	}

	// 3. Dynamic route rewrite (__placeholder__).
	if rewritten, ok := h.resolveDynamicRoute(fsPath); ok {
		w.Header().Set("Cache-Control", "no-cache")
		http.ServeFileFS(w, r, h.fs, rewritten)
		return
	}

	// 4. SPA fallback.
	h.serveIndex(w, r)
}

// resolveDynamicRoute maps a request for a non-existent path to a
// pre-rendered __placeholder__ path generated by Next.js static export.
//
// Next.js uses generateStaticParams with a sentinel __placeholder__ ID to
// produce static assets (HTML pages, RSC .txt payloads) for dynamic route
// segments like /agents/[id]. When the client navigates to a concrete ID
// (e.g., /agents/abc123), the RSC payload request becomes agents/abc123.txt
// which does not exist on disk. This function rewrites such requests to the
// __placeholder__ equivalent (agents/__placeholder__.txt).
//
// Handled request patterns:
//   - agents/abc123.txt           → agents/__placeholder__.txt           (RSC payload)
//   - agents/abc123/__next.*.txt  → agents/__placeholder__/__next.*.txt  (nested RSC segments)
//   - agents/abc123               → agents/__placeholder__.html          (full page load)
func (h *spaHandler) resolveDynamicRoute(fsPath string) (string, bool) {
	segments := strings.Split(fsPath, "/")
	if len(segments) < 2 {
		return "", false
	}

	for i := 1; i < len(segments); i++ {
		seg := segments[i]
		if seg == "__placeholder__" || strings.HasPrefix(seg, "__next.") || strings.HasPrefix(seg, "_next") {
			continue
		}

		trial := make([]string, len(segments))
		copy(trial, segments)
		trial[i] = "__placeholder__" + path.Ext(seg)
		candidate := strings.Join(trial, "/")

		if h.isFile(candidate) {
			return candidate, true
		}

		// Extensionless last segment (full page load): try .html variant.
		if i == len(segments)-1 && path.Ext(seg) == "" {
			if h.isFile(candidate + ".html") {
				return candidate + ".html", true
			}
		}
	}

	return "", false
}

func (h *spaHandler) serveIndex(w http.ResponseWriter, r *http.Request) {
	w.Header().Set("Cache-Control", "no-cache")
	http.ServeFileFS(w, r, h.fs, "index.html")
}

// isFile reports whether name refers to a regular file (not a directory)
// in the embedded filesystem.
func (h *spaHandler) isFile(name string) bool {
	f, err := h.fs.Open(name)
	if err != nil {
		return false
	}
	defer f.Close()
	info, err := f.Stat()
	if err != nil {
		return false
	}
	return !info.IsDir()
}

// isHashedAsset returns true for Next.js build assets that include a content
// hash in the filename and are safe to cache indefinitely.
func isHashedAsset(p string) bool {
	return strings.HasPrefix(p, "_next/static/")
}
