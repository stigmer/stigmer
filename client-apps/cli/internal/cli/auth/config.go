package auth

import "golang.org/x/oauth2"

// Auth0 PKCE configuration for Stigmer Cloud.
//
// These values are public metadata for a Native/PKCE application — they are
// NOT secrets. Auth0 client IDs are public identifiers (like a username, not
// a password) and PKCE eliminates the need for a client secret entirely.
//
// The authorize and token endpoints are hardcoded because Auth0's well-known
// URL structure is stable ({domain}/authorize, {domain}/oauth/token) and
// avoiding OIDC discovery saves a network round-trip at login time.
const (
	Auth0Domain  = "https://stigmer-prod.us.auth0.com"
	ClientID     = "kIT6URf4HKn6YzrQVVFTFN63BrSJdTPM"
	Audience     = "https://api.stigmer.com/"
	CallbackPort = "8088"
	CallbackPath = "/auth/callback"
)

// CallbackURL returns the full OAuth redirect URI for the local callback server.
func CallbackURL() string {
	return "http://localhost:" + CallbackPort + CallbackPath
}

// NewOAuthConfig builds an oauth2.Config for the PKCE authorization code flow.
//
// The returned config has no ClientSecret — PKCE replaces it with a runtime
// code_verifier/code_challenge pair generated by golang.org/x/oauth2.
func NewOAuthConfig() *oauth2.Config {
	return &oauth2.Config{
		ClientID: ClientID,
		Endpoint: oauth2.Endpoint{
			AuthURL:  Auth0Domain + "/authorize",
			TokenURL: Auth0Domain + "/oauth/token",
		},
		RedirectURL: CallbackURL(),
		Scopes:      []string{"openid", "profile", "email", "offline_access"},
	}
}
