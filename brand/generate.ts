/** Generate upload assets and runtime SVG copies from brand/logo.svg; geometry has one owner. */
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import * as path from "node:path";
import sharp from "sharp";
import { brandLockupSvg, brandSvg } from "./assets.mjs";

const root = fileURLToPath(new URL("../", import.meta.url));
async function write(relative: string, data: string | Buffer): Promise<void> {
  const target = path.join(root, relative);
  await mkdir(path.dirname(target), { recursive: true });
  await writeFile(target, data);
}

async function main(): Promise<void> {
  const original = await readFile(
    new URL("./logo.svg", import.meta.url),
    "utf8",
  );
  const paths = [...original.matchAll(/<path d="([^"]+)"\/>/g)].map(
    (match) => match[1],
  );
  if (paths.length !== 1 || /<(?:mask|defs)\b|\bstroke=/.test(original)) {
    throw new Error(
      "The brand source must contain one filled outline with no masks or reinforcing strokes.",
    );
  }
  await write(
    "brand/geometry.ts",
    `/** Generated by npm run generate:brand from logo.svg. Do not edit. */\nexport const MARK_PATHS = ${JSON.stringify(paths, null, 2)} as const;\n`,
  );
  for (const [suffix, color] of [
    ["", "#0a0a0a"],
    ["-white", "#fefefe"],
  ]) {
    const svg = await brandSvg({ color });
    if (suffix) await write(`brand/logo${suffix}.svg`, svg);
    await write(
      `brand/logo${suffix}.png`,
      await sharp(Buffer.from(svg)).png().toBuffer(),
    );
    const lockup = await brandLockupSvg({ color });
    await write(`brand/logo-lockup${suffix}.svg`, lockup);
    await write(
      `brand/logo-lockup${suffix}.png`,
      await sharp(Buffer.from(lockup)).png().toBuffer(),
    );
  }
  await write(
    "site/public/logo-lockup-white.svg",
    await brandLockupSvg({ color: "#fefefe" }),
  );
  await write(
    "brand/avatar.png",
    await sharp(
      Buffer.from(await brandSvg({ color: "#fefefe", background: "#0a0a0a" })),
    )
      .png()
      .toBuffer(),
  );
  await write(
    "site/public/logo-white.svg",
    await brandSvg({ color: "#fefefe" }),
  );
  await write(
    "site/public/favicon.svg",
    await brandSvg({
      size: 32,
      color: "#fefefe",
      background: "#0a0a0a",
      tight: true,
    }),
  );
  for (const theme of ["light", "dark"]) {
    await write(
      `client-apps/web/public/favicon-${theme}.svg`,
      await brandSvg({
        size: 32,
        color: theme === "dark" ? "#fefefe" : "#0a0a0a",
        background: theme === "dark" ? "#0a0a0a" : "#f1f1f1",
        tight: true,
      }),
    );
  }
  console.log("Brand assets generated from brand/logo.svg.");
}
void main().catch((error: unknown) => {
  console.error(error);
  process.exitCode = 1;
});
