/** Generate upload assets and runtime SVG copies from brand/logo.svg and brand/source/shaded.svg. */
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import * as path from "node:path";
import sharp from "sharp";
import {
  BRAND_DARK,
  BRAND_LIGHT,
  SHADED_FACES,
  SHADED_TONES,
  brandLockupSvg,
  brandShadedSvg,
  brandSvg,
} from "./assets.mjs";

const root = fileURLToPath(new URL("../", import.meta.url));
async function write(relative: string, data: string | Buffer): Promise<void> {
  const target = path.join(root, relative);
  await mkdir(path.dirname(target), { recursive: true });
  await writeFile(target, data);
}

async function main(): Promise<void> {
  const original = await readFile(
    new URL("./logo.svg", import.meta.url),
    "utf8",
  );
  const paths = [...original.matchAll(/<path d="([^"]+)"\/>/g)].map(
    (match) => match[1],
  );
  if (paths.length !== 1 || /<(?:mask|defs)\b|\bstroke=/.test(original)) {
    throw new Error(
      "The brand source must contain one filled outline with no masks or reinforcing strokes.",
    );
  }
  const shaded = await readFile(
    new URL("./source/shaded.svg", import.meta.url),
    "utf8",
  );
  const faces = [
    ...shaded.matchAll(/<path data-face="([a-z-]+)" fill="#[0-9a-f]{6}" d="/g),
  ].map((match) => match[1]);
  if (
    faces.join() !== SHADED_FACES.join() ||
    (shaded.match(/<path\b/g) ?? []).length !== faces.length ||
    /<(?:mask|defs)\b|\bstroke=/.test(shaded)
  ) {
    throw new Error(
      `The shaded source must draw the faces ${SHADED_FACES.join(", ")} in that order, each one filled path.`,
    );
  }
  await write(
    "brand/geometry.ts",
    `/** Generated by npm run generate:brand from logo.svg. Do not edit. */\nexport const MARK_PATHS = ${JSON.stringify(paths, null, 2)} as const;\n`,
  );
  const shadedPaths = [
    ...shaded.matchAll(/<path data-face="([a-z-]+)" fill="#[0-9a-f]{6}" d="([^"]+)"/g),
  ].map(
    (match, index) => ({
      d: match[2],
      dark: SHADED_TONES.dark[SHADED_FACES[index]],
      light: SHADED_TONES.light[SHADED_FACES[index]],
    }),
  );
  await write(
    "brand/shaded-geometry.ts",
    `/** Generated by npm run generate:brand from source/shaded.svg. Do not edit. */\nexport const SHADED_PATHS = ${JSON.stringify(shadedPaths, null, 2)} as const;\n`,
  );
  for (const [suffix, color] of [
    ["", BRAND_DARK],
    ["-white", BRAND_LIGHT],
  ]) {
    const svg = await brandSvg({ color });
    if (suffix) await write(`brand/logo${suffix}.svg`, svg);
    await write(
      `brand/logo${suffix}.png`,
      await sharp(Buffer.from(svg)).png().toBuffer(),
    );
    const lockup = await brandLockupSvg({ color });
    await write(`brand/logo-lockup${suffix}.svg`, lockup);
    await write(
      `brand/logo-lockup${suffix}.png`,
      await sharp(Buffer.from(lockup)).png().toBuffer(),
    );
    const flatLockup = await brandLockupSvg({ color, flat: true });
    await write(`brand/logo-lockup-flat${suffix}.svg`, flatLockup);
    await write(
      `brand/logo-lockup-flat${suffix}.png`,
      await sharp(Buffer.from(flatLockup)).png().toBuffer(),
    );
  }
  for (const [suffix, on] of [
    ["", "light"],
    ["-white", "dark"],
  ] as const) {
    const svg = await brandShadedSvg({ on });
    await write(`brand/logo-shaded${suffix}.svg`, svg);
    await write(`site/public/logo-shaded${suffix}.svg`, svg);
    await write(
      `brand/logo-shaded${suffix}.png`,
      await sharp(Buffer.from(svg)).png().toBuffer(),
    );
  }
  await write(
    "site/public/logo-lockup-white.svg",
    await brandLockupSvg({ color: BRAND_LIGHT }),
  );
  await write(
    "brand/avatar.png",
    await sharp(
      Buffer.from(await brandShadedSvg({ on: "dark", background: BRAND_DARK })),
    )
      .png()
      .toBuffer(),
  );
  await write(
    "client-apps/web/public/brand-avatar.png",
    await readFile(path.join(root, "brand/avatar.png")),
  );
  await write(
    "site/public/logo-white.svg",
    await brandSvg({ color: BRAND_LIGHT }),
  );
  await write(
    "site/public/favicon.svg",
    await brandSvg({
      size: 32,
      color: BRAND_LIGHT,
      background: BRAND_DARK,
      tight: true,
    }),
  );
  for (const theme of ["light", "dark"]) {
    await write(
      `client-apps/web/public/favicon-${theme}.svg`,
      await brandSvg({
        size: 32,
        color: theme === "dark" ? BRAND_LIGHT : BRAND_DARK,
        background: theme === "dark" ? BRAND_DARK : BRAND_LIGHT,
        tight: true,
      }),
    );
  }
  console.log(
    "Brand assets generated from brand/logo.svg and brand/source/shaded.svg.",
  );
}
void main().catch((error: unknown) => {
  console.error(error);
  process.exitCode = 1;
});
